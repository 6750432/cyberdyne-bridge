import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_日志 = None
_原件 = {}
_表 = None
空气名 = {"air", "cave_air", "void_air"}


def _说(文):
    if _日志:
        try:
            _日志(文)
            return
        except Exception:
            pass
    print(文, flush=True)


def _载表():
    global _表
    if _表 is not None:
        return _表
    for 路 in (os.path.join(ROOT, "外挂", "常识", "方块交互表.json"),
               os.path.join(ROOT, "常识库", "方块交互表.json")):
        try:
            with open(路, encoding="utf-8") as f:
                _表 = (json.load(f) or {}).get("方块") or {}
            return _表
        except Exception:
            continue
    _表 = {}
    return _表


def 要镐子吗(名):
    """查表。表里没有 → 返回 None（= 不知道，调用方必须交回原方法 ✓）。"""
    条 = _载表().get(str(名))
    if isinstance(条, dict):
        return "镐子" in (条.get("要") or [])
    return None


def 装上(bridge, 日志=None, **kw):
    global _日志
    _日志 = 日志
    if not _载表():
        return {"好": False, "为什么": "方块交互表读不到（外挂/常识/方块交互表.json）",
                "打了": []}
    栈类 = getattr(bridge, "任务栈", None)
    if 栈类 is None:
        return {"好": False, "为什么": "找不到 任务栈 类", "打了": []}
    if getattr(栈类, "_工具查表装了", False):
        return {"好": True, "为什么": "已经装过了（幂等）", "打了": []}
    原 = getattr(栈类, "_看完成了没", None)
    if not callable(原):
        return {"好": False, "为什么": "任务栈._看完成了没 不是函数（锚点没了）", "打了": []}
    _原件[id(栈类)] = 原

    def _看完成了没(self, 步, s, 任=None):
        try:
            动 = (步 or {}).get("动作")
            if 动 == "挖":
                p = (步 or {}).get("p") or [0, 0, 0]
                名 = self._方块名(s, p)
                # ★★★ 2026-10-09：**空气名先判，再查表** ✓
                #   查表的规矩是"表里没有 → 返回 None（= 不知道，必须交回原方法）"✓
                #   可 **`air` / `cave_air` / `void_air` 压根不在方块交互表里**
                #   （那表是 1044 个**方块**的交互数据，空气不算方块）✗
                #   → 于是「挖完了、方块变成空气」这一拍会**交回主链那条硬规则** ✗
                #     → 主链拿 air 去查 `_要镐子("air")` → 又走回老路 ✓
                #   这不是"表没读到"，是**我们查错了问题**：
                #   空气 = 目标已经没了 = **物理事实已经判完了** ✓ 跟"要不要镐子"无关 ✓
                #   （离线用例 C3 就是这么红的 ✗ —— 产品侧不该在空气上问镐子的事 ✓）
                #   ⚠⚠ 2026-10-09 **我自己在这儿捅过一个漏子** ✗ ——
                #     第一版写的是 `if 名 is None or str(名) in 空气名: return True` ✗
                #     **把「雷达没读数」也当成了「挖完了」** ✓
                #     实机后果（当场抓到，任务账本原文）：
                #       13:22:41.778 步骤完成 挖  用了 **0.0 秒**  ← 那根原木还在！
                #       13:23:41.977 步骤失败 拾  等了 60 秒还没成（超时）
                #     ⚠ 而这个坑**主链的注释里早写着**：
                #       「探针没到货（None）**不算挖完** —— 只有明确读到空气才算。
                #         原来把 None 也算进去，结果接单后第一拍就"挖完了"（0.2 秒），
                #         而那一格其实还在（后面 60 秒的"拾"超时就是这么来的）。」
                #     ★ 规矩：**`None` 是"不知道"，不是"没有"** ✗
                #       "不知道"永远不许当成"好消息"（不许 fail-open ✓）
                #       —— 跟主链那 12 处 `or [0,0,0]` 是**同一个病根** ✓
                if str(名) in 空气名:
                    return True, None
                要 = 要镐子吗(名)
                # ★ 只有"表**明确说不要镐子**"时才接管 ✓（None = 不知道 → 不碰 ✓）
                if 要 is False:
                    有镐 = False
                    try:
                        有镐 = bool(self._有工具(s, "pickaxe"))
                    except Exception:
                        有镐 = True          # 查不出来就当"有"，别乱接管 ✗
                    if not 有镐:
                        # 交回**物理事实**：方块还在=没完成；没了=完成 ✓
                        完成 = (名 is None) or (str(名) in 空气名)
                        if 完成:
                            _说(f"[工具查表] 「{名}」不用镐子，已经挖掉了 ✓")
                        return bool(完成), None
        except Exception as e:
            print(f"[工具查表] 接管时出岔子（交回主链）：{e}", flush=True)
        return 原(self, 步, s, 任)

    _看完成了没.__name__ = getattr(原, "__name__", "_看完成了没")
    栈类._看完成了没 = _看完成了没
    栈类._工具查表装了 = True
    _说(f"[工具查表] 挂上了（包类方法，不动顶层对象 ✓）：表里说不用镐子的方块，"
        f"主链那条硬规则判不死它了")
    return {"好": True, "为什么": "", "打了": [
        "任务栈._看完成了没()  ← 接住主链对「草/土/沙/砾/原木」的误判（只在这些方块上接管）"]}


def 卸下(bridge):
    global _日志
    栈类 = getattr(bridge, "任务栈", None)
    原 = _原件.pop(id(栈类), None) if 栈类 is not None else None
    if not 原:
        return {"好": True, "为什么": "本来就没装", "打了": []}
    栈类._看完成了没 = 原
    try:
        del 栈类._工具查表装了
    except AttributeError:
        pass
    _日志 = None
    return {"好": True, "为什么": "", "打了": ["还原 任务栈._看完成了没()"]}
