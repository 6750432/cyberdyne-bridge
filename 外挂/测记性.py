    print("── N 组：重启预热 ──")
    记._挖过.clear()
    记._预热过[0] = False
    变过 = [{"p": [30, 60, 30], "前": "oak_log", "t": 1},
           {"p": [31, 60, 30], "前": "dirt", "t": 2}]
    n1 = 记.预热({"变了": 变过})
