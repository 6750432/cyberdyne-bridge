    #   包装认不出"这一只是新的一只"✗ ⇒ 装上去了却还是老函数 ✓（L5 连红三轮 ✓）
    #   规矩：**替身要干净**（老祖思维第 13 条：存身份别存号码 ✓ 这里是它的近亲 ✓）
    class 假栈挖:
        def __init__(self, 步, 第几=0):
            self.发过的 = []
            self.任务 = {"id": "任务-挖账-1", "名字": "常识：stone_pickaxe", "状态": "跑",
                       "第几步": 第几, "重试": 0, "重试到": 0.0, "下发过": False,
                       "步骤": list(步)}

        def 接(self, 名字, 步骤, s):
            self.接过的 = getattr(self, "接过的", [])
            self.接过的.append((名字, 步骤))
            return True

        def _看完成了没(self, 步, s, 任=None):
            # ★ 这里要**像真主链那样**回 True ✓ —— 它表示"手说这一步成了" ✓
            #   记性那层再**补一道**：背包里真多了掉落物才算完 ✓（M 组测的就是这道 ✓）
            return True, None

        def _下发(self, 步, 任, 现在, s):
            self.发过的.append(步)
            return True

        def 发(self, 东西):
            self.发过的.append(东西)
            return True

    类挖 = type("栈类挖", (), dict(vars(假栈挖)))
