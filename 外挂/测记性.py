    #   2026-10-10 上午补的用例（主人：「补」）。三件事各钉一条：
    #     ① 账本本身记得住、读得回（落盘）；
    #     ② 下发那一刻：挖过 + 现状是空气 ⇒ **跳过**（不挖空气）；
    #     ③ 账本里没有 ⇒ 照常挖（别把正经事拦下）。
    print("── L 组：挖过账（挖矿前先读账本）──")
