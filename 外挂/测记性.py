    试("J2 ★★ `scan.可交互` 那边也认（手侧三处读数都要认 ✓）",
       记._那格是什么(_帧读, [11, 64, 10]) == "birch_log")
    试("J3 ★★★ 那一格**没有读数** → 返回 None ✓（绝不编一个名字 ✗ —— 编了就是骗自己 ✓）",
       记._那格是什么(_帧读, [99, 99, 99]) is None)
    试("J4 ★★ 坐标带小数点也认（状态帧里常是 float ✓ 得先取整 ✓）",
       记._那格是什么(_帧读, [10.7, 64.2, 10.4]) == "oak_log")

