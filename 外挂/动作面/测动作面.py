"""M7b·第 3–4 步 · 动作面补丁的离线断言。

补丁是运行时魔法，光靠"在游戏里看似乎没问题"永远说不清是哪一条生效了。
所以这里用手工造的事实帧（虚拟时钟 + 假的物品/掉落探针）把每条规矩单独拧出来：

  A ★ 开关关着时，补丁**绝对没加载**（子进程 + sys.modules + 类字典三重验）
  B 危险物品拒单（运行时那道闸）
  C 参数不完整拒单（fail-closed）
  D 合成：判据是**开工基准**（不是绝对值 —— 背包里本来就有也不算数）
  E 箱子里取：同上
  F 往箱子里放：基准算法（「把 3 个放进去」不许被错判成「全放光」）
  G 探针扣包合并（不把主链那份 watch_items 顶掉）
  H 卸下之后**完全还原**
  I 两个中文坑在补丁层的防线（精确比较 + 坐标形状）
  J 三条口令（合成 N 个 X / 从箱子 X Y Z 拿 N 个 X / 把 N 个 X 放进箱子 X Y Z）
  K prompt 包壳（整句锚点替换，词表 9+3，宪法那条不进去）
  L ★ 锚点找不到 → 必须拒绝启动（子进程里把组Prompt 换成假货，看它会不会抛）

用法：
    python3 外挂/动作面/测动作面.py [-v]
退出码：0 = 全过；1 = 有失败。
"""

