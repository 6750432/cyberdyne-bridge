通过, 失败 = [], []
详细 = False


def 断言(名, 条件, 实际=None):
    行 = f"{'✅' if 条件 else '❌'} {名}" + (f"　实际：{实际}" if (实际 is not None and not 条件) else "")
    (通过 if 条件 else 失败).append(行)
    if 详细 or not 条件:
        print(行)


def 造帧(我=(0.0, 78.0, 0.0), 血=20.0, 方块=None, 物品=None, 掉落=(),
         卡住=None, 插件=(True, True)):
    """造一帧事实。物品={MC名: 数量}。"""
    块 = [{"p": list(k), "name": v} for k, v in (方块 or {}).items()]
    return {
        "type": "state", "connected": True, "t": _虚拟[0] * 1000,
        "pos": list(我), "hp": float(血), "food": 20, "onGround": True,
        "threats": [], "players": [], "friends": [],
        "weapons": [], "foods": [], "drops": list(掉落),
        "plugins": {"pathfinder": 插件[0], "body": 插件[1]},
        "blocks": 块 or None, "items": 物品, "furnace": None,
        "watched": None, "respawned": False, "acting": "idle", "held": None,
        "near": [], "look": {"yaw": 0.0, "pitch": 0.0}, "msg": None,
        "deaths": 0, "attacked_by": None, "stuck_count": 0, "stuck_ms": 卡住,
    }


def 建栈():
    m4 = dict(CFG["m4"])
    m4["task_enable"] = True
    说 = []
    return bridge.任务栈(m4, lambda *a, **k: 说.append(a), lambda o: None, 日志目录), 说


def 走(栈, 秒=0.2, **帧参):
    """跑一拍，把发出去的命令抓下来。返回 (占不占用, 命令表)。"""
    _虚拟[0] += 秒
    帧 = 造帧(**帧参)
    命令 = []
    栈.发 = 命令.append
    return 栈.跑(帧), 命令


def 发过的(命令):
    return [c for c in 命令 if isinstance(c, dict) and c.get("cmd") in
            ("craft", "chest_take", "chest_put", "watch_items")]


