    走(栈x, 物品={"cobblestone": 3})
    断言("【说明】写了「保留」就是另一种语义：看降到保留数以下（此处未变→未完）",
         栈x.任务["第几步"] == 0, 栈x.任务["第几步"])
    走(栈x, 秒=6, 物品={"cobblestone": 0})
    断言("降到保留数 0 → 完成", 栈x.任务["第几步"] >= 1, 栈x.任务["第几步"])

    # 只写保留、不写数量的写法
    _虚拟[0] += 100
    栈y, _ = 建栈()
    好 = 栈y.接("留 5 个其余全放进去", [{"动作": "往箱子里放", "p": [21, 78, -21],
                                    "物品": "cobblestone", "保留": 5}],
             造帧(物品={"cobblestone": 20}))
    断言("只写「保留」不写「数量」也算合法", 好 is True)
    走(栈y, 物品={"cobblestone": 20})
    断言("还是 20 个 → 未完", 栈y.任务["第几步"] == 0, 栈y.任务["第几步"])
    走(栈y, 秒=6, 物品={"cobblestone": 5})
    断言("降到 5 → 完成", 栈y.任务["第几步"] >= 1, 栈y.任务["第几步"])


