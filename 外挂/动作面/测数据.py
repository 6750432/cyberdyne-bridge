通过, 失败 = [], []
详细 = False


def 断言(名, 条件, 实际=None):
    行 = f"{'✅' if 条件 else '❌'} {名}" + (f"　实际：{实际}" if (实际 is not None and not 条件) else "")
    (通过 if 条件 else 失败).append(行)
    if 详细 or not 条件:
        print(行)


def 跑核对(数, bridge_=None):
    """拿一份数据跑一遍核对，返回 (通过数, 失败数, 失败清单)。"""
    查 = 自检模块.自检器()
    数据模块.核对数据(查, 数, bridge_ or bridge)
    return len([x for x in 查.通过 if isinstance(x, dict)]), len(查.失败), \
        [f"{x['组']} / {x['名']}" for x in 查.失败]


# ══════════════════ A 真数据必须全过 ══════════════════
def 用例_真数据():
    查 = 自检模块.自检器()
    数 = 数据模块.核对(查)
    断言("四份外置数据能加载", 数 is not None)
    断言("真数据核对：一条都不能失败", not 查.失败,
         [x["名"] for x in 查.失败])
    断言("MC 版本跟 config.json 一致",
         数 and 数["版本"] == 数据模块.读配置().get("mc_version"), 数 and 数["版本"])
    return 数


# ══════════════════ B 坑一：火把的「把」 ══════════════════
def 用例_坑一_火把():
    句 = "把 3 个火把 放进箱子 21 78 -21"
    抠 = 中文模块.抠数量词(句)
    断言("抠数量词之后「火把」还是「火把」（没被抠成「火」）", "火把" in 抠, 抠)
    断言("抠数量词确实把「3 个」抠掉了", "3 个" not in 抠 and "3个" not in 抠, 抠)

    # ★ 反例证明：如果按"见把就删"的错写法会怎样
    错写法 = 句.replace("把", " ")          # 这就是那个坑
    断言("【反例】见把就删的错写法确实会把「火把」毁掉（证明这坑是真的）",
         "火把" not in 错写法 and "火" in 错写法, 错写法)

    表 = 数据模块.载入()["物品映射"]
    断言("词表里有「火把」→ torch（否则这句永远解析不出东西）",
         表.get("火把") == "torch", 表.get("火把"))
    断言("「把 3 个火把 放进箱子 21 78 -21」能解析出物品 torch",
         中文模块.取物品名(句, 表, 切点=("放进箱子",), 取前=True) == "torch",
         中文模块.取物品名(句, 表, 切点=("放进箱子",), 取前=True))


# ══════════════════ C 坑二：坐标污染 ══════════════════
def 用例_坑二_坐标():
    句1 = "把 3 个石头 放进箱子 21 78 -21"
    句2 = "从箱子 21 78 -21 拿 3 个 cobblestone"
    断言("「把 3 个石头 放进箱子 21 78 -21」的坐标是 [21,78,-21]",
         中文模块.取坐标串(句1) == [[21.0, 78.0, -21.0]], 中文模块.取坐标串(句1))
    断言("「从箱子 21 78 -21 拿 3 个 …」的坐标也是 [21,78,-21]",
         中文模块.取坐标串(句2) == [[21.0, 78.0, -21.0]], 中文模块.取坐标串(句2))

    # ★ 反例证明：不抠数量词的话会读成什么
    生 = 中文模块.数字式.findall(句1)[:3]
    断言("【反例】不抠数量词就会读成坐标 [3,21,78]（证明这坑是真的）",
         [float(x) for x in 生] == [3.0, 21.0, 78.0], 生)

    断言("数量也能抓对（3 个 → 3）", 中文模块.取数量(句1) == 3, 中文模块.取数量(句1))
    断言("「合成 5 个木板」→ 5", 中文模块.取数量("合成 5 个木板") == 5)
    断言("「x8」这种写法也认", 中文模块.取数量("拿 x8 个木头") == 8,
         中文模块.取数量("拿 x8 个木头"))
    断言("没有数量词时用缺省 1", 中文模块.取数量("把石头放进箱子") == 1)
    断言("没有坐标时返回空表（不瞎猜一个坐标出来）",
         中文模块.取坐标串("合成 3 个火把") == [], 中文模块.取坐标串("合成 3 个火把"))

    表 = 数据模块.载入()["物品映射"]
    for 句, 想要 in (("从箱子 21 78 -21 拿 3 个 圆石", "cobblestone"),
                    ("从箱子 21 78 -21 拿 2 个 火把", "torch"),
                    ("从箱子 21 78 -21 拿 1 个 面包", "bread"),
                    ("从箱子 21 78 -21 拿 3 个 cobblestone", "cobblestone")):
        得 = 中文模块.取物品名(句, 表, 切点=("拿", "取", "要"))
        断言(f"「{句}」→ {想要}", 得 == 想要, 得)
    得 = 中文模块.取物品名("把 5 个 圆石 放进箱子 21 78 -21", 表,
                          切点=("放进箱子",), 取前=True)
    断言("「把 5 个 圆石 放进箱子 …」→ cobblestone", 得 == "cobblestone", 得)
    断言("认不出来的东西返回空串（绝不瞎猜）",
         中文模块.取物品名("把 3 个 你说的那个 放进箱子 21 78 -21", 表,
                          切点=("放进箱子",), 取前=True) == "")


# ══════════════════ D 词表与主链的关系 ══════════════════
def 用例_词表关系():
    数 = 数据模块.载入()
    看家 = set(bridge.任务栈.允许动作)
    禁 = set(bridge.翻译器.禁止步骤)
    断言("prompt 词表 = 主链允许动作 − 宪法禁止步骤",
         set(数["动作词表"]["基础"]) == (看家 - 禁),
         {"词表": 数["动作词表"]["基础"], "该有": sorted(看家 - 禁)})
    断言("宪法禁止的「打」**不在** prompt 词表里",
         not (set(数["动作词表"]["基础"]) & 禁))
    断言("主链允许动作里确实有「打」（对比：主链 10 个 vs prompt 9 个）",
         "打" in 看家 and len(看家) == 10, sorted(看家))
    断言("扩展词表正好三个", set(数["动作词表"]["扩展"]) == {"合成", "箱子里取", "往箱子里放"})


# ══════════════════ E 危险物品 ══════════════════
