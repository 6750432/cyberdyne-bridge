# ══════════════════ F 物品映射 ══════════════════
def 用例_物品映射():
    数 = 数据模块.载入()
    表 = 数["物品映射"]
    基线 = dict(bridge.指令层.物品名)
    断言("基线 21 条一条都没丢", not (set(基线) - set(表)),
         sorted(set(基线) - set(表)))
