"""M7b·第 2 步 · 外置数据的离线断言。

为什么要有这一套：数据一旦离开代码，就会跟代码漂移。漂移**不报错**，
只是静默地"看起来能用"。所以这里把每条关系都钉成断言。

★ 本文件最重要的一组是【G 反向测试】：
    故意喂坏数据进去，看校验会不会**真的报错**。
    主人记进项目宪法的那句话 ——「测试通过 ≠ 测试有意义」——
    就是这一组的由来。一个从来不会失败的校验，等于没有校验。

用法：
    python3 外挂/动作面/测数据.py [-v]
退出码：0 = 全过；1 = 有失败。
"""

