#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""M7b·动作面外挂 —— 中文口语的三个纯函数（第 3/4 步要用，先写好并用坑清单测住）。

为什么现在就写：这三个函数踩过两个**极硬的中文语义坑**，写在报告里不如写成
会失败的测试。它们不碰主链、不依赖任何外挂状态，纯进纯出。

┌───────────────────────────────────────────────────────────────┐
│ 坑一：「火把」的「把」                                         │
└───────────────────────────────────────────────────────────────┘
「把 3 个火把 放进箱子」这句话里有两个「把」：
    · 头一个「把」是量词（把 3 个…）
    · 后一个「把」是**名词的一部分**（火把）
任何「见把就删」的写法都会把「火把」删成「火」，然后查表查不到、解析失败。
→ 所以 抠数量词() 只认「数字 + 量词」成对出现的形态，**绝不单删一个「把」字**。

┌───────────────────────────────────────────────────────────────┐
│ 坑二：「把 3 个石头 放进箱子 21 78 -21」的坐标污染              │
└───────────────────────────────────────────────────────────────┘
坐标是按「三连数字」抓的。句子里那个「3」会跟 21、78 凑成一组，
被读成坐标 (3, 21, 78) —— 小家伙就会往一个荒唐的地方跑。
→ 所以 取坐标串() 内部**先抠数量词再抓坐标**，调用方不用记这件事。
"""

import re

# ★ 量词只认「跟数字成对出现」的形态：
#     「3 个」「3块」「x3」「×3」
#   —— 单独一个「把」字永远不在这个表里。
量词 = "个|块|根|张|支|颗|份|条|把|只|双|对|串"
数量词式 = re.compile(rf"(?:\d+\s*(?:{量词}))|[x×]\s*\d+")

# 抓坐标用的：一个数字（可带负号和小数）
数字式 = re.compile(r"-?\d+(?:\.\d+)?")


def 抠数量词(文):
    """把「3 个」「x3」这类**数量词**从句子里抠掉，其余一个字不动。

    ★ 为什么必须抠：坐标是按三连数字抓的，「把 3 个石头放进箱子 21 78 -21」
      不抠就会被读成坐标 (3,21,78)。
    ★ 为什么不单删「把」：「火把」会变成「火」。
    """
    if not 文:
        return ""
    return 数量词式.sub(" ", str(文))


def 取坐标串(文, 最多=1):
    """从句子里抓坐标，返回 [[x,y,z], …]。

    ★ 内部先抠数量词 —— 这是坑二的根治办法，调用方不用记。
    """
    干 = 抠数量词(文)
    数 = 数字式.findall(干)
    出 = []
    for i in range(0, len(数) - 2, 3):
        出.append([float(数[i]), float(数[i + 1]), float(数[i + 2])])
        if len(出) >= 最多:
            break
    return 出


def 取数量(文, 缺省=1):
    """抓「3 个」里的 3；抓不到就用缺省。"""
    配 = re.search(rf"(\d+)\s*(?:{量词})", str(文 or ""))
    if 配:
        return int(配.group(1))
    配 = re.search(r"[x×]\s*(\d+)", str(文 or ""))
    return int(配.group(1)) if 配 else 缺省


def 取物品名(文, 表, 切点=(), 取前=False):
    """把口语物品名归一成 MC 名（查 表）；查不到返回空串。

    ★ 取前/取后很要紧：
        「把 3 个 cobblestone 放进箱子 …」 → 物品名在切点**前面**
        「从箱子 … 拿 3 个 cobblestone」   → 物品名在切点**后面**
      谁前谁后是主人的说话习惯决定的，不能只顾一头。

    做法：先按切点切一刀，再去掉数量词/数字/句首的「把|将」，
    分词之后**先查表**（精确匹配），再退一步认英文名（带下划线的），
    最后查不到就返回空串 —— **绝不瞎猜**。
    """
    尾 = str(文 or "")
    for q in 切点:
        if q in 尾:
            尾 = 尾.split(q, 1)[0] if 取前 else 尾.split(q, 1)[1]
            break
    尾 = 抠数量词(尾)
    尾 = 数字式.sub(" ", 尾)
    尾 = re.sub(r"^[\s，,、]*(?:把|将)", " ", 尾.strip())
    尾 = re.sub(r"(个|块|根|张|支|颗|份|条|的|了)", " ", 尾)
    词 = [w for w in re.split(r"[\s，,、。！？:：]+", 尾.strip()) if w]
    for w in 词:
        if w in 表:
            return 表[w]
    for w in 词:                                  # 英文物品名（带下划线）直接用
        if re.fullmatch(r"[a-z_]{3,40}", w):
            return w
    return ""


if __name__ == "__main__":
    # 手工试一试（机器验的在 测数据.py）
    for 句 in ["把 3 个火把 放进箱子 21 78 -21",
               "把 3 个石头 放进箱子 21 78 -21",
               "从箱子 21 78 -21 拿 2 个 火把",
               "合成 5 个木板"]:
        print(f"「{句}」")
        print(f"   抠数量词 → 「{抠数量词(句).strip()}」")
        print(f"   坐标     → {取坐标串(句)}")
        print(f"   数量     → {取数量(句)}")
