#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""M7b·动作面外挂 —— 任务栈补丁（第 3 步：第一次真的打补丁）。

┌───────────────────────────────────────────────────────────────┐
│ 这个文件是「魔法」本体，所以规矩写最前面                        │
└───────────────────────────────────────────────────────────────┘
★★ 补丁**只打在内存里**。磁盘上的 bridge.py 一个字节都不动。
   `git diff 基线-M1-M7a -- bridge.py` 永远输出空；指纹永远 2499f81f807431b0…。

★★ **开关关着就一个补丁都不打**：`装上(开关=False)` 立刻返回，连一个属性
   都不碰。开关的唯一出处是 config.json 的 `m7.expand_actions`。

┌───────────────────────────────────────────────────────────────┐
│ 挂上去的七样东西                                               │
└───────────────────────────────────────────────────────────────┘
  ① 任务栈.扩展动作    = {合成, 箱子里取, 往箱子里放}（类属性，装上才有）
  ② 任务栈.危险物品    = 从 prompts/危险物品.txt 读（跟手侧那份必须一致）
  ③ 任务栈.允许动作    = 原来那 10 个 ∪ 扩展的 3 个
        ★ 这一条很关键：主链构造翻译器时写的是
          `允许动作=任务栈.允许动作`，所以只要在构造**之前**把类属性扩好，
          翻译器的 `合法步骤` 就自动跟着扩了 —— 不用再去调翻译器。
          （原来那把「锁」原样存在 `_原["允许动作"]` 里，卸下时还原。）
  ④ 任务栈.接()         ← 危险物品闸 + 参数完整性 + 扩展开关门控
  ⑤ 任务栈._看完成了没() ← 三种新动作的完成判据（**开工先记基准**）
  ⑥ 任务栈._下发()       ← 下发 craft / chest_take / chest_put
  ⑦ 任务栈._挂探针()     ← 把新动作要用的物品名并进 watch_items

┌───────────────────────────────────────────────────────────────┐
│ 两个中文语义坑，在补丁逻辑里怎么被处理                          │
└───────────────────────────────────────────────────────────────┘
  【坑一】「火把」的「把」 —— 这个坑在**指令层口令**那一层（第 4 步），
          补丁这一层只认已经解析好的 MC 物品名（torch），碰不到中文分词。
          但物品名本身要在这儿被校验：`危险物品` 和 `物品映射` 都是**精确
          字符串比较**，绝不做「包含」判断 —— 否则「火把」会跟「把」扯上关系。
  【坑二】坐标污染 —— 同样在口令那一层用 `中文.取坐标串` 解决（第 4 步）。
          补丁这一层拿到的 `步["p"]` 已经是三个数，这里只做一次形状校验：
          **不是三个数就拒单**，绝不猜。

  ★ 换句话说：两个坑的"防"分两层 —— 解析层（中文.py，第 2 步已做完并测住）
    + 执行层（本文件，只接受干净的成品数据，形状不对就 fail-closed）。
"""

import inspect

扩展动作 = frozenset({"合成", "箱子里取", "往箱子里放"})

# 卸下时用来还原（只在装上那一刻填）
_原 = {}
_已装 = False
_主链 = None          # 装上那一刻记下来；新接/新下发要用它的 时刻()


def _时刻():
    """★ 主链的 时刻() 要通过 _主链 动态取。

    第一版我直接在新接() 里写 `时刻()` —— 补丁是**运行时** import 的模块，
    模块级名字空间里根本没有主链的函数，当场 NameError。
    2026-10-01 被 测动作面.py 的 B 组用例抓到。
    """
    return _主链.时刻()


# ══════════════════════════ 小工具 ══════════════════════════

def _三个数(值):
    """坐标必须是三个数 —— 不是就返回 None（**绝不猜**，fail-closed）。"""
    if not isinstance(值, (list, tuple)) or len(值) < 3:
        return None
    try:
        return [float(值[0]), float(值[1]), float(值[2])]
    except (TypeError, ValueError):
        return None


def _是危险物品(名, 危险集):
    """★ 精确比较，不做「包含」判断。

    用 `in` / 子串去判，迟早会把无关的东西卷进来 —— 「火把」跟「把」、
    「石头」跟「圆石」这类中文里一堆包含关系。所以这里只认全等。
    """
    if not 名:
        return False
    return str(名).strip() in 危险集


# ══════════════════════════ 装上 ══════════════════════════

def 装上(bridge, 数=None, 开关=False):
    """把动作面挂到 bridge 上（**只改内存，不改文件**）。

    参数：
        bridge  已经 import 好的主链模块
        数      数据.py 载入() 的结果（要 危险物品 那一份）。不传就自己读。
        开关    config.json 的 m7.expand_actions。**False 就什么都不做。**

    返回 {"好": bool, "为什么": str, "打了": [说明…]}
    """
    global _已装, _主链
    if not 开关:
        return {"好": False, "打了": [],
                "为什么": "开关关着 —— 一个补丁都不打（行为与基线逐字节相同）"}
    if _已装 or getattr(bridge, "_动作面外挂", None):
        return {"好": False, "打了": [], "为什么": "已经打过了，不重复打"}
    主链 = _主链 = bridge
    if not isinstance(数, dict):
        import 数据 as 数据模块
        数 = 数据模块.载入()
    危险集 = frozenset(数["危险物品"])

    栈 = bridge.任务栈
    打的 = []

    # ── ① 先把要挂的原件存好（卸下要用）──
    for 名 in ("接", "_看完成了没", "_下发", "_挂探针"):
        assert callable(getattr(栈, 名, None)), f"主链上没有 任务栈.{名}() —— 拒绝打补丁"
        _原[名] = getattr(栈, 名)
    _原["允许动作"] = 栈.允许动作

    # ── ② 类属性：扩展动作 / 危险物品 / 允许动作 ──
    栈.扩展动作 = 扩展动作
    栈.危险物品 = 危险集
    栈.允许动作 = frozenset(set(栈.允许动作) | set(扩展动作))
    打的.append(f"任务栈.扩展动作 = {'、'.join(sorted(扩展动作))}")
    打的.append(f"任务栈.危险物品 = {len(危险集)} 条（来自 prompts/危险物品.txt）")
    打的.append(f"任务栈.允许动作 {len(_原['允许动作'])} → {len(栈.允许动作)} 个"
                f"（翻译器的合法步骤跟着自动扩）")

    def 扩展开着(self):
        return hasattr(type(self), "扩展动作")
    栈.扩展开着 = 扩展开着

    # ── ③ 接单：危险物品闸 + 参数完整性 + 扩展开关门控 ──
    def 新接(self, 名字, 步骤, s):
        步骤 = list(步骤 or [])
        险的, 缺的 = [], []
        for 步 in 步骤:
            if not isinstance(步, dict):
                continue
            动 = 步.get("动作")
            可能的名字 = [步.get("物品"), 步.get("方块")]
            输 = 步.get("输入")
            if isinstance(输, dict):
                可能的名字.append(输.get("name"))
            for x in 可能的名字:
                if _是危险物品(x, 危险集):
                    险的.append(str(x))
            if 动 == "往箱子里放":
                n = 步.get("数量")
                有数 = isinstance(n, (int, float)) and n >= 1
                if not 有数 and 步.get("保留") is None:
                    缺的.append("往箱子里放：既没给「数量」也没给「保留」")
            if 动 in ("箱子里取", "往箱子里放") and _三个数(步.get("p")) is None:
                缺的.append(f"{动}：坐标不是三个数（{步.get('p')!r}）")
            if 动 == "合成" and not 步.get("物品"):
                缺的.append("合成：没说要合成什么")
        if 险的:
            # ★ 运行时那道闸。手侧插件里还有一道一模一样的（两道独立的闸）。
            self.说(f"[{_时刻()}] 这活里有危险东西（{'、'.join(sorted(set(险的)))}）—— "
                    f"我不碰。", 紧急=True)
            self._记("拒单", 原因="危险物品", 物品=sorted(set(险的)))
            return False
        if 缺的:
            self.说(f"[{_时刻()}] 这个活我没法干：{'；'.join(缺的)}。", 紧急=True)
            self._记("拒单", 原因="参数不全", 说明=缺的)
            return False
        if not 扩展开着(self):
            野 = sorted({str(步.get("动作")) for 步 in 步骤
                        if isinstance(步, dict)} & set(扩展动作))
            if 野:
                self.说(f"[{_时刻()}] 「{'、'.join(野)}」这些本事我还没开 —— 不接。",
                        紧急=True)
                self._记("拒单", 原因="扩展开关没开", 动作=野)
                return False
        return _原["接"](self, 名字, 步骤, s)
    栈.接 = 新接
    打的.append("任务栈.接()  ← 危险物品闸 + 参数完整性 + 开关门控")

    # ── ④ 完成判据：三种新动作（**开工先记基准**）──
    def _取基准(self, 步, s, 键):
        """★ M7b 的核心机关：**开工那一刻先把存货记下来当基准**。

        为什么要这一步：
          「合成 3 个火把」如果判据是"背包里有 3 个火把"，那背包里本来就有 5 个
          的时候，这一步**第一拍就"完成"了**，一个火把都没合成。
          「把 3 个石头放进箱子」同理：「≤ 保留数」会把"放 3 个"错判成"全放光"。
          所以判据一律是**相对开工那一刻的增减量**，不是绝对值。

        返回 (有没有基准, 现在的读数)。
        ★ 只有探针**真的报了这件东西的数**才记基准 ——
          手侧的 watch_items 对盯着的名字一律报数（没有的报 0），
          所以"这个名字不在读数里"就等于"探针还没到货"，这时候记基准会记成 0，
          将来就会误判。宁可多等一拍。
        """
        名 = 步.get("物品")
        计 = (s or {}).get("items") or {}
        有读数 = isinstance(计, dict) and 名 in 计
        现在 = self._物品数量(s, 名)
        if 步.get(键) is None:
            if 有读数:
                步[键] = 现在
                self._记("步骤参数补全", 动作=步.get("动作"), 基准=键, 值=现在)
                return False, 现在        # 刚记完，这一拍不算完成
            return False, 现在            # 探针还没到货 —— 既不算完，也不记基准
        return True, 现在

    def 新看完成了没(self, 步, s, 任=None):
        动 = 步.get("动作")
        if 动 not in 扩展动作:
            return _原["_看完成了没"](self, 步, s, 任)
        数量 = float(步.get("数量") or 1)
        if 动 in ("合成", "箱子里取"):
            # 进项：比开工那一刻**多出**至少 数量 个
            有, 现在 = _取基准(self, 步, s, "_进项前")
            if not 有:
                return False, None
            return 现在 >= float(步["_进项前"]) + 数量, None
        # 往箱子里放（出项）
        if 步.get("保留") is not None:
            # 写死了保留数：直接看"降到保留数以下"
            计 = (s or {}).get("items") or {}
            if 步.get("物品") not in 计:
                return False, None
            return self._物品数量(s, 步.get("物品")) <= float(步["保留"]), None
        有, 现在 = _取基准(self, 步, s, "_放前")
        if not 有:
            return False, None
        return 现在 <= float(步["_放前"]) - 数量, None
    栈._看完成了没 = 新看完成了没
    打的.append("任务栈._看完成了没()  ← 三种判据（一律相对「开工基准」算，不看绝对值）")

    # ── ⑤ 下发：三个新命令（节流规矩跟主链一致）──
    def 新下发(self, 步, 任, 现在, s):
        动 = 步.get("动作")
        if 动 not in 扩展动作:
            return _原["_下发"](self, 步, 任, 现在, s)
        if 现在 < float(任.get("重试到") or 0):        # 退避期间不下发
            return False
        # ★ 三种都是"会重复"的长动作 —— 复刻主链那条规矩：
        #   **重下 = 打断上一次**，太勤的结果是一直在"重新开始"（踩过两次）。
        重下 = self._数("动手重下毫秒", 5000) / 1000.0
        卡住 = isinstance(s.get("stuck_ms"), (int, float)) and s["stuck_ms"] < 1500
        if 现在 - self.上次下发 < 重下 and not 卡住:
            return False
        if 动 == "合成":
            self.发({"cmd": "craft", "item": 步.get("物品"),
                     "count": int(max(1, min(float(步.get("数量") or 1), 64)))})
        elif 动 == "箱子里取":
            self.发({"cmd": "chest_take", "p": _三个数(步.get("p")),
                     "物品": 步.get("物品"),
                     "数量": int(max(1, min(float(步.get("数量") or 1), 64)))})
        else:
            self.发({"cmd": "chest_put", "p": _三个数(步.get("p")),
                     "物品": 步.get("物品"),
                     "数量": int(max(1, min(float(步.get("数量") or 1), 64))),
                     "保留": int(max(0, float(步.get("保留") or 0)))})
        self.上次下发 = 现在
        return True
    栈._下发 = 新下发
    打的.append("任务栈._下发()  ← craft / chest_take / chest_put（含节流与退避）")

    # ── ⑥ 探针：把新动作要用的物品名并进 watch_items ──
    def 新挂探针(self, 步骤, s):
        """★ 主链不认识这三个新动作，不会替我们把物品名挂上探针。

        做法：**把它原来要发的那条 watch_items 扣下来**，再加上我们要的，
        合成一条发出去。
        为什么要"扣下来再合并"，而不是自己重算一份：
          手侧的 watch_items 是**整表覆盖**（`看的物品 = msg.list`），发两次
          等于后一次把前一次顶掉；而自己重算一份就等于把主链的逻辑抄一遍，
          迟早漂移。扣包合并是既不漂移也不冲突的唯一写法。
        """
        扣到的 = []
        原发 = self.发

        def 抓包(o):
            if isinstance(o, dict) and o.get("cmd") == "watch_items":
                扣到的.append(list(o.get("list") or []))
                return                    # 先扣住，不发
            原发(o)

        self.发 = 抓包
        try:
            原挂 = _原["_挂探针"](self, 步骤, s)
        finally:
            self.发 = 原发
        基 = 扣到的[0] if 扣到的 else []
        加 = sorted({str(步.get("物品")) for 步 in (步骤 or [])
                    if isinstance(步, dict) and 步.get("动作") in 扩展动作
                    and 步.get("物品")})
        if 加:
            self.发({"cmd": "watch_items", "list": sorted(set(基) | set(加))[:16]})
        return 原挂
    栈._挂探针 = 新挂探针
    打的.append("任务栈._挂探针()  ← 扣包合并 watch_items（不覆盖主链那份）")

    # ── ⑦ 指令层三条口令（第 4 步）──
    _装指令层(主链, 栈, 数, 打的, 危险集)

    # ── ⑧ 翻译器 prompt 包壳（第 4 步；锚点对不上会抛 锚点错）──
    _装翻译器(主链, 栈, 数, 打的)

    # ── ⑨ 记号 ──
    bridge._动作面外挂 = {
        "装上时刻": __import__("time").time(),
        "扩展动作": sorted(扩展动作),
        "危险物品": sorted(危险集),
        "原允许动作": sorted(_原["允许动作"]),
    }
    已装 = True
    globals()["_已装"] = True
    打的.append("bridge._动作面外挂 记号（自检靠它判「是不是已经打过了」）")
    return {"好": True, "为什么": "挂上去了", "打了": 打的}


# ══════════════════════════ 第 4 步：指令层口令 ══════════════════════════
#
# 三条口语口令。**故意排在主链 ④「去坐标」和 ⑦「合成/放」的前面** ——
# 否则「把 3 个石头放进箱子 21 78 -21」会被单步的「放」抢走，
# 「合成 3 个火把」会被单步的「合成」抢走（而它拿到的物品名是「3 个火把」，认不出来）。
#
# ★ 两个中文坑就是在这儿被处理的：
#     取坐标串() 内部先抠数量词 —— 否则「把 3 个石头放进箱子 21 78 -21」
#     会被读成坐标 (3,21,78)（坑二）。
#     取物品名() 只按**完整词**查表，绝不"见把就删" ——
#     否则「火把」会被删成「火」（坑一）。

取箱词 = ("从箱子", "从箱里", "箱子里拿", "箱子里取", "从仓库")
存箱词 = ("放进箱子", "放进箱里", "存进箱子", "收到箱子里", "放箱子")
合成词 = ("合成", "做一个", "做个", "造一个", "做几个", "造几个")


def _口令(self, 原, 表):
    """三条口令 → 任务书。听不懂就返回 None（交给主链原版的解析）。"""
    import 中文

    def 两三个数(文):
        return 中文.取坐标串(文, 最多=1)

    def 归一(文, 切点, 取前=False):
        return 中文.取物品名(文, 表, 切点=切点, 取前=取前)

    # 「从箱子 21 78 -21 拿 3 个 cobblestone」
    if any(w in 原 for w in 取箱词):
        坐标们 = 两三个数(原)
        名 = 归一(原, ("拿", "取", "要"))
        n = 中文.取数量(原)
        if not 坐标们 or not 名:
            return {"act": "task", "名字": "取东西（缺坐标或缺物品名）", "步骤": []}
        return {"act": "task", "名字": f"去箱子拿 {n} 个 {名}",
                "步骤": [{"动作": "走到", "p": 坐标们[0], "到点": 2.5},
                        {"动作": "箱子里取", "p": 坐标们[0], "物品": 名, "数量": n}]}

    # 「把 3 个 cobblestone 放进箱子 21 78 -21」
    if any(w in 原 for w in 存箱词):
        坐标们 = 两三个数(原)
        名 = 归一(原, 存箱词, 取前=True)
        n = 中文.取数量(原)
        if not 坐标们 or not 名:
            return {"act": "task", "名字": "存东西（缺坐标或缺物品名）", "步骤": []}
        return {"act": "task", "名字": f"把 {n} 个 {名} 放进箱子",
                "步骤": [{"动作": "走到", "p": 坐标们[0], "到点": 2.5},
                        {"动作": "往箱子里放", "p": 坐标们[0], "物品": 名, "数量": n}]}

    # 「合成 3 个火把」—— 没带数字的老写法（「合成 火把」）**故意不接**，
    #   留给主链的单步合成（那是 M3 就有的行为，不许被我们改掉）。
    if any(w in 原 for w in 合成词) and (中文.取数量(原, 缺省=0) > 0):
        n = max(1, min(中文.取数量(原), 64))
        名 = 归一(原, 合成词)
        if not 名:
            return {"act": "task", "名字": "合成（缺物品名）", "步骤": []}
        return {"act": "task", "名字": f"合成 {n} 个 {名}",
                "步骤": [{"动作": "合成", "物品": 名, "数量": n}]}
    return None


def _装指令层(主链, 栈, 数, 打的, 危险集):
    指 = 主链.指令层
    _原["解析"] = 指.解析
    表 = 数["物品映射"]

    def 新解析(self, 说话人, 原文=""):
        原 = str(原文 or "").strip()
        if 原:
            try:
                动作 = _口令(self, 原, 表)
            except Exception as e:
                # ★ 口令解析自己出错 → **当听不懂**，绝不猜一个动作出来
                self.说(f"[{主链.时刻()}] 这句我解析的时候卡了一下（{type(e).__name__}: {e}）"
                        f"—— 我先当没听懂。")
                动作 = None
            if 动作 is not None:
                return 动作
        return _原["解析"](self, 说话人, 原文)

    指.解析 = 新解析
    打的.append("指令层.解析()  ← 三条口令（合成 N 个 X / 从箱子 X Y Z 拿 N 个 X / "
                "把 N 个 X 放进箱子 X Y Z）")


# ══════════════════════════ 第 4 步：组 Prompt 包壳 ══════════════════════════
#
# 主链的 组Prompt 是把字符串拼出来的，里面有两处硬编码：
#   ① 尾巴那行「【任务书的步骤类型】走到(p=[x,y,z]) / 挖(p) / …」
#   ② 心跳那段「★★ 步骤里的「动作」只能用这九个词，…：走到 / 挖 / …」（基线里重复了两行）
#
# 外挂**不动主链那两行**，而是包住 组Prompt：先调原版拿到基线 prompt，
# 再按**整句锚点**把那两行换掉。
# ★ 锚点找不到 → 抛 锚点错 → 拒绝启动（绝不悄悄不生效）。
#
# 做法上用**正则匹配整行**而不是硬编码基线原句 —— 主链哪天微调一个空格，
# 硬编码就会失配，而正则只认「【任务书的步骤类型】」这个前缀（自检 E 组已经钉住了它）。

class 锚点错(Exception):
    """prompt 里的整句锚点找不到了 —— 外挂必须拒绝启动。"""


def _换prompt(文, 数, 要求必须有词表=False):
    import re
    基础 = 数["步骤清单"]["基础"]
    扩展 = 数["步骤清单"]["扩展"]
    词 = list(数["动作词表"]["基础"]) + list(数["动作词表"]["扩展"])

    配1 = re.compile(r"【任务书的步骤类型】[^\n]*")
    如果 = 配1.findall(str(文))
    if not 如果:
        raise 锚点错("prompt 里找不到「【任务书的步骤类型】」那一行")
    新1 = "【任务书的步骤类型】" + 基础 + " / " + 扩展
    文 = 配1.sub(lambda _m: 新1, 文, count=1)

    配2 = re.compile(r"只能用这[^\n]*")
    有几句 = len(配2.findall(str(文)))
    if 有几句:
        新2 = (f"只能用这 {len(词)} 个词，**一个别的字都不许有**："
               + " / ".join(词))
        文 = 配2.sub(lambda _m: 新2, 文)
    elif 要求必须有词表:
        raise 锚点错("prompt 里找不到「只能用这…个词」那一句（心跳用途必须有）")
    return 文, 有几句


def _装翻译器(主链, 栈, 数, 打的, 临时目录=None):
    import tempfile
    译 = 主链.翻译器
    _原["组Prompt"] = 译.组Prompt

    # ── ★ 先做一次"干跑"，验锚点真的在（锚点对不上就拒绝启动）──
    试 = 译({"prompt_limit": 6000}, lambda *a, **k: None,
           临时目录 or tempfile.mkdtemp(prefix="外挂干跑-"),
           任务栈=栈, 三觉=None, 人格="", 允许动作=栈.允许动作, 记忆=None)
    原样 = _原["组Prompt"](试, {}, 用途="心跳", 任务状况="没有任务")
    _换prompt(原样, 数, 要求必须有词表=True)        # 干跑，出错就往上抛

    def 新组Prompt(self, s, 用途="翻译", 任务状况="没有任务", 说话人=None, 原话=None):
        文 = _原["组Prompt"](self, s, 用途=用途, 任务状况=任务状况,
                            说话人=说话人, 原话=原话)
        try:
            新文, _ = _换prompt(文, 数, 要求必须有词表=(用途 == "心跳"))
        except 锚点错:
            # 运行时锚点没了 → 宁可给基线 prompt（少几个词），也绝不崩掉主循环。
            # （启动时的干跑已经把这一条挡在门外了。）
            return 文
        return 新文

    译.组Prompt = 新组Prompt
    打的.append(f"翻译器.组Prompt()  ← 包壳替换两处硬编码句子"
                f"（步骤类型行 + 词表行；词表换成 {len(数['动作词表']['基础'])}"
                f"+{len(数['动作词表']['扩展'])} 个词）")


# ══════════════════════════ 卸下 ══════════════════════════

def 卸下(bridge):
    """把补丁摘干净（测试要用：证明"打上去"和"摘下来"都是可控的）。"""
    global _已装
    if not _已装:
        return False
    栈 = bridge.任务栈
    指 = getattr(bridge, "指令层", None)
    译 = getattr(bridge, "翻译器", None)
    for 名, 原件 in _原.items():
        if 名 == "允许动作":
            栈.允许动作 = 原件
        elif 名 == "解析" and 指 is not None:
            指.解析 = 原件
        elif 名 == "组Prompt" and 译 is not None:
            译.组Prompt = 原件
        else:
            setattr(栈, 名, 原件)
    for 名 in ("扩展动作", "危险物品", "扩展开着"):
        if hasattr(栈, 名):
            delattr(栈, 名)
    _原.clear()
    if hasattr(bridge, "_动作面外挂"):
        del bridge._动作面外挂
    _已装 = False
    return True


def 报个话(bridge):
    """一句话说清现在的状态（给自检和演练用）。"""
    栈 = getattr(bridge, "任务栈", None)
    return {
        "开关装上了": _已装,
        "任务栈有扩展动作": hasattr(栈, "扩展动作") if 栈 else False,
        "任务栈允许动作数": len(getattr(栈, "允许动作", ()) or ()),
        "danger数": len(getattr(栈, "危险物品", ()) or ()),
        "记号": bool(getattr(bridge, "_动作面外挂", None)),
    }
