#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""空間資訊決策點盤點 —— 主人 2026-10-08 清单 P0-2。

一句话：**哪些决策，本该先看一眼空间信息、却压根没看。**

为什么值得单独立一个测试
========================
主人的 T1「資訊有卻不用」是最贵的一类 bug：
    · 跳起来撞天花板，日志上却报「成功了」
    · 对着空气挥镐挥了 60 秒
    · 挖回来 6 个泥土（坐标差一格）
它们的共同点不是"算错了"，是**该看的东西没看**。

所以这张表**做成断言**：每条都钉住「这个决策点到底接没接」。
★ 已知缺口用 `★缺口` 标记 —— 哪天补上了，**这里会变红**，提醒我们把它改成 ✅。

检查分两档（诚实标注）
----------------------
    [行为] 真的调代码跑一遍，看行为对不对
    [源码] 只看源码里有没有那段逻辑（弱一点，但比忘了强）

跑法：python3 外挂/测空间决策.py
"""

import ast
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")
手 = os.path.join(ROOT, "node", "server.js")
身 = os.path.join(ROOT, "node", "plugins", "body", "proto_body.js")
通过, 失败 = [], []
缺口 = []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


def 读(路):
    try:
        return io.open(路, encoding="utf-8").read()
    except Exception:
        return ""


def 任何车厢有(关键字):
    """在任何一个车厢的补丁里找这段逻辑（我一开始把文件写死了，冤枉了两条 ✗）。"""
    import glob
    for p in glob.glob(os.path.join(外挂根, "*", "补丁.py")):
        if 关键字 in 读(p):
            return True
    return False


def 标缺口(名, 理由):
    """★已知缺口：**断言它还没接**。补上了这里会红 —— 那是提醒，不是失败。"""
    缺口.append((名, 理由))
    print(f"   ★缺口  {名} —— {理由}")


def 主():
    手源 = 读(手)
    身源 = 读(身)

    print("=" * 74)
    print("  空間資訊決策點盤點（11 個）")
    print("=" * 74)
    print("  ［行为］= 真跑；［源码］= 只看有没有那段逻辑")
    print()

    # ── ① 挥镐／破坏：得知道目标格是什么方块 ──
    试("① 挥镐／破坏 —— 先查「那格是什么」再决定用不用工具 ［源码］",
       "该用什么工具(块.name)" in 身源 and "我手里没有" in 身源,
       "proto_body.js 里没找到挖掘前置校验")

    # ── ② 跳跃：得知道头顶是不是空的 ──
    试("② 跳跃 —— **跳之前先看头顶那一格** ［源码］"
       "（2026-10-08 接上：头顶堵着就直接拒，并说清楚撞的是什么）",
       "跳起来会撞头" in 身源 and "offset(0, 2, 0)" in 身源,
       "跳跃里没有头顶格检查 —— 顶着天花板按 jump 是白按，日志还报成功")

    # ── ③ 放置：得知道目标格空不空 + 会不会压到自己 ──
    试("③ 放置 —— 目标格得是空的 ［源码］", "那里不是空的" in 身源,
       "放置没查目标格")
    试("③b 放置 —— 而且**不许放自己脚下**（MC 不许，人会把自己埋了） ［源码］",
       "不许挖脚下" in 身源 or "允许挖脚下" in 身源, "没找到脚下保护")
    试("③c 放置 —— 落点由**雷达**说了算（车厢问身边哪格是空的） ［源码］",
       "def 身边空位" in 读(os.path.join(外挂根, "生存常识", "补丁.py")),
       "车厢里没有身边空位()")

    # ── ④ 撿拾走位：得知道掉落物在哪儿 ──
    试("④ 撿拾 —— 手侧要报掉落物的**坐标** ［源码］",
       "drops.push" in 手源 and "pos:" in 手源, "手侧没报掉落物坐标")
    试("④b 撿拾 —— 车厢要**自己绕着掉落物走**（不是站着等） ［源码］"
       "（2026-10-08 接上）", 任何车厢有("def _拾方位"),
       "没有绕圈捡的逻辑")

    # ── ⑤ 尋路：前方／脚下可走性 ──
    寻路 = os.path.join(ROOT, "node", "plugins", "pathfinder")
    试("⑤ 尋路 —— 交给寻路插件（它自己会看可走性，主链只下发目标点） ［源码］",
       os.path.isdir(寻路) or "pathfinder" in 手源, "没找到寻路插件")

    # ── ⑥ 搭桥防掉落：脚下前方是不是空的 ──
    if not any(k in 手源 + 身源 for k in ("搭桥", "防掉落", "不掉下去")):
        标缺口("⑥ 搭桥防掉落", "**一处都没有** —— 它现在不会给自己搭路，走到沟边只能绕")
    else:
        试("⑥ 搭桥防掉落 ［源码］", True)

    # ── ⑦ 避開危險：岩漿／火／仙人掌 ──
    试("⑦ 避開危險 —— 危险方块单子 ［源码］",
       "危险方块" in 手源 and "lava" in 手源 and "cactus" in 手源,
       "没找到危险方块表")

    # ── ⑧ 攻擊：目標實體位置 ──
    试("⑧ 攻擊 —— 找最近的目标实体 + 距离判定 ［源码］",
       "function 找最近" in 身源 and "distanceTo" in 身源, "没找到找最近()")

    # ── ⑨ 開啟容器：箱子／熔爐／工作台座標 ──
    试("⑨ 開啟容器 —— 熔炉靠坐标开、工作台靠 findBlock 找 ［源码］",
       "openFurnace" in 手源 and "crafting_table" in 身源,
       "没找到开容器/找工作台")

    # ── ⑩ 吃東西：手持物品狀態 ──
    试("⑩ 吃東西 —— 有口粮偏好表，吃之前看手上拿的是不是吃的 ［源码］",
       "口粮偏好" in 手源 and "FOOD_RANK" in 手源, "没找到口粮偏好")

    # ── ⑪ 天亮判斷：天空可見度 ──
    试("⑪ 天亮判斷 —— 手侧按 `bot.time.isDay` 报「白天」 ［源码］",
       "bot.time.isDay" in 手源 and "出.白天" in 手源, "没报白天/黑夜")
    试("⑪b 而且车厢真的用它（夜里要不要火把这种判断） ［源码］",
       读(os.path.join(ROOT, "bridge.py")).count("白天") > 0,
       "车厢里没用 scan.白天")

    print()
    print("─" * 74)
    print(f"  已接：**{len(通过)}** 条 ｜ 缺口：**{len(缺口)}** 处")
    if 缺口:
        for n, r in 缺口:
            print(f"    ★ {n}：{r}")
    if 失败:
        print(f"  ❌ 没接上：{len(失败)} 处")
        for f in 失败:
            print(f"    · {f['名']} —— {f['为啥']}")
    print("─" * 74)
    print()
    print("  这张表的意义：**缺口是钉住的**，不会忘；补上了会变红提醒我们改。")
    print("=" * 74)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
