#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""车厢能力 —— **谁知道能干啥，自己报；要用的按名字去要** ✓

主人 2026-10-09 晚上问的原话：
  「我什么东西都写得大差不差了，是不是你在给我重复造轮子啊？
    **他脑子都不思考一下每个车厢能干啥然后自己去调用吗？自动化啊**」

主人说得对 ✓ 而根子不在"某个功能没复用" ✗ —— 在于**系统里没有"谁知道能干啥"这回事** ✗
  于是每次要用一个本事，就得**手接一次** ✓
  手接一次没事 ✓ 手接两次就开始抄 ✓ 手接三次必抄第二遍 ✗
  （今晚我就抄了三遍：竖井 / 读雷达 / 一套阶梯 ✓ 而每一样**主人早就写好了** ✓）

这一份就是那个"册子" ✓ 三条规矩：
  ① **谁有什么本事，自己报** ✓ —— 扫描已经挂上车的车厢模块（`车厢_<名>_入口`）
     ⚠ **不写死名单** ✗（写死名单就是又抄了一遍 ✓）挂谁扫谁 ✓
  ② **要用的按名字去要** ✓ —— `要("安排一趟挖到")` ⇒ 拿得到就用 ✓
  ③ **要不到就出声** ✗ —— 绝不自己临时造一个 ✗（那正是"抄第二遍"的起点 ✓）

★ 这也是 Smalltalk 那一课的下半场 ✓：
  对象知道自己有什么方法 ✓ 外面也问得出来（`--自省` 是上半场 ✓ 这里是下半场 ✓）
"""

import sys

# 哪些模块算"车厢" —— 按**命名约定**扫 ✓ 不写死具体名字 ✗
车厢前缀 = "车厢_"


def _车厢们():
    """→ {车厢名: 模块} ✓ 从 sys.modules 里按约定捞 ✓（挂谁有谁 ✓）"""
    出 = {}
    try:
        for 名, m in list(sys.modules.items()):
            s = str(名)
            if not s.startswith(车厢前缀) or m is None:
                continue
            # 车厢_生存常识_入口 ⇒ 生存常识 ✓
            中间 = s[len(车厢前缀):]
            车厢 = 中间.split("_")[0] or 中间
            出[车厢] = m
    except Exception:
        pass
    return 出


def 清单():
    """→ {能力名: [车厢名…]} ✓ —— 把**所有车厢的所有公开函数**列出来 ✓

    为什么按"函数名"当能力名 ✓：
      车厢的补丁本来就是"把某本事挂到车上" ✓ 它的公开函数**就是**它能干的事 ✓
      不用再让人去写一遍清单 ✗（写清单也是抄第二遍 ✓）
    """
    册 = {}
    for 车厢, m in _车厢们().items():
        for 名 in dir(m):
            if 名.startswith("_"):
                continue
            值 = getattr(m, 名, None)
            # ⚠ 我第一版这里还比了一句 `__module__ == m.__name__` ✗
            #   结果**假车厢（测试用的桩）一律被滤掉** ✓ 真车厢虽然没事 ✓
            #   但这就是个脆判据 ✗（判据要用在它真正管的地方 ✓）
            #   ⇒ 只留一条：**公开 + 可调用** ✓
            if callable(值):
                册.setdefault(名, []).append(车厢)
    return 册


def 谁能(能力):
    """→ [车厢名…] ✓ 谁会这个本事 ✓（空表 = 没人会 ✓）"""
    return list(清单().get(能力) or [])


def 要(能力, 出声=None):
    """→ 那个可调用对象 ✓ ｜ 没有就 None ✓ **而且要出声** ✗

    ★ 规矩：**要不到不许自己造** ✗ —— 自己造就是"抄第二遍"的起点 ✓
      （今晚主人连点我三次，三次都是我"自己造了一个" ✓）
    """
    册 = _车厢们()
    有 = [c for c in 谁能(能力) if callable(getattr(册.get(c), 能力, None))]
    if not 有:
        if 出声:
            出声(f"[车厢能力] ✗ 没有哪节车厢会「{能力}」"
                 f"（挂着的车厢：{'、'.join(sorted(册)) or '一节都没挂'}）"
                 f" —— **不许自己临时造一个** ✓（主人点过：别抄第二遍 ✗）")
        return None
    if len(有) > 1 and 出声:
        # ★ 多个车厢都会同一件事 ⇒ **出声** ✗（要么合并、要么指明用谁 ✓ 别闷着挑一个 ✓）
        出声(f"[车厢能力] ⚠ 「{能力}」有 {len(有)} 节车厢都会：{'、'.join(有)}"
             f" —— 挑「{有[0]}」用 ✓ 但这说明**有重复实现** ✓ 该合并 ✓")
    return getattr(册[有[0]], 能力)


def 印清单():
    """给人看的一页 ✓（主人一句话就能知道车上有什么本事 ✓）"""
    册 = 清单()
    print("═══ 车厢能力册 ✓（谁有什么本事，自己报的 ✓）═══")
    for 能力 in sorted(册):
        谁 = "、".join(册[能力])
        标 = "  ⚠ 有重复" if len(册[能力]) > 1 else ""
        print("  %-24s ← %s%s" % (能力, 谁, 标))
    print("（共 %d 项本事，来自 %d 节车厢 ✓）" % (len(册), len(_车厢们())))
    return 0


if __name__ == "__main__":
    sys.exit(印清单())
