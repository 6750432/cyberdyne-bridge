def 造环境(步骤=None, 第几步=0, 状态="跑"):
    b = 假bridge()
    # ★ 造一个**临时类**（车钩就是往**类**上打补丁的 ✓）
    #   ⚠⚠ 实例必须**由这个类造出来** ✗ —— 我第一版写的是
    #     `栈 = 假任务栈(...)`，可类却是另造的 `栈类` ✓
    #     → **实例的类根本不是被包装的那个类** → 包了也没用 ✗
    #     表现极具迷惑性：`装上` 报告"打了补丁 ✓"、类上确实换成了壳 ✓
    #     可一调 `栈._下发(...)` 走的还是原来那个类的方法 ✗
    #     这一条我查了**四轮**才找出来 ✓ 记下来：**替身的类必须和实例是一家人** ✓
    类 = type("栈类", (), {
        "车钩活着的实例": [],
        **{k: v for k, v in vars(假任务栈).items() if k.startswith("_")},
    })
    栈 = 类(步骤, 第几步, 状态)
    类.车钩活着的实例 = [栈]
    叙类 = type("叙类", (假叙事者,), {})       # 每套环境一个新鲜的叙事者类 ✓
    b.任务栈 = 类
    b.叙事者 = 叙类
    return b, 栈


def 回执(cmd="place", 够不着=True, 距=5.2, **额外):
    e = {"cmd": cmd, "ok": False, "why": f"那地方在 {距} 格外，够不着（手最多伸 4.5 格）",
         "取消": "够不着"}
