通过, 失败 = [], []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


def 喂台阶(帧, 层=3, dx=1, dz=0, 名="dirt"):
    """★★★ 甲（2026-10-09 主人「甲乙丙一起」）：下钻之前先看清**落脚的台阶格** ✓

    真机上这几格是「挖空守卫」盯上、雷达报回来的 ✓ —— 用例里得照实喂 ✓
    （不喂 → 向下盲挖会**先请雷达**再下钻 ✓ 那是新行为，不是旧用例要测的东西 ✓）
    """
    位 = 帧.get("pos") or [0, 0, 0]
    x0, y0, z0 = int(位[0]), int(位[1]), int(位[2])
    for i in range(1, 层 + 1):
        帧.setdefault("blocks", []).append(
            {"p": [x0 + dx * i, y0 - i, z0 + dz * i], "name": 名})
    return 帧


def 造帧(pos=(-34.0, 50.0, -21.0), 地面="dirt", 石头=None, 可交互=None):
    """照手侧 扫环境() 的真实形状造一帧。`石头` 就是 scan.石头 那份暴露情报。"""
    return {
        "pos": list(pos),
        "inv": [],
        "items": {},
        # ★ 身边那 4 格必须给：车厢要靠它知道"哪格是空的"（好在旁边放工作台）。
        #   不给的话它会**拒绝规划**（fail-closed）—— 我第一次写漏了，
        #   D2 就挂在「雷达还没盯我身边那 4 格」上 ✗
        "blocks": [{"p": [-33, 50, -21], "name": "air"},
                   {"p": [-35, 50, -21], "name": "stone"},
                   {"p": [-34, 50, -20], "name": "stone"},
                   {"p": [-34, 50, -22], "name": "stone"}],
        "scan": {
            "t": int(time.time() * 1000),
            "地面": 地面,
            "方块": [{"name": "dirt", "count": 40}],
            # ★ 也得给一份木头：石镐的链子是「撸树 → 木板 → 木棍 → 工作台 → 挖石头」，
            #   木头定位不到的话，整条计划会先在"出去找树"那一步停住 ✗
            #   （第二次踩：第一次是漏了 blocks，这次是漏了 可交互。）
            # ★★★ 2026-10-09 第三次踩：**只报一根原木也不够** ✗
            #   石镐那条计划要挖 **3 根**原木 ✓，而 `落坐标` 现在守新规矩 ——
            #   "坐标只能来自证据，不能来自算术" ✓ 挑不到第二处就如实报缺 ✓
            #   手侧真实长这样：一根树干会**一连几格**都报回来 ✓（实机视觉原话：
            #   oak_log(-116,80,152) / (-116,81,152) / (-116,82,152) ✓）
            #   所以帧也得按实机报一串 ✓ —— 不是放宽断言，是把假帧改成真的 ✓
            "可交互": 可交互 if 可交互 is not None else [
                {"name": "oak_log", "p": [-30, 50, -21]},
                {"name": "oak_log", "p": [-30, 51, -21]},
                {"name": "oak_log", "p": [-30, 52, -21]},
            ],
            "危险": [],
            "石头": 石头,
        },
    }


# ── 三种情报：埋住的 / 露着但被挡的 / 露着且看得见 ──
埋住的 = {"name": "stone", "p": [10, 70, 10], "裸露": False,
         "视线": None, "挡": [{"name": "dirt", "p": [10, 71, 10], "相对": [0, 1, 0]}]}
被挡的 = {"name": "stone", "p": [10, 70, 10], "裸露": True, "视线": False,
         "挡前": {"name": "dirt", "p": [9, 70, 10]},
         "挡": [{"name": "dirt", "p": [9, 70, 10], "相对": [-1, 0, 0]}]}
看得见 = {"name": "stone", "p": [10, 70, 10], "裸露": True, "视线": True,
         "挡": [], "挡前": None}


def 主():
    sys.path.insert(0, 外挂根)
    sys.path.insert(0, ROOT)
    import 车钩
    import bridge

    def 载(名):
        p = os.path.join(外挂根, 名, "补丁.py")
        spec = importlib.util.spec_from_file_location(f"测_{名}", p)
        m = importlib.util.module_from_spec(spec)
        sys.modules[f"测_{名}"] = m
        sys.path.insert(0, os.path.join(外挂根, 名))
        spec.loader.exec_module(m)
        return m

    常 = 载("生存常识")

    # ══════════ A 组：反矿透 —— 埋住的不许进求解器的视野 ══════════
    print("── A 组：反矿透（埋住的看不见）──")
    试("A1 ★★★ 整个被埋住的石头：**不进扫描表**（求解器看不见它，就不会瞄它）",
       "stone" not in 常.扫描表(喂台阶(造帧(石头=埋住的))), str(常.扫描表(造帧(石头=埋住的))))
    试("A2 ★★★ 露在外面的石头：正常进表",
       (常.扫描表(造帧(石头=看得见)) or {}).get("stone") == [10, 70, 10],
       str(常.扫描表(造帧(石头=看得见))))
    试("A3 ★★ 露着但**我这条视线被挡**：照样进表 —— 挡着的部分靠前置任务解决，不是靠不喂",
       (常.扫描表(造帧(石头=被挡的)) or {}).get("stone") == [10, 70, 10],
       str(常.扫描表(造帧(石头=被挡的))))
    试("A4 ★★ 情报缺失（老版本的手）→ **照旧放行**（这条是故意 fail-open 的：宁可多挖一次，不能因为拿不到情报就不干活）",
       (常.扫描表(造帧(石头={"name": "stone", "p": [10, 70, 10]})) or {}).get("stone")
       == [10, 70, 10])

    # ══════════ B 组：口径一致 —— 同一份情报只有一处实现 ══════════
    print("── B 组：口径一致 ──")
    帧 = 造帧(石头=被挡的)
    试("B1 坐标对上 → 给出情报",
       isinstance(常._遮挡情报(帧, [10, 70, 10]), dict))
    试("B2 坐标对不上 → 给 None（**不许张冠李戴**：情报只覆盖「最近的石头」那一块）",
       常._遮挡情报(帧, [99, 70, 99]) is None)
    试("B3 没有 scan.石头 → None",
       常._遮挡情报(造帧(), [10, 70, 10]) is None)
    # ★★★ 2026-10-08 晚 实机抓到的那条：**目标不是石头**（tree 上的 oak_log）。
    #   手侧会现算任何方块的遮挡 ✓，可车厢原来只从 `scan.石头` 取 → 拿不到 ✗
    #   → 「先挖掉挡着的」插不进去 → 每秒重试同一镐。这条断言就是钉这个的。
    帧树 = 造帧(可交互=[{"name": "oak_log", "p": [7, 70, 7], "裸露": True,
                       "视线": False, "挡前": {"name": "oak_leaves", "p": [7, 71, 7]}}])
    _情 = 常._遮挡情报(帧树, [7, 70, 7])
    试("B4 ★★★ **目标不是石头时也能拿到遮挡情报**（情报来自 scan.可交互，不是只有 scan.石头）",
       isinstance(_情, dict) and (_情.get("挡前") or {}).get("name") == "oak_leaves",
       repr(_情))
    试("B5 坐标对不上时，可交互那份也不许张冠李戴",
       常._遮挡情报(帧树, [8, 70, 7]) is None)

    # ══════════ C 组：向下盲挖原语（地质学常识）══════════
    print("── C 组：向下盲挖原语 ──")
    步, 说 = 常.安排一趟向下盲挖(喂台阶(造帧()), 层=3)
    试("C1 ★★ 出得来步骤", isinstance(步, list) and len(步) >= 3, str(步)[:120])
    if 步:
        试("C2 ★★★ 是**阶梯式**下挖：每层都往下挪一格（不是直上直下把自己埋进竖井）",
           [s["p"][1] for s in 步 if s.get("动作") == "走到"]
           == [49, 48, 47],
           str([s.get("p") for s in 步 if s.get("动作") == "走到"]))
        试("C3 ★★ 有界：3 层就是 9 步，不会无限下钻",
           len(步) == 9, f"{len(步)} 步")
        试("C4 ★★★ **不瞄任何具体方块**（挖到什么算什么）—— 步骤里不该出现「方块」这个键",
           all("方块" not in s for s in 步), json.dumps(步, ensure_ascii=False)[:160])
        试("C5 每一步的动作都是任务栈认的",
           all(s.get("动作") in bridge.任务栈.允许动作 for s in 步),
           str(sorted({s.get("动作") for s in 步} - set(bridge.任务栈.允许动作))))
    试("C6 看不清坐标时**拒绝**出计划（fail-closed），不是瞎挖",
       常.安排一趟向下盲挖({"pos": None})[0] is None)

    # ══════════ D 组：端到端 —— 主线挂上真编组，看它到底排出什么步骤 ══════════
    print("── D 组：端到端（意图 → 步骤表）──")
    列 = 车钩.列车(bridge)
    列.车厢表 = 车钩.发现车厢()
    车钩.编组文件 = os.path.join(tempfile.gettempdir(), "测视线遮挡-编组.json")
    列.换轨(["动作面", "生存常识"], 理由="测试")
    试("D1 车厢挂上了", 列.编组 == ["动作面", "生存常识"], str(列.编组))
    译 = bridge.翻译器({"prompt_limit": 6000}, lambda *a, **k: None,
                     tempfile.gettempdir(), 任务栈=None, 三觉=None, 人格="",
                     允许动作=bridge.任务栈.允许动作, 记忆=None)

    # ① 露着、但视线被泥土挡着 —— **实机那一幕**
    _, 任, 因 = 译.收输出('{"意图":"要","目标":"stone_pickaxe"}', 造帧(石头=被挡的), 用途="心跳")
    试("D2 ★★ 排得出步骤表", 任 is not None, f"原因={因}")
    if 任:
        步表 = 任["步骤"]
        挖位 = [(i, s.get("p")) for i, s in enumerate(步表) if s.get("动作") == "挖"]
        # ① 那条挡着的泥土，必须**排在石头前面**
        前 = [(i, p) for i, p in 挖位 if p == [9, 70, 10]]
        后 = [(i, p) for i, p in 挖位 if p == [10, 70, 10]]
        试("D3 ★★★ 挡着的泥土**排在石头前面**（这就是「前置任务插入」）",
           bool(前) and bool(后) and 前[0][0] < 后[0][0],
           json.dumps(挖位, ensure_ascii=False))
        试("D4 ★★★ 挖泥土那一步**指名**挖的是 dirt（不指名就会挖错东西还算完成）",
           any(s.get("动作") == "挖" and s.get("p") == [9, 70, 10]
               and s.get("方块") == "dirt" for s in 步表),
           json.dumps([s for s in 步表 if s.get("动作") == "挖"], ensure_ascii=False)[:200])

    # ② 整个被埋住 —— 反矿透：不许瞄，改走【向下盲挖】
    _, 任2, 因2 = 译.收输出('{"意图":"要","目标":"stone_pickaxe"}', 造帧(石头=埋住的), 用途="心跳")
    试("D5 ★★★ 埋住的石头**绝不会**出现在任何一步的坐标里（反矿透）",
       任2 is None or all(s.get("p") != [10, 70, 10] for s in 任2["步骤"]),
       json.dumps([s.get("p") for s in (任2 or {}).get("步骤", [])], ensure_ascii=False)[:200])
    if 任2:
        动 = [s.get("动作") for s in 任2["步骤"]]
        # ★★★ 2026-10-09 更新（主人「甲乙丙一起」→ 甲）：
        #   从前这里只认「立刻向下盲挖」✗ —— 可甲现在要求**下钻之前先看清落脚的格子** ✓
        #   看不清就**先去请雷达 / 换个地方** ✓（不做没凭据的深钻 ✗ 这是主人点名的 ✓）
        #   所以正解变成两条之一 ✓：
        #     ① 读数齐 → 照旧「向下盲挖」（往下挖、往下走 ✓）
        #     ② 读数不齐 → 「先请雷达 / 出去找」这些**真能执行的步子** ✓
        #        （反正**不许**是空计划 ✗ 也不许去瞄那块埋住的石头 ✗ —— D5 守着那条 ✓）
        往下 = ("挖" in 动 and any(s.get("p") and s["p"][1] < 50 for s in 任2["步骤"]
                                 if s.get("动作") == "走到"))
        先看清 = bool(任2["步骤"]) and any(s.get("动作") in ("走到", "挖")
                                       for s in 任2["步骤"])
        试("D6 ★★★ 找不到裸露的石头 → **给得出能执行的下一步** ✓"
           "（读数齐就下钻 ✓ 不齐就先请雷达/出去找 ✓ —— 甲那条规矩 ✓ 不许空计划 ✗）",
           往下 or 先看清,
           json.dumps(任2["步骤"][:6], ensure_ascii=False)[:220])

    # ③ 看得见的石头 —— 不许被新逻辑误伤
    _, 任3, 因3 = 译.收输出('{"意图":"要","目标":"stone_pickaxe"}', 造帧(石头=看得见), 用途="心跳")
    if 任3:
        挖位3 = [s.get("p") for s in 任3["步骤"] if s.get("动作") == "挖"]
        试("D7 ★★ 看得见的石头照常挖（新逻辑不许误伤正常路径）",
           [10, 70, 10] in 挖位3, json.dumps(挖位3, ensure_ascii=False)[:160])

    # ══════════ 汇总 ══════════
    print("\n" + "═" * 62)
    print(f"视线遮挡车厢：{len(通过)} 过 / {len(失败)} 失败")
    for f in 失败:
        print(f"  ❌ {f['名']} —— {f['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
