#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""任务书体检·车厢本体 —— 模型交上来的任务书，字段不对就整份退回去。

┌───────────────────────────────────────────────────────────────────┐
│ 它治的是什么病（2026-10-07 实机抓到的真 bug）                     │
└───────────────────────────────────────────────────────────────────┘
实机当天，小家伙**一次都没走出去过**。手侧日志一直在喊：

    走不过去：p 得是三个数

任务快照（任务栈自己存的）里写着：

    {"动作": "走到", "目标": "copper_ore(-38,50,-23)"}

模型把坐标写进了「目标」，而主链 `_下发()` 读的是 `步["p"]`。
于是发出去的是 `{"act":"goto","p":[]}` —— 手当场拒收，重试 3 次 × 60 秒，
然后任务失败；下个心跳模型再写一遍，**永远循环**。

★ 但真正的窟窿在校验器：`翻译器._校验任务()` 只在 `p` **是列表且长度≥3**
  的时候才去查坐标。`p` 整个缺失 / 类型不对 —— **它一个字都不查**。

  这正是本项目最恨的失败方式：不报错、不崩溃、日志一片祥和，
  主人以为它去挖矿了，其实它在地上站了一下午。

┌───────────────────────────────────────────────────────────────────┐
│ 挂在哪儿，为什么挂那儿                                           │
└───────────────────────────────────────────────────────────────────┘
挂在 `翻译器._校验任务()` 上 —— **那是模型输出进来的那道门**。

不挂在 `任务栈.接()` 上的理由：接() 只回一个 bool，拒单原因就丢了；
而 `_校验任务()` 回的是 `(好, 原因, 干净)`，原因能顺着
`收输出()` → 心跳 → 一路传出去（「拒单反馈」车厢就是接这个原因的）。
**能说清为什么拒，比拒本身更重要。**

★ 顺序：主链自己的检查**先跑**，它拒了就原样返回它的理由。
  本车厢只在主链**放过**了的情况下补刀。（免得把「不许有『打』」
  这种宪法级提示，盖成一句干巴巴的「缺 p」。）

┌───────────────────────────────────────────────────────────────────┐
│ 规矩：缺了就是拒，**绝不猜、绝不自动补**                          │
└───────────────────────────────────────────────────────────────────┘
主人 2026-10-07 定的：「缺坐标时直接拒掉」。

所以这里**不会**去 `"copper_ore(-38,50,-23)"` 里抠数字。为什么：
    · 有些方块名里本身就带逗号和数字，抠出来的可能是别人家的坐标
    · 「猜」一旦开了头，下次「大概是这个意思吧」就挡不住了
    · 拒掉之后模型自己会改（原因会喂回去，见「拒单反馈」车厢）

两道闸：
    ① **不认识的字段** → 拒。这一条就抓住了「目标」那个 bug。
    ② **必填字段缺失 / 坐标形状不对** → 拒。
"""

import os
import sys

_原 = {}
_已装 = False
_主链 = None
_记 = None
统计 = {"体检过": 0, "退回": 0, "退回原因归类": {}}


# ══════════════════════════ 字段表 ══════════════════════════
# ★ 下面这份「认识字段」是**从主链代码里 grep 出来的**，不是拍脑袋写的。
#   出处命令：
#     grep -oE '步\.get\("[^"]+"|步\["[^"]+"\]' bridge.py | sort -u
#     grep -oE '步\.get\("[^"]+"' 外挂/动作面/补丁.py | sort -u
#   主链哪天读了新字段，这张表就得跟着加 —— 加漏了会**误退**合法任务书，
#   这是本车厢唯一需要维护的地方。
认识字段 = frozenset({
    "动作", "action",                       # 动作名本身（主链两个都认）
    "p",                                    # 坐标 [x,y,z]，或占位符 "起点"
    "到点", "超时_ms", "等待超时_ms",          # 到点半径 / 各步超时
    "物品", "数量", "方块", "名", "方式",       # 名词类参数
    "输入", "燃料",                          # 熔炉
    "熔炉", "条件",                          # wait_until
    "跳过", "距离", "谁", "血量",             # 猎手/躲人的那些
    "看方块", "第几块", "共几块",             # 分块挖
    "ms", "文本", "保留",                     # 等 / 说 / 往箱子里放
})

# 每个动作**必须有**的字段。没列的 = 不强求。
必填 = {
    "走到": ("p",),
    "挖": ("p",),
    "放": ("p",),
    "说": ("文本",),
    "熔炉放料": ("p", "输入", "燃料"),
    "熔炉取成品": ("p",),
    "合成": ("物品",),
    "箱子里取": ("p", "物品"),
    "往箱子里放": ("p", "物品"),
}

# 给模型看的**正确写法**。退回原因里会带上它 —— 光说"你错了"没用，
# 得让它知道对的长什么样。
写法 = {
    "走到": "走到(p=[x,y,z], 到点=2.5)",
    "挖": "挖(p=[x,y,z])",
    "放": "放(p=[x,y,z], 方块=方块名)",
    "说": "说(文本=你要说的话)",
    "拾": "拾(物品=物品名, 数量=1)",
    "熔炉放料": "熔炉放料(p=[x,y,z], 输入=物品名, 燃料=物品名)",
    "熔炉取成品": "熔炉取成品(p=[x,y,z], 物品=物品名, 数量=1)",
    "合成": "合成(物品=物品名, 数量=1)",
    "箱子里取": "箱子里取(p=[x,y,z], 物品=物品名, 数量=1)",
    "往箱子里放": "往箱子里放(p=[x,y,z], 物品=物品名, 数量=1)",
    "等": "等(ms=2000)",
    "wait_until": "wait_until(条件=…, 等待超时_ms=30000)",
}


def _说(文本):
    if _记:
        _记(文本, 屏幕=False)


def _归类(原因):
    """把退回原因归个类，好统计 —— 只看前几个字。"""
    键 = (原因 or "?")[:12]
    统计["退回原因归类"][键] = 统计["退回原因归类"].get(键, 0) + 1


# ══════════════════════════ 单步体检 ══════════════════════════

def _坐标形状(p):
    """返回 None = 没问题；否则返回一句人话。

    ★ **只检查形状，绝不修正内容。** 「起点」是主链认的占位符，放行。
    """
    if p == "起点":
        return None
    if isinstance(p, (list, tuple)):
        if len(p) < 3:
            return (f"只给了 {len(p)} 个数 —— 坐标要三个（x y z）")
        for v in p[:3]:
            try:
                float(v)
            except (TypeError, ValueError):
                return f"里有不是数字的东西（{v!r}）—— 三个都要是数字"
        return None
    return (f"不是三个数，拿到的是 {type(p).__name__}：{str(p)[:40]!r}"
            f" —— 要写成 p=[x,y,z] 这样")


def 体检一步(步, 序):
    """一步 → None（合格）或一句退回理由。"""
    if not isinstance(步, dict):
        return f"第 {序} 步不是个对象（是 {type(步).__name__}）"

    动 = str(步.get("动作") or 步.get("action") or "")
    if not 动:
        return f"第 {序} 步没写「动作」"

    # ── 闸①：不认识的字段 ──
    #   这一条就是抓「目标」那个 bug 的。模型换个名字写，等于主链读不到。
    野 = sorted(set(步) - 认识字段)
    if 野:
        要 = 必填.get(动) or ()
        对 = 写法.get(动, "")
        提示 = f"；它需要 {'、'.join(要)}" if 要 else ""
        # ★ 光说"你写错了"没用 —— 必须把**正确写法**摆出来，模型才知道怎么改。
        #   （第一版这里只写了"它需要 p"，测试当场判它不合格。）
        示范 = f"。正确写法：{对}" if 对 else ""
        return (f"第 {序} 步「{动}」里有**不认识的字段**：{'、'.join(野)}"
                f"{提示}{示范}。字段名必须和规格一模一样，写错了就等于没写。")

    # ── 闸②：必填字段 ──
    缺 = [k for k in (必填.get(动) or ())
          if 步.get(k) is None or 步.get(k) == "" or 步.get(k) == []]
    if 缺:
        对 = 写法.get(动, "")
        return (f"第 {序} 步「{动}」缺 {'、'.join(缺)}"
                + (f"。正确写法：{对}" if 对 else ""))

    # ── 闸③：坐标的形状 ──
    if "p" in (必填.get(动) or ()):
        坏 = _坐标形状(步.get("p"))
        if 坏:
            return f"第 {序} 步「{动}」的坐标{坏}"

    # ── 闸④：往箱子里放 —— 数量/保留 至少给一个（跟动作面同一条规矩）──
    if 动 == "往箱子里放" and 步.get("数量") is None and 步.get("保留") is None:
        return f"第 {序} 步「往箱子里放」既没给「数量」也没给「保留」"

    return None


def 体检(步骤):
    """整份任务书的步骤表 → None（合格）或一句退回理由。

    ★ **一票否决**：任何一步不合格，整份退回。
      不像话的半份任务书比没有更危险 —— 它会在跑到一半的时候卡住。
    """
    for i, 步 in enumerate(步骤 or [], 1):
        坏 = 体检一步(步, i)
        if 坏:
            return 坏
    return None


# ══════════════════════════ 装上 / 卸下 ══════════════════════════

def 装上(bridge, 开关=True, 车钩=None, 日志=None):
    global _已装, _主链, _记
    if not 开关:
        return {"好": False, "打了": [],
                "为什么": "开关关着 —— 一个补丁都不打（行为与基线逐字节相同）"}
    if _已装 or getattr(bridge, "_任务书体检外挂", None):
        return {"好": False, "打了": [], "为什么": "已经打过了，不重复打"}
    _主链, _记 = bridge, 日志

    译 = getattr(bridge, "翻译器", None)
    if 译 is None or not callable(getattr(译, "_校验任务", None)):
        return {"好": False, "打了": [],
                "为什么": "主链上没有 翻译器._校验任务() —— 拒绝打补丁"}

    # ★ `bridge.翻译器` 拿到的**就是类本身**，不是实例 —— 所以别再 type() 一次，
    #   那会得到 `type`（元类）。2026-10-07 踩过：
    #   `AttributeError: type object 'type' has no attribute '_校验任务'`。
    译类 = 译
    原 = 译类._校验任务          # ★ 取**类上**那个，调用时自己传 self

    def 新校验(self, 任务, s):
        # ★ 主链自己的检查**先跑**：它拒了就原样返回它的理由。
        #   （免得把「任务书里不许有『打』」这种宪法级提示，
        #     盖成一句干巴巴的「缺 p」。）
        好, 原因, 干净 = 原(self, 任务, s)
        if not 好:
            return 好, 原因, 干净
        坏 = 体检((干净 or {}).get("步骤") or [])
        if 坏:
            统计["退回"] += 1
            _归类(坏)
            _说(f"任务书体检：退回 —— {坏}")
            return False, 坏, None
        统计["体检过"] += 1
        return True, None, 干净

    译类._校验任务 = 新校验
    _原["_校验任务"] = 原
    bridge._任务书体检外挂 = True
    _已装 = True
    return {"好": True, "为什么": "",
            "打了": [f"翻译器._校验任务()  ← 必填字段闸 + 不认识的字段闸"
                    f"（认识 {len(认识字段)} 个字段，{len(必填)} 个动作有必填要求）"]}


def 卸下(bridge):
    global _已装
    if not _已装:
        return False
    译 = getattr(bridge, "翻译器", None)
    if 译 is not None and "_校验任务" in _原:
        译._校验任务 = _原["_校验任务"]        # 同上：译就是类
    _原.clear()
    if hasattr(bridge, "_任务书体检外挂"):
        del bridge._任务书体检外挂
    _已装 = False
    return True


def 报个话(bridge):
    return {"装上": _已装, "统计": dict(统计),
            "记号": bool(getattr(bridge, "_任务书体检外挂", None))}
