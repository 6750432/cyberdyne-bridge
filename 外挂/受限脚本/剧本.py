#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""受限剧本 —— 让大模型一次写一小段「剧本」，而不是一步一句。

┌───────────────────────────────────────────────────────────────────┐
│ 为什么要这个东西                                                 │
└───────────────────────────────────────────────────────────────────┘
2026-10-07 对比 Numen（言出法随）时看明白的：它让大模型**写 Lua 程序**，
一次调用连干几十步；我们让模型填 JSON，一次一两步。这不是小差距，这是
一个数量级的表达力差距。

但我们的底线不能丢 —— **不信任模型的每一句话**。所以两头都要：
    多给表达力（能写循环、能批量重复）
    ⚠ 但绝不放宽校验（展开出来的东西照样逐条过 fail-closed 闸）

┌───────────────────────────────────────────────────────────────────┐
│ 折中方案：**静态展开**，不是「解释执行」                          │
└───────────────────────────────────────────────────────────────────┘
★ 关键设计：剧本不是"运行时被解释"的，而是**在接单之前就被展开成一张
  扁平的具体步骤表**。循环在展开时就被拆开，`i` 在展开时就被代入成
  具体数字。所以：

    · 校验器看到的 = 真正会跑的，一个字节都不差（没有"运行期才知道"）
    · 不支持变量运算、不支持条件分支 —— 那些会让步骤变得"不可静态判定"
    · 模型写的循环次数必须是**字面量**，不是表达式

  换句话说：**给的是"写起来省事"，不是"跑起来更自由"。**

┌───────────────────────────────────────────────────────────────────┐
│ 剧本长什么样                                                     │
└───────────────────────────────────────────────────────────────────┘
    # 井号开头是注释
    走到 100 64 -200
    挖 石头                       ← 不对，挖只要坐标，看下面的规格表
    挖 100 64 -200
    重复 5 次 记作 i {
      挖 100+i 64 -200
      走到 100+i 64 -199
    }
    合成 物品=crafting_table 数量=1
    说 我去挖矿了

┌───────────────────────────────────────────────────────────────────┐
│ ⚠ 这个文件带的**新攻击面**，以及怎么堵的                          │
└───────────────────────────────────────────────────────────────────┘
主链的 `任务栈.接()` 只查「动作在不在 `允许动作` 里」，而 **「打」就在
允许动作里**（主链 line 1372）。拦住「打」的是它上面的**翻译器**
（`翻译器.禁止步骤 = {"打"}`）—— 可剧本这条路**根本不经过翻译器**。

所以本文件必须自己把这道闸补上，否则「剧本」就成了绕过宪法的后门：
    ① 禁止动作（翻译器.禁止步骤 ∪ 翻译器.攻击类）= 一个字都不许出现
    ② 动作必须在 `允许动作` 里（清单外的连解析都不过）
    ③ 危险物品（拿得到那份名单的话）精确比对
    ④ 步数上限 / 重复上限 / 嵌套上限 —— 防止一段剧本把脑卡死
见 `展开()` 里的 ① ② ③ ④ 四道。`--自检` 里有专门打这个后门的用例。
"""

import json
import os
import re
import sys

# ══════════════════════════ 规格表 ══════════════════════════
# 每一行剧本 → 一个步骤字典。字段名**必须和主链 bridge.py 的 _下发() 对得上**，
# 对不上的话步骤会被静默忽略 —— 所以这张表是"接口契约"，改主链就得改这里。
#
#   坐标 = 行首连着几个裸 token（数字 / 算式 / 「起点」）
#   命名 = `键=值`
#   自由 = 剩下整行都是文本（只有「说」这样）
规格 = {
    "走到":       {"坐标": True,  "命名": set(),             "说明": "走到 x y z"},
    "挖":         {"坐标": True,  "命名": set(),             "说明": "挖掉 x y z 那格"},
    "放":         {"坐标": True,  "命名": set(),             "说明": "在 x y z 放一个方块"},
    "说":         {"坐标": False, "命名": set(), "自由": True, "说明": "说 一段话"},
    "拾":         {"坐标": False, "命名": {"物品"},           "说明": "拾 [物品=名字]"},
    "熔炉取成品": {"坐标": True,  "命名": set(),             "说明": "熔炉取成品 x y z"},
    "熔炉放料":   {"坐标": True,  "命名": {"输入", "数量", "燃料"},
                  "说明": "熔炉放料 x y z 输入=铁矿:3 燃料=煤炭:1"},
    "合成":       {"坐标": False, "命名": {"物品", "数量"},   "说明": "合成 物品=名字 [数量=2]"},
    "箱子里取":   {"坐标": True,  "命名": {"物品", "数量"},   "说明": "箱子里取 x y z 物品=名字 数量=10"},
    "往箱子里放": {"坐标": True,  "命名": {"物品", "数量", "保留"},
                  "说明": "往箱子里放 x y z 物品=名字 数量=10（或 保留=5）"},
    "等":         {"坐标": False, "命名": {"秒"},             "说明": "等 秒=3"},
}

默认上限 = {"最多步": 40, "最多重复": 16, "最多嵌套": 2, "最多行": 400}

# 循环行：`重复 5 次 记作 i {`
_循环头 = re.compile(
    r"^重复\s+(\d+)\s+次(?:\s+记作\s+([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*))?\s*\{\s*$")
_数字 = re.compile(r"^-?\d+$")
_正数 = re.compile(r"^\d+$")
_名字 = re.compile(r"^[A-Za-z_][\w.]*$")


class 剧本错(Exception):
    """剧本有问题 —— 一律拒绝执行，绝不"猜你的意思"。"""


# ══════════════════════════ 坐标算式 ══════════════════════════
# ★ **刻意不用 eval()**。只用得着四种写法，写个小解析器就够了：
#   3    i    3+i    3-2*i

def _算式(文, 变量):
    文 = 文.strip()
    if 文 in 变量:
        return 变量[文]
    if _数字.match(文):
        return int(文)
    项 = re.findall(r"([+-]?)\s*([^+-]+)", 文)
    if not 项:
        raise 剧本错(f"看不懂的坐标写法「{文}」")
    总 = 0
    for 号, 体 in 项:
        体 = 体.strip()
        if not 体:
            continue
        if "*" in 体:
            左, _, 右 = 体.partition("*")
            左, 右 = 左.strip(), 右.strip()
            if 左 in 变量 and _正数.match(右):
                值 = 变量[左] * int(右)
            elif 右 in 变量 and _正数.match(左):
                值 = int(左) * 变量[右]
            else:
                raise 剧本错(f"乘号两边必须是「数字 * 循环变量」：看不懂「{体}」")
        elif 体 in 变量:
            值 = 变量[体]
        elif _正数.match(体):
            值 = int(体)
        else:
            raise 剧本错(f"看不懂的坐标写法「{体}」（只认 数字、循环变量、数字±变量）")
        总 = 总 - 值 if 号 == "-" else 总 + 值
    return 总


# ══════════════════════════ 一行 → 一个步骤 ══════════════════════════

def _切参数(词):
    """行首连着几个裸 token = 坐标；从第一个 `键=值` 开始都算命名参数。"""
    位置, 命名 = [], {}
    i = 0
    while i < len(词) and "=" not in 词[i]:
        位置.append(词[i])
        i += 1
    for 段 in 词[i:]:
        if "=" not in 段:
            raise 剧本错(f"「{段}」既不是坐标也不是 键=值 —— 我不猜")
        键, _, 值 = 段.partition("=")
        键, 值 = 键.strip(), 值.strip()
        if not 键 or not 值:
            raise 剧本错(f"「{段}」的键或值是空的")
        命名[键] = 值
    return 位置, 命名


def _一行(行, 变量, 允许动作, 禁止动作, 危险物品):
    """一行剧本 → 一个步骤字典（已做完所有静态检查）。"""
    词 = 行.split()
    if not 词:
        return None
    动 = 词[0]
    身 = 词[1:]

    # ★ ① 禁止动作 **放在最前面查** —— 它是宪法级红线。
    #   顺序不能反：如果先查「认不认识这个动词」，那么等哪天有人把
    #   「打」加进规格表，这道闸就等于不存在了。红线的检查永远排第一。
    if 动 in 禁止动作:
        raise 剧本错(f"★「{动}」是禁止动作（宪法①②条）—— 剧本里永远不许有它")
    # ② 动作必须是剧本登记过的
    if 动 not in 规格:
        raise 剧本错(f"不认识的剧本动词「{动}」（剧本只认：{'、'.join(规格)}）")
    # ③ 动作必须在主链的动作清单里
    if 动 not in 允许动作:
        raise 剧本错(f"「{动}」不在主链的动作清单里 —— 我不接")

    规 = 规格[动]
    步 = {"动作": 动}

    # 「说」是特殊的：剩下整行都是文本
    if 规.get("自由"):
        文 = 行[len(动):].strip()
        if not 文:
            raise 剧本错("「说」后面得有话说")
        步["文本"] = 文[:120]
        return 步

    位置, 命名 = _切参数(身)

    # 坐标
    if 规.get("坐标"):
        if len(位置) != 3:
            raise 剧本错(f"「{动}」要三个坐标，给了 {len(位置)} 个"
                       f"（正确写法：{规['说明']}）")
        if 位置[0] == "起点":
            if len(位置) != 3:
                raise 剧本错("「起点」要写三次（起点 起点 起点）")
            步["p"] = "起点"
        else:
            步["p"] = [_算式(x, 变量) for x in 位置]
    elif 位置:
        raise 剧本错(f"「{动}」不收坐标，可你给了 {' '.join(位置)}（正确写法：{规['说明']}）")

    # 命名参数
    多余 = set(命名) - set(规["命名"])
    if 多余:
        raise 剧本错(f"「{动}」不认识参数 {'、'.join(sorted(多余))}（它能收："
                   f"{'、'.join(sorted(规['命名'])) or '无'}）")

    for 键, 值 in 命名.items():
        if 键 == "数量":
            if not _正数.match(值):
                raise 剧本错(f"数量必须是正整数，给了「{值}」")
            步["数量"] = int(值)
        elif 键 == "秒":
            try:
                f = float(值)
            except ValueError:
                raise 剧本错(f"秒数必须是个数，给了「{值}」")
            步["秒"] = f
        elif 键 in ("输入", "燃料"):
            # 熔炉那两样是 `物品名:数量`，主链要的是 {"name":…,"count":…}
            名, _, 数 = 值.partition(":")
            名 = 名.strip()
            数 = (数 or "1").strip()
            if not _名字.match(名):
                raise 剧本错(f"{键} 的物品名不合法：「{名}」")
            if not _正数.match(数):
                raise 剧本错(f"{键} 的数量不合法：「{数}」")
            步[键] = {"name": 名, "count": int(数)}
        elif 键 == "物品":
            if not _名字.match(值):
                raise 剧本错(f"物品名不合法：「{值}」")
            步["物品"] = 值
        elif 键 == "保留":
            if not _正数.match(值):
                raise 剧本错(f"保留数量必须是正整数，给了「{值}」")
            步["保留"] = int(值)

    # ③ 危险物品：**精确比对，绝不做包含判断**
    #    （「火把」跟「把」、「石头」跟「圆石」这种坑，2026-10-01 栽过）
    见到的 = [步.get("物品")]
    for k in ("输入", "燃料"):
        if isinstance(步.get(k), dict):
            见到的.append(步[k].get("name"))
    for x in 见到的:
        if x and str(x).strip() in 危险物品:
            raise 剧本错(f"「{x}」是危险物品 —— 剧本里不许碰")

    return 步


# ══════════════════════════ 展开 ══════════════════════════

def 展开(文本, 允许动作, 禁止动作=(), 危险物品=(),
         最多步=None, 最多重复=None, 最多嵌套=None):
    """剧本 → 扁平的步骤表。**全是静态展开，没有运行期求值。**

    返回 {"好":bool, "为什么":str, "步骤":[…], "统计":{…}}
    任何一条不过就返回 好=False —— **抛出异常只用于程序写错，不用于剧本写错**。
    """
    上限 = dict(默认上限)
    if 最多步 is not None:
        上限["最多步"] = 最多步
    if 最多重复 is not None:
        上限["最多重复"] = 最多重复
    if 最多嵌套 is not None:
        上限["最多嵌套"] = 最多嵌套

    允许动作 = frozenset(允许动作)
    禁止动作 = frozenset(禁止动作)
    危险物品 = frozenset(x for x in 危险物品 if x)

    步骤 = []
    统计 = {"行数": 0, "循环次数": 0, "最深处": 0, "展开了几行": 0}

    def 走(行段, 变量, 深):
        统计["最深处"] = max(统计["最深处"], 深)
        i = 0
        while i < len(行段):
            行号, 行 = 行段[i]
            i += 1
            if not 行:
                continue
            统计["行数"] += 1
            if 统计["行数"] > 上限["最多行"]:
                raise 剧本错(f"剧本太长（超过 {上限['最多行']} 行）")
            m = _循环头.match(行)
            if m:
                次数 = int(m.group(1))
                名 = m.group(2) or "_i"
                if 次数 < 1:
                    raise 剧本错(f"第 {行号} 行：重复次数得 ≥1")
                if 次数 > 上限["最多重复"]:
                    raise 剧本错(f"第 {行号} 行：重复 {次数} 次太多了"
                               f"（一次最多 {上限['最多重复']} 次）")
                if 深 + 1 > 上限["最多嵌套"]:
                    raise 剧本错(f"第 {行号} 行：循环嵌套太深（最多 "
                               f"{上限['最多嵌套']} 层）")
                # 找出配对的 }
                层 = 1
                j = i
                while j < len(行段):
                    if _循环头.match(行段[j][1]):
                        层 += 1
                    elif 行段[j][1] == "}":
                        层 -= 1
                        if 层 == 0:
                            break
                    j += 1
                if 层 != 0:
                    raise 剧本错(f"第 {行号} 行：这个「重复」没有配对的「}}」")
                身 = 行段[i:j]
                i = j + 1
                统计["循环次数"] += 1
                for k in range(次数):
                    走(身, dict(变量, **{名: k}), 深 + 1)
                    if len(步骤) > 上限["最多步"]:
                        raise 剧本错(f"展开后步骤超过 {上限['最多步']} 步 —— "
                                   f"剧本别写太大，分几次交给我")
                continue
            if 行 == "}":
                raise 剧本错(f"第 {行号} 行：多了个「}}」，没有对应的「重复」")
            步 = _一行(行, 变量, 允许动作, 禁止动作, 危险物品)
            if 步:
                步骤.append(步)
                统计["展开了几行"] += 1
                if len(步骤) > 上限["最多步"]:
                    raise 剧本错(f"展开后步骤超过 {上限['最多步']} 步 —— "
                               f"剧本别写太大，分几次交给我")

    # 切行：去注释、去空行，但保留行号（出错好找）
    行段 = []
    for 号, 原 in enumerate(str(文本 or "").splitlines(), 1):
        行 = 原.split("#", 1)[0].strip()
        行段.append((号, 行))

    统计["总行"] = len(行段)
    try:
        走(行段, {}, 0)
    except 剧本错 as e:
        return {"好": False, "为什么": str(e), "步骤": [], "统计": 统计}

    if not 步骤:
        return {"好": False, "为什么": "剧本是空的（一行活儿都没有）",
                "步骤": [], "统计": 统计}
    return {"好": True, "为什么": "", "步骤": 步骤, "统计": 统计}


def 说明书(允许动作=None):
    """生成给模型看的剧本语法说明（外置文本，跟动作面一个规矩）。"""
    行 = ["【剧本写法】你可以用「剧本」代替「步骤」：一次把一串活儿写清楚。",
          "剧本是按行写的，一行一个动作。# 后面的都是注释。", ""]
    可用 = [k for k in 规格 if (允许动作 is None or k in 允许动作)]
    for k in 规格:
        if k not in 可用:
            continue
        行.append("  " + 规格[k]["说明"])
    行 += ["",
          "循环（次数必须是写死的数字，不能是算出来的）：",
          "  重复 5 次 记作 i {",
          "    挖 100+i 64 -200",
          "  }",
          "",
          "坐标里可以出现循环变量 i：写法有 3、i、3+i、3-2*i 这几种。",
          "坐标也可以写「起点 起点 起点」，表示「从你自己的位置算起」。",
          "",
          "⚠ 剧本里**没有**条件判断、没有变量计算 —— 展开出来就是一张死表。",
          "  想分情况，就分开写几段剧本，看情况交哪一段。"]
    return "\n".join(行)


# ══════════════════════════ 自检 ══════════════════════════
# 风格跟 外挂/动作面/自检.py 一致：**每条都打印，人工看得见**。

def 跑自检():
    通过, 失败 = [], []

    def 该过(名, 文本, 期待步数=None, 允许动作=None, **kw):
        r = 展开(文本, 允许动作=(_默认允许 if 允许动作 is None else 允许动作), **kw)
        if not r["好"]:
            失败.append((名, "该过却没过：" + r["为什么"]))
        elif 期待步数 is not None and len(r["步骤"]) != 期待步数:
            失败.append((名, f"步数 {len(r['步骤'])} ≠ 期望 {期待步数}"))
        else:
            通过.append(名)
        return r

    def 该拦(名, 文本, 关键词="", 允许动作=None, **kw):
        r = 展开(文本, 允许动作=(_默认允许 if 允许动作 is None else 允许动作), **kw)
        if r["好"]:
            失败.append((名, f"该拦却放过了（展开成 {len(r['步骤'])} 步）"))
        elif 关键词 and 关键词 not in r["为什么"]:
            失败.append((名, f"拦住了但理由不对：「{r['为什么']}」里没有「{关键词}」"))
        else:
            通过.append(名)
        return r

    _默认允许 = frozenset(规格) | {"打"}

    # ── A 组：正常剧本 ──
    该过("A1 一行", "挖 100 64 -200", 1)
    该过("A2 多行", "挖 100 64 -200\n走到 100 64 -199", 2)
    该过("A3 注释与空行", "# 注\n\n挖 1 2 3\n   # 又一注", 1)
    该过("A4 说（自由文本）", "说 我去挖矿了，你等我", 1)
    该过("A5 起点占位", "挖 起点 起点 起点", 1)

    r = 该过("A6 循环展开", "重复 3 次 记作 i {\n  挖 10+i 64 -200\n}", 3)
    if r["好"] and [s["p"][0] for s in r["步骤"]] != [10, 11, 12]:
        # ★ 这行是重点：循环**在展开时**就把 i 代进去了
        失败.append(("A6 循环展开", f"i 没代对：{[s['p'][0] for s in r['步骤']]}"))
