def 主():
    argv = sys.argv[1:]
    if not argv or argv[0] in ("-h", "--help", "帮助"):
        print(__doc__)
        return 0
    if argv[0] == "--自检":
        查 = 跑自检()
        _打印查(查)
        return 1 if 查["失败"] else 0
