#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""收集车厢 —— 离线测试。

English: Offline tests for the "collect" carriage: collapse a run of dig-then-pickup steps
into a single hand-side `collect` command, and never collapse it wrongly.

跑法：python3 外挂/测收集.py
"""

import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")
通过, 失败 = [], []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


class 假任务栈:
    def __init__(self):
        self.接过的 = []

    def 接(self, 名字, 步骤, s):
        self.接过的.append((名字, 步骤))
        return True

    # ⚠ 替身必须是**同一个类**（今天栽过"替身的类必须和实例是一家人"✗）——
    #   这两个方法原来没有 ✓ → 车厢"看见"没法接 ✓ → 静默不接线 ✗
    #   用例 E1/E2 一跑就露馅了 ✓ 正是它该干的事 ✓
    def _下发(self, 步, 任, 现在, s):
        self.发的 = getattr(self, "发的", [])
        self.发的.append({"动作": 步.get("动作")})       # 原装：只会记一笔 ✓
        return True

    def _看完成了没(self, 步, s, 任=None):
        return None, None


class 假bridge:
    pass


def 载(名):
    p = os.path.join(外挂根, 名, "补丁.py")
    spec = importlib.util.spec_from_file_location(f"测_{名}", p)
    m = importlib.util.module_from_spec(spec)
    sys.modules[f"测_{名}"] = m
    sys.path.insert(0, os.path.join(外挂根, 名))
    spec.loader.exec_module(m)
    return m


def 造环境():
    b = 假bridge()
    # ★ 允许动作要是**集合**（主链类属性就是这么个东西 ✓）
    类 = type("栈类", (), dict(vars(假任务栈)))
    类.允许动作 = frozenset({"走到", "挖", "拾", "合成", "放"})
    b.任务栈 = 类
    return b, 类


def 主():
    sys.path.insert(0, 外挂根)
    sys.path.insert(0, ROOT)
    收 = 载("收集")
    b, 类 = 造环境()

    print("── A 组：装上 / 卸下 ──")
    r = 收.装上(b)
    试("A1 装上了", bool(r.get("好")), str(r))
    r2 = 收.装上(b)
    试("A2 ★★ 重复装是幂等的（不许套两层 ✓）", bool(r2.get("好")), str(r2))
    试("A3 ★★★ 顺手把 `collect` 加进**允许动作**了 ✓"
       "（新动作不同时开闸 = 当场拒单 ✗ 今天栽过「你说开了可它不会」那个坑 ✓）",
       "collect" in 类.允许动作, str(sorted(类.允许动作)))

    print("── B 组 ★★★ 该收的收掉（实机 14:28 那条链）──")
    # 挖 oak_log 掉 oak_log ✓（原木掉自己 ✓）
    计划 = [{"动作": "走到", "p": [-143, 80, 148]},
           {"动作": "挖", "p": [-143, 80, 148], "方块": "oak_log"},
           {"动作": "拾", "物品": "oak_log", "数量": 1},
           {"动作": "挖", "p": [-143, 80, 148], "方块": "oak_log"},
           {"动作": "拾", "物品": "oak_log", "数量": 1},
           {"动作": "挖", "p": [-143, 80, 148], "方块": "oak_log"},
           {"动作": "拾", "物品": "oak_log", "数量": 1},
           {"动作": "合成", "物品": "oak_planks", "数量": 4}]
    栈 = 类()
    栈.接("砍树", 计划, {})
    送 = 栈.接过的[-1][1]
    动 = [x.get("动作") for x in 送]
    试("B1 ★★★ 「挖/拾」×3 → **收成一条 collect** ✓（原来 6 步 ✓）",
       动.count("collect") == 1 and 动.count("挖") == 0 and 动.count("拾") == 0, str(动))
    条 = [x for x in 送 if x.get("动作") == "collect"][0]
    试("B2 ★★★ 数量按**组数**算 ✓（3 组 → 数量 3 ✓ 不拍 ✗）",
       条.get("数量") == 3, str(条))
    试("B3 ★★★ 收的是**掉落物**的名字 ✓（挖 oak_log 掉 oak_log ✓）",
       条.get("物品") == "oak_log", str(条))
    试("B4 ★★ 别的步骤**一个字不动** ✓（走到/合成都得原样 ✓）",
       "走到" in 动 and "合成" in 动, str(动))

    # ★ 挖草方块掉的是 dirt（不是 grass_block）★ 这正是「物理引擎规则」那条
    计划2 = [{"动作": "挖", "p": [1, 60, 1], "方块": "grass_block"},
            {"动作": "拾", "物品": "dirt", "数量": 1},
            {"动作": "挖", "p": [1, 60, 1], "方块": "grass_block"},
            {"动作": "拾", "物品": "dirt", "数量": 1}]
    栈.接过的 = []
    栈.接("挖草", 计划2, {})
    送2 = 栈.接过的[-1][1]
    条2 = [x for x in 送2 if x.get("动作") == "collect"]
    试("B5 ★★★ 「挖 grass_block → 拾 **dirt**」也认得 ✓"
       "（掉什么**查表**说的 ✓ 不是我猜的 ✗ —— 挖草方块掉的是土 ✓）",
       bool(条2) and 条2[0].get("物品") == "dirt" and 条2[0].get("数量") == 2, str(送2))

    print("── C 组 ★★★ 不该收的**一步都不许动**（宁可少收，不许收错 ✗）──")
    # ① 只有一组 → 不收 ✓（收了反而多绕路 ✗）
    栈.接过的 = []
    栈.接("挖一下", [{"动作": "挖", "p": [1, 60, 1], "方块": "oak_log"},
                  {"动作": "拾", "物品": "oak_log", "数量": 1}], {})
    试("C1 ★★★ 只有**一组** → 原样不动 ✓（规矩①：一组不值得收 ✗）",
       [x.get("动作") for x in 栈.接过的[-1][1]] == ["挖", "拾"], str(栈.接过的[-1][1]))

    # ② 「拾」的东西不是那一挖的掉落物 → 不收 ✓
    栈.接过的 = []
    栈.接("拾错东西", [{"动作": "挖", "p": [1, 60, 1], "方块": "oak_log"},
                    {"动作": "拾", "物品": "stick", "数量": 1},
                    {"动作": "挖", "p": [1, 60, 1], "方块": "oak_log"},
                    {"动作": "拾", "物品": "stick", "数量": 1}], {})
    试("C2 ★★★ 「拾」的不是那一挖的掉落物 → **不收** ✓（规矩④）",
       not any(x.get("动作") == "collect" for x in 栈.接过的[-1][1]),
       str(栈.接过的[-1][1]))

    # ③ 中间夹了别的动作 → 断开 ✓
    栈.接过的 = []
    栈.接("夹了别的", [{"动作": "挖", "p": [1, 60, 1], "方块": "oak_log"},
                    {"动作": "拾", "物品": "oak_log", "数量": 1},
                    {"动作": "走到", "p": [2, 60, 1]},
                    {"动作": "挖", "p": [1, 60, 1], "方块": "oak_log"},
                    {"动作": "拾", "物品": "oak_log", "数量": 1}], {})
    试("C3 ★★★ 中间夹了「走到」→ **断开**✗（规矩②：收起来的必须是连着的 ✓）",
       not any(x.get("动作") == "collect" for x in 栈.接过的[-1][1]),
       str(栈.接过的[-1][1]))

    # ④ 两处不同的地方挖同名方块 → 断开 ✓（我第一版只看名字 ✗ 会把两组活儿并成一条 ✗）
    栈.接过的 = []
    栈.接("两棵树", [{"动作": "挖", "p": [10, 60, 1], "方块": "oak_log"},
                  {"动作": "拾", "物品": "oak_log", "数量": 1},
                  {"动作": "挖", "p": [99, 60, 1], "方块": "oak_log"},
                  {"动作": "拾", "物品": "oak_log", "数量": 1}], {})
    试("C4 ★★★ **两处不同地方**的同名方块 → 断开 ✗"
       "（我第一版只看名字 ✓ 会把两棵树的活儿并成一条 → 它跑去一棵树挖两下 ✗）",
       not any(x.get("动作") == "collect" for x in 栈.接过的[-1][1]),
       str(栈.接过的[-1][1]))

    # ⑤ 拿不准的方块（查不到掉落物）→ 不动 ✓
    栈.接过的 = []
    栈.接("不认识的方块", [{"动作": "挖", "p": [1, 60, 1], "方块": "某个不存在的方块"},
                      {"动作": "拾", "物品": "某个不存在的方块", "数量": 1},
                      {"动作": "挖", "p": [1, 60, 1], "方块": "某个不存在的方块"},
                      {"动作": "拾", "物品": "某个不存在的方块", "数量": 1}], {})
    试("C5 ★★★ 查表查不到掉什么 → **原样不动** ✓（规矩⑤：拿不准就不动 ✗）",
       not any(x.get("动作") == "collect" for x in 栈.接过的[-1][1]),
       str(栈.接过的[-1][1]))

    print("── E 组 ★★★ 新动作必须**接线**（光开闸不接线 = 等于没做 ✗）──")
    b3, 类3 = 造环境()
    收.卸下(b3)
    收.装上(b3)
    栈3 = 类3()
    栈3.发的 = []
    栈3.发 = lambda m: 栈3.发的.append(m)
    栈3._下发({"动作": "collect", "物品": "oak_log", "数量": 3}, {}, 0.0, {})
    试("E1 ★★★ 脑的 `collect` → 手的 `{cmd:\"collect\"}` ✓"
       "（这一步不接，手那边再多能力也白搭 ✓）",
       bool(栈3.发的) and 栈3.发的[-1].get("cmd") == "collect"
       and 栈3.发的[-1].get("物品") == "oak_log" and 栈3.发的[-1].get("数量") == 3,
       str(栈3.发的[-1:]))
    试("E2 ★★★ 背包里够了 → 判完成 ✓（判据跟「拾」一模一样 ✓）",
       栈3._看完成了没({"动作": "collect", "物品": "oak_log", "数量": 3},
                    {"items": {"oak_log": 3}})[0] is True)
    试("E3 ★★★ 背包里不够 → 判**没**完成 ✓（不许假完成 ✗）",
       栈3._看完成了没({"动作": "collect", "物品": "oak_log", "数量": 3},
                    {"items": {"oak_log": 1}})[0] is False)
    试("E4 ★★★ 这一帧**没有背包清单** → 判没完成 ✓（「不知道」≠「完成」✗）",
       栈3._看完成了没({"动作": "collect", "物品": "oak_log", "数量": 3}, {})[0] is False)
    收.卸下(b3)

    print("── D 组：卸下还原 ──")
    收.卸下(b)
    栈2 = 类()
    栈2.接("卸下之后", 计划, {})
    试("D1 ★★★ 卸下之后**一字不差**（不再收 ✓ 也不再有 collect 这个动作 ✓）",
       [x.get("动作") for x in 栈2.接过的[-1][1]] == [x.get("动作") for x in 计划]
       and "collect" not in getattr(类, "允许动作", set()),
       str([x.get("动作") for x in 栈2.接过的[-1][1]]))

    print(f"\n{'═' * 62}")
    print(f"收集车厢：{len(通过)} 过 / {len(失败)} 失败")
    for x in 通过:
        print(f"  ✅ {x}")
    for x in 失败:
        print(f"  ❌ {x['名']} —— {x['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
