def 可用方块(状态):
    """**给求解器看的「附近有什么」** = 扫描报的 + 脚下那块。

    ★ 为什么要加脚下那块：求解器只认 `方块在哪` 这张表。如果只喂扫描结果，
      它不知道「石头就在我脚下」，于是 `#stone_tool_materials` 这个标签里
      它会挑中 `blackstone`（字母序靠前、难度并列）—— 而黑石在下界。
      把脚下那块加进去，它就会正确地挑 `cobblestone`。
    """
    表 = 扫描表(状态)
    _报(f"[探针-可用] 扫描表给了 {sorted(表)} ｜ scan.石头="
        f"{((状态 or {}).get('scan') or {}).get('石头')!r}")
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 and 脚位:
        表.setdefault(脚名, 脚位)
    return 表


def 脚下是什么(状态):
    """我正踩着的是什么方块 —— 扫描的「地面」字段，配合已知的自身坐标。

    这是**唯一一处能"免费"拿到坐标的方块**：不用扫描给，位置就是
    `[floor(x), floor(y)-1, floor(z)]`，而自身坐标是状态帧里每拍都有的。
    """
    扫 = (状态 or {}).get("scan") or {}
    名 = 扫.get("地面")
    if not 名:
        return None, None
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return 名, None
    return 名, [int(我[0] // 1), int(我[1]) - 1, int(我[2] // 1)]


def 找坐标(步骤, 状态, 扫描缓存, 要挖吗=False):
    """一个符号化步骤 → 具体坐标。找不到返回 (None, 原因)。"""
    方块 = 步骤.get("目标方块") or 步骤.get("方块")
    if not 方块:
        return None, "这一步没说要找哪个方块"

    # ① 扫描里有就直接用
    if 方块 in 扫描缓存:
        return 扫描缓存[方块], None

    # ★★★ 2026-10-09 主人问「**为啥在找合欢木**？」—— 根在这儿：
    #   求解器手里**没有任何"这里有什么木头"的情报**时，会按配方默认挑一种 ✗
    #   （实机挑中 `acacia_log` ✗ 可那片林子只有橡木/白桦 ✓）→ 于是"永远找不到"✗
    #   雷达现在会连**同一族**一起报回来（`*_log` ✓）⇒ 同族的就该**能用** ✓
    #   ⚠ 族是**算出来的**（下划线后那半段 ✓）不是写死名单 ✗ ——
    #     所以 `oak_planks` 和 `oak_log` **不同族** ✓ 绝不会拿原木替木板 ✓
    for 名有, 位有 in 扫描缓存.items():
        if _同族吗(名有, 方块):
            _说(f"  · 要「{方块}」可周围只有「{名有}」—— **同族（{_族名(名有)}），用它** ✓")
            return 位有, None

    # ② 它是不是我**正脚下**那块？—— 地面字段 + 自身坐标 = 免费定位
    #
    #   ⚠ 但「挖」不能用这个位置：手侧 `挖()` 有一条安全护栏
    #     （`node/plugins/body/proto_body.js:216`）——
    #     **不许挖自己正脚下那块**，理由是「挖了我自己就掉下去了」。
    #     所以这里必须分开：能定位 ≠ 能挖。
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 == 方块 and 脚位:
        if 要挖吗:
            return None, (f"我正站在「{方块}」上，可手侧不许我挖自己脚下那块"
                        f"（挖了我自己就掉下去）；扫描里又没报别的「{方块}」位置")
        return 脚位, None

    # ③ 定位不到 —— **明确失败，绝不猜**。而且要说清楚是哪一种「找不到」：
    #    「压根没有」和「有但没报位置」对主人来说是完全不同的两件事。
    扫 = (状态 or {}).get("scan") or {}
    见过的 = {b.get("name") for b in (扫.get("方块") or []) if isinstance(b, dict)}
    贴身的 = {b.get("name") for b in (扫.get("可交互") or []) if isinstance(b, dict)}
    # ★★★ 2026-10-09 主人当场抓到的**谎报** ✗（原话：「报错里写的找不到木头，
    #   但是之前挖的那棵树只挖了一块下来啊」✓）：
    #   旧版只看「方块 census + 可交互」两栏 ✗ ⇒ 雷达**点名找**那一栏（`scan.找` ✓）
    #   明明报回来了也当没看见 ✓ ⇒ 张嘴就是"我周围压根没有" ✗ = **误报** ✓
    #   （误报比漏报更危险 —— 这一条栽过好几回了 ✓）
    #   规矩：**三栏一起看**（方块 / 可交互 / 找 ✓），而且**说清楚为什么没有** ✓
    找过 = [b for b in (扫.get("找") or []) if isinstance(b, dict)]
    找名 = {b.get("name") for b in 找过 if b.get("name")}
    同族找 = {n for n in 找名 if _同族吗(n, 方块)}
    # ★★★ 2026-10-09：**两种落空都要点单** —— 让雷达按任务穷举这一类方块。
    #   从前这里是纯抱怨：说一句「拿不到坐标」然后**什么都不做**，
    #   于是主链每秒重试、日志刷屏，主人看到的就是「雷达是摆设吗」✗
    #   现在落空即点单：下一拍 `scan.找` 里就该有它 ✓（有就真找，没有才说没有 ✓）。
    if 方块 not in 见过的 and 方块 not in 贴身的 and not 同族找:
        _要雷达找(方块)
        return None, (f"**我周围压根没有「{方块}」** —— 扫描看到的只有 "
                    f"{'、'.join(sorted(x for x in 见过的 if x)[:6]) or '（一片空）'}。"
                    f"**已经让雷达点名找它了**；还是找不到就得走到有它的地方去。")
    if 同族找:
        # ★ 雷达**真报回来了** ✓ —— 那就绝不许说"压根没有" ✗
        _要雷达找(方块)
        return None, (f"雷达点名找**报回了同族的**："
                    f"{'、'.join(sorted(x for x in 同族找)[:4])} ✓ —— "
                    f"可它们**整个被埋住**（反矿透：不瞄看不见的 ✗）⇒ "
                    f"要么先把挡着的那块挖开 ✓，要么换个地方找 ✓"
                    f"（**这回不是「没有」，是「没露出来」** ✓ 两件事不一样 ✗）")
    _要雷达找(方块)
    return None, (f"我周围有「{方块}」，但手侧这一拍只上报了「兴趣方块」名单里的坐标 —— "
                f"**已经让雷达点名找它了**，下一拍就该有位置；这一拍我不瞎挖。")


