def 身边空位(状态, 我=None):
    """★ 用**雷达**找「身边哪一格是空的」—— 放方块就放这儿，不猜。

    主人 2026-10-07：「妈的都有雷达了还不知道放哪儿？」
    坐标是白拿的（我 ± 1），「是不是空的」正是雷达该回答的事。
    返回 (空位列表, 还没读数的那几格)。
    """
    我 = 我 or (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return [], []
    x, y, z = int(我[0] // 1), int(我[1]), int(我[2] // 1)
    候选 = [(x + 1, y, z), (x - 1, y, z), (x, y, z + 1), (x, y, z - 1)]
    已知 = {}
    for 条 in ((状态 or {}).get("blocks") or []):
        p = 条.get("p")
        if isinstance(p, (list, tuple)) and len(p) >= 3:
            已知[(int(p[0]), int(p[1]), int(p[2]))] = str(条.get("name") or "")
    空, 没读数 = [], []
    for c in 候选:
        if c not in 已知:
            没读数.append(list(c))
        elif 已知[c] in 空气名:
            空.append(list(c))
    return 空, 没读数


def 落坐标(计划, 状态):
    """符号化计划 → 具体步骤表。返回 (步骤表, 失败原因)。

    ★ 熔炼那一支是 2026-10-07 接上的：手侧**早就有** `furnace_put` /
      `furnace_take` 两个命令，主链**早就认** `熔炉放料` / `熔炉取成品`
      两个动作（`bridge.py:1348` 里甚至有现成的用法示例）。
      所以这一段**一行主链都不用改**，只是把常识库的「烧炼」翻译过去。
    """
    扫 = 扫描表(状态)
    步骤, 缺 = [], []
    _挖过 = {}          # (块名, 坐标) → 挖了几次（第二次起往下走一格）
    炉位 = None                      # 放炉子那一刻的位置，后面烧东西要用
    # 脚下那块：`地面` 字段给名字，自身坐标给位置 —— 这是**唯一**
    # 不用扫描报坐标就能确定位置的方块（而且不是猜的）。
    脚名, 脚位 = 脚下是什么(状态)

    def 我的位置():
        我 = (状态 or {}).get("pos")
        if isinstance(我, (list, tuple)) and len(我) >= 3:
            return [int(我[0] // 1), int(我[1]), int(我[2] // 1)]
        return None

    for 步 in 计划:
        动 = 步.get("动作")

        if 动 == "合成":
            步骤.append({"动作": "合成", "物品": 步.get("物品"),
                        "数量": 步.get("数量") or 1})
            continue

        if 动 == "挖":
            名 = 步.get("目标方块")
            p, 因 = 找坐标(步, 状态, 扫, 要挖吗=True)
            if p is None and 名 and 名 == 脚名 and 脚位:
                # ★★ 2026-10-07 想通的零改动解法：**不用找，脚下的就已经知道了。**
                #
                #   手侧的 `地面` 字段告诉我们「我踩着的就是 X」，而自身坐标每拍都有
                #   → **脚下那块 X 的坐标是确定无疑的**（不是猜的）。
                #   唯一的麻烦是手侧护栏不许挖「正脚下那块」（挖了自己就掉下去）。
                #
                #   那就**先挪开一格，再挖原来那格**。
                #   挪开之后它就不再是脚下那块了，护栏自然放行；
                #   而且主链的 `_挂探针()` 会把这一格报回来，完成判据也走得通。
                #
                #   ⚠ 这不是"猜一个坐标去挖" —— 坐标是从「地面字段 + 自身坐标」
                #     推出来的**事实**，只是需要先让开一步。
                我 = 我的位置()
                if 我:
                    旁边 = [我[0] + 1, 我[1], 我[2]]
                    步骤.append({"动作": "走到", "p": 旁边, "到点": 1.5})
                    步骤.append({"动作": "挖", "p": list(脚位), "方块": 名})
                    if 名:
                        步骤.append({"动作": "走到", "p": list(脚位), "到点": 3.0})
                        步骤.append({"动作": "拾", "物品": 挖了掉什么(名), "数量": 1})
                    _说(f"  · 挖 {名}：它就在我脚下 —— 先挪开一格再挖（不猜坐标）")
                    continue
            if p is None:
                缺.append(f"挖 {名}：{因}")
                continue
            # 同一个块要挖好几下时（3 个木头、3 块石头），原样重复同一坐标 ——
            # 第二下就是对着空气挥镐。往**下一格**走：树干往下长，石头下面还是石头。
            记数 = _挖过.setdefault((名, tuple(p)), 0)
            _挖过[(名, tuple(p))] = 记数 + 1
            if 记数:
                p = [p[0], p[1] - 记数, p[2]]
            # ★★★ 2026-10-08：挖 步骤必须**带上要挖什么**！
            #   实机抓到的：计划挖 oak_log，它却挖回来 6 个 dirt ——
            #   树早砍了、那格现在是土，而判据只看「那格变空气了没」，
            #   于是**挖错东西照样算完成**，整条链接下来全是假的。
            # ★★★ 2026-10-08 实机：**得先走过去再挖**！
            #   原来写成「挖 → 走到 → 拾」，结果目标在 14 格外，挖的够得着范围
            #   只有 4.5 格 → 一下都挖不动，白等 60 秒超时。
            #   正确顺序：走到（到点 3.0，正好在够得着范围内）→ 挖 → 拾。
            if 名:
                步骤.append({"动作": "走到", "p": list(p), "到点": 3.0})
            步骤.append({"动作": "挖", "p": p, "方块": 名} if 名
                        else {"动作": "挖", "p": p})
            if 名:
                # 挖下来的东西掉地上没人捡 → 下一步「合成木板」报「要工作台」。
                # 走过去会自动吸附，再补一步「拾」兜底。
                步骤.append({"动作": "拾", "物品": 挖了掉什么(名), "数量": 1})
            continue

        if 动 == "放":
            位 = 我的位置()
            if 位 is None:
                缺.append(f"放 {步.get('方块')}：状态帧里没有我自己的坐标")
                continue
            # ★★ 2026-10-07 实机翻车 + 主人一句点醒：
            #   原来放「我自己站的那格」—— 可 MC 不许把方块放在自己占着的那格上。
            #   改成**问雷达**：身边 4 格哪格是 air 就放哪格。
            空, 没读数 = 身边空位(状态, 位)
            if 空:
                放位 = 空[0]
            elif 没读数:
                return None, (f"雷达还没盯我身边那 {len(没读数)} 格"
                              f"（放{步.get('方块')}要先知道旁边哪格是空的）")
            else:
                放位 = [位[0] + 1, 位[1], 位[2]]      # 四周全堵着 → 先挖开一格
                步骤.append({"动作": "挖", "p": list(放位)})
            步骤.append({"动作": "放", "p": 放位, "方块": 步.get("方块")})
            if "furnace" in str(步.get("方块") or ""):
                炉位 = list(放位)
            continue

        if 动 in ("烧炼", "高炉"):
            if 炉位 is None:
                return None, "计划里要烧东西，可前面没有「放炉子」那一步 —— 我不敢乱烧"
            料 = 步.get("料") or {}
            if len(料) != 1:
                return None, f"这一步要同时烧 {len(料)} 种原料，我现在只支持一种"
            原, 数 = next(iter(料.items()))
            燃 = 步.get("燃料") or {}
            # 手侧要求离炉子 **4.5 格内**才能放料/取货 —— 所以先走过去
            步骤.append({"动作": "走到", "p": list(炉位), "到点": 2.5})
            步骤.append({"动作": "熔炉放料", "p": list(炉位),
                        "输入": {"name": 原, "count": int(数)},
                        "燃料": {"name": 燃.get("物品"),
                               "count": int(燃.get("数量") or 1)}})
            # 取成品那一步自带「等它烧完」—— 主链的完成判据是
            # 「背包里这个物品够了没」，没够就一直等，不用我再插等待
            步骤.append({"动作": "熔炉取成品", "p": list(炉位),
                        "物品": 步.get("物品"), "数量": int(步.get("数量") or 1)})
            continue

        if 动 in ("烟熏", "营火", "切石", "锻造"):
            return None, f"这一步要「{动}」（加工 {步.get('物品')}）—— 这一支还没接线"

        if 动 == "走到":
            p, 因 = 找坐标(步, 状态, 扫)
            if p is None:
                缺.append(f"走到 {步.get('目标方块')}：{因}")
                continue
            步骤.append({"动作": "走到", "p": p, "到点": 2.5})
            continue

        return None, f"计划里有我不认识的动作「{动}」"

    if 缺:
        统计["定位失败"] += 1
        return None, "定位不到这些目标：\n  · " + "\n  · ".join(缺[:4])
    return 步骤, None


