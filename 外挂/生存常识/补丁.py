def 补拼音(文):
    """拼音 → 汉字（只换认识的词，别的一个字不动）。"""
    出 = str(文 or "").lower()
    for 拼, 汉 in 拼音表:
        出 = 出.replace(拼, 汉)
    return 出


def 认口令(最久前=90.0):
    """主人刚说的话里有没有「造 XX / 做 XX / 给我来个 XX」→ 直接给物品名。

    ★ 聊天那条路上大模型**十次有九次只回白话**，一个 `意图` 字段都不吐 ——
      光答应不干活。这里本地直接接单。
    """
    原 = str(_上次原话.get("原话") or "").strip()
    原 = 补拼音(原)      # ★ 拼音也认（主人打不出中文，这是他实际能敲的东西）
    if not 原:
        return None
    if time.time() - float(_上次原话.get("时刻") or 0) > 最久前:
        return None
    if not any(w in 原 for w in 造词):
        return None
    表 = _名字表()
    return 认物品(原, 表) if 表 else None


def 认意图(解析):
    """从模型输出里认出「这是一个意图」。不是意图就返回 None。"""
    if not isinstance(解析, dict):
        return None
    for 键 in ("意图", "intent", "要", "想要"):
        if 键 in 解析:
            意图 = str(解析.get(键) or "")
            目标 = 解析.get("目标") or 解析.get("item") or 解析.get("物件")
            if 目标:
                return str(目标)
            if 意图 and 意图 not in 意图名:
                # 「意图」字段直接写了物品名（模型常见写法）
                return 意图
    return None


