def _记账(译, 用途, 目标, 原因, 结果="常识推演后定位失败"):
    """把车厢自己的结论写进 LLM 审计。

    ★★★ 2026-10-08 对齐协议：**强类型断言 —— 缺字段直接报错，不准静默**。
       上一版这里是 `except Exception: pass`：我把 `_记账(...)` 那行弄丢以后，
       「定位失败」的原因**整整一个下午不落日志**，我全靠猜 ✗
       这就是 T2「静默失败」本人 —— 所以这里改成 fail-loud：
         · 缺字段 / 空白   → **抛 ValueError**
         · 原因不是字符串   → **抛 TypeError**
         · 写不进审计       → **出声报**（不再吞）
    """
    字段 = {"用途": 用途, "结果": 结果, "目标": 目标, "原因": str(原因)[:300]}
    坏 = [k for k, v in 字段.items() if v is None or (isinstance(v, str) and not v.strip())]
    if 坏:
        raise ValueError(f"_记账 缺字段：{'、'.join(坏)}（整包：{字段}）")
    if 原因 is not None and not isinstance(原因, str) and not isinstance(原因, (list, tuple)):
        raise TypeError(f"_记账 的「原因」得是字符串/列表，拿到 {type(原因).__name__}")
    写不进去 = None
    try:
        译._记账(字段)
    except Exception as e:                     # noqa: BLE001 —— 但**必须出声**
        写不进去 = f"{type(e).__name__}: {e}"
    if 写不进去:
        _报(f"★ _记账 写不进审计：{写不进去} ｜ 本来要记：{字段}")
    return 写不进去


def _背包(s):
    """从状态帧里读背包 → {物品名: 个数}。

    ★★ 2026-10-07 主人当场抓到的 bug：
       状态帧里这个字段叫 **`items`**（`bridge.py:1657` 的 `_物品数量` 读的就是它），
       我原来写的 `inv` / `背包` **一个都不存在** —— 于是车厢**永远以为自己是空手**。
       主人把工具塞给它了，它照样从零开始盘算「撸树→木镐→…」，
       在石山上找不到木头，就一直出去找、永远不挖矿。

    ⚠ 而且 `items` **只在「被盯梢的物品」里才有**：手侧的 `物品快照()` 只报
      `看的物品` 名单里的东西，而主链平时不盯背包（`_挂探针` 开始盯、
      `_撤探针` 就清空）。所以光改字段名还不够 —— 还得让它**一直盯着全量**，
      见 `_盯背包()`。
    """
    物 = (s or {}).get("items")
    出 = {}
    if isinstance(物, dict):
        for k, v in 物.items():
            try:
                出[str(k)] = int(v or 0)
            except (TypeError, ValueError):
                pass
    elif isinstance(物, list):        # 兼容别的写法
        for 条 in 物:
            if isinstance(条, dict) and 条.get("name"):
                出[条["name"]] = int(条.get("count") or 1)
    return {k: v for k, v in 出.items() if v}


def _盯背包(实例):
    """让手侧**一直**报背包全量（`*` = 所有物品）。"""
    if 实例 is None:
        return False
    try:
        实例.发({"cmd": "watch_items", "list": ["*"]})
        return True
    except Exception:
        return False


def _补盯背包(bridge):
    """包一层 `任务栈._撤探针`：主链清空盯梢之后，我们**顺手再把背包盯回来**。

    ★ 不这么做的话，每做完一个任务背包就看不见了 —— 而车厢恰恰是在
      「没任务」的时候（心跳）才被问话，也就是**永远看不见**。
    """
    栈类 = getattr(bridge, "任务栈", None)
    if 栈类 is None or not callable(getattr(栈类, "_撤探针", None)):
        return None
    # ★★★ 2026-10-08 实机总根（背包那一半）：
    #   手侧的 `watch_items` 是「**最后发的那个说了算**」—— 主链接单时发的是
    #   「只盯 oak_log」（任务里 拾 那步要的），把车厢的 `["*"]`（全量）**覆盖掉了** ✗
    #   于是背包快照只有 `{oak_log: 0}` → 车厢过滤掉 0 → **空背包** →
    #   求解器以为它一无所有 → 走「出去找」→ 拐去「挖阶梯上地表」。
    #   规矩：**每次挂探针都顺手把全量 `*` 补上**（后发的说了算，那就最后发）。
    if callable(getattr(栈类, "_挂探针", None)):
        _原["_挂探针"] = 栈类._挂探针

        def 新挂探针(self, 步骤, s):
            r = _原["_挂探针"](self, 步骤, s)
            try:
                self.发({"cmd": "watch_items", "list": ["*"]})
            except Exception as e:
                _报(f"补盯全量背包没发出去：{e}")
            return r

        栈类._挂探针 = 新挂探针
        _报("挂探针包壳装上了：接单时会把背包全量补盯上（不然主链只盯任务要的那几样）")

    _原["_撤探针"] = 栈类._撤探针

    def 新撤探针(self):
        r = _原["_撤探针"](self)
        _盯背包(self)          # 清完立刻盯回来
        return r

    栈类._撤探针 = 新撤探针
    return "任务栈._撤探针()  ← 清完盯梢顺手把背包盯回来（不然看不见主人的工具）"


