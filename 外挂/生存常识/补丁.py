# 意图词 → 常识库要的「目标物品」。**这是一张小对照表，不是配方表。**
意图名 = {
    "取物": "目标", "要": "目标", "拿": "目标", "做": "目标",
    "挖矿": "目标", "采集": "目标", "合成": "目标",
}


def 认意图(解析):
    """从模型输出里认出「这是一个意图」。不是意图就返回 None。"""
    if not isinstance(解析, dict):
        return None
    for 键 in ("意图", "intent", "要", "想要"):
        if 键 in 解析:
            意图 = str(解析.get(键) or "")
            目标 = 解析.get("目标") or 解析.get("item") or 解析.get("物件")
            if 目标:
                return str(目标)
            if 意图 and 意图 not in 意图名:
                # 「意图」字段直接写了物品名（模型常见写法）
                return 意图
    return None


# ══════════════════════════ 装上 / 卸下 ══════════════════════════

def 装上(bridge, 开关=True, 车钩=None, 日志=None):
    global _已装, _主链, _记
    if not 开关:
        return {"好": False, "打了": [],
                "为什么": "开关关着 —— 一个补丁都不打（行为与基线逐字节相同）"}
    if _已装 or getattr(bridge, "_生存常识外挂", None):
        return {"好": False, "打了": [], "为什么": "已经打过了，不重复打"}
    _主链, _记 = bridge, 日志
    try:
        import 求解器 as _求解器          # noqa: F401
    except Exception as e:
        return {"好": False, "打了": [],
                "为什么": f"常识库读不了（{type(e).__name__}: {e}）—— 拒绝打补丁"}

    译 = getattr(bridge, "翻译器", None)
    if 译 is None or not callable(getattr(译, "收输出", None)):
        return {"好": False, "打了": [], "为什么": "主链上没有 翻译器.收输出()"}

    _原["收输出"] = 译.收输出

    def 新收输出(self, 文本, s, 用途="翻译"):
        # 先让里面那层按老规矩做（严格 JSON、宪法检查、字段体检……）
        动作, 任务, 原因 = _原["收输出"](self, 文本, s, 用途=用途)
        # ★ 老路子**成了**就原样放行 —— 一个字不动
        #   （任务书、单步动作都走这条，宪法检查、字段体检全在里头）
        if 任务 is not None or 动作 is not None:
            return 动作, 任务, 原因
        # ★ 老路子**没成**，才轮到问一句：它是「意图」吗？
        #   （第一版写成「有理由就早退」，于是意图被那句
        #     「没有 act 字段」的拒绝理由**饿死在门口**，整条路根本走不到。
        #     2026-10-07 被测试当场抓到。）

        # ★ 走这儿 = 模型给的不是任务书、也不是单步动作 —— 那它是不是「意图」？
        import json as _json
        原文 = str(文本 or "").strip()
        if not (原文.startswith("{") and 原文.endswith("}")):
            return 动作, 任务, 原因
        try:
            解析 = _json.loads(原文)
        except Exception:
            return 动作, 任务, 原因
        目标 = 认意图(解析)
        if not 目标:
            return 动作, 任务, 原因

        统计["接到意图"] += 1
        _说(f"生存常识：接到意图「要 {目标}」—— 本地推演，不请示大模型")
        import 求解器
        r = 求解器.求解(目标, 1, 背包=_背包(s), 方块在哪=可用方块(s))
        if not r["好"]:
            统计["推演失败"] += 1
            _说(f"生存常识：推演不出来 —— {r['为什么']}")
            self.说(f"[{time.strftime('%H:%M')}] 「{目标}」我做不到：{r['为什么']}",
                   紧急=True)
            return None, None, f"常识推演说做不到：{r['为什么']}"

        步骤, 因 = 落坐标(r["计划"], s)
        if 步骤 is None:
            统计["定位失败"] += 1
            _记账(self, 用途, 目标, 因)
            # ★★ 如果卡的是「周围压根没有某个方块」—— 别站那儿干等，
            #    **自己出门找**。按心跳一趟一趟走，边走边等新扫描。
            缺的 = [x.get("目标方块") for x in r["计划"]
                  if x.get("动作") == "挖" and x.get("目标方块")]
            缺的 = [x for x in 缺的 if f"压根没有「{x}」" in str(因)]
            if 缺的:
                探, 说明 = 安排一趟探索(目标, s, 缺的)
                if 探:
                    统计["出去找"] = 统计.get("出去找", 0) + 1
                    _说(f"生存常识：{说明}")
                    try:
                        self.说(f"[{time.strftime('%H:%M')}] {说明}", 紧急=True)
                    except Exception:
                        pass
                    _记账(self, 用途, 目标, 说明)
                    return None, {"名字": f"常识：出去找 {目标}",
                                 "为什么": 说明, "步骤": 探}, None
            _说(f"生存常识：推演出来了，但定位不到目标 —— {因}")
            self.说(f"[{time.strftime('%H:%M')}] 我知道怎么做「{目标}」，"
                    f"可我看不见要挖的东西：{因}", 紧急=True)
            return None, None, f"定位不到：{因}"

        # ★★ 到**这一步**才算真成了，才清探索的账。
        #    原来写在「推演成功」那一刻 —— 可推演成功 ≠ 坐标解析成功，
        #    于是每轮心跳都先清账、再发现定位失败、再安排「第 1 趟」……
        #    实测就是这样：永远朝东走、永远「第 1 趟」，原地打转。
        #    （2026-10-07 实机日志：连着两轮都是「朝东走 16 格（第 1 趟）」。）
        清探索(目标)
        统计["推演成功"] += 1
        _说(f"生存常识：推演出 {len(步骤)} 步")
        for i, 步 in enumerate(步骤, 1):
            _说(f"  {i:2d}. {步.get('动作')} {步.get('物品') or 步.get('块') or 步.get('p')}")
        return None, {"名字": f"常识：{目标}", "为什么": "本地依赖树推的",
                     "步骤": 步骤}, None

    # 类属性？不 —— `bridge.翻译器` 拿到的是**类本身**
    译.收输出 = 新收输出
    打 = ["翻译器.收输出()  ← 认得「意图」，本地推演成步骤表"]
    p = _装提示词(bridge)
    if p:
        打.append(p)
    else:
        打.append("⚠ 翻译器.组Prompt() 没找到 —— 提示词没换，模型还会写步骤")
    bridge._生存常识外挂 = True
    _已装 = True
    return {"好": True, "为什么": "", "打了": 打}


def _记账(译, 用途, 目标, 原因):
    """把车厢自己的结论也写进 LLM 审计 —— 不然审计里只有里面那层
    「没有 act 字段」，看不出真正发生了什么。"""
    try:
        译._记账({"用途": 用途, "结果": "常识推演后定位失败",
                "目标": 目标, "原因": str(原因)[:300]})
    except Exception:
        pass


def _背包(s):
    """从状态帧里读背包 → {物品名: 个数}。读不到就给空（求解器会从头推）。"""
    物 = (s or {}).get("inv") or (s or {}).get("背包") or []
    出 = {}
    if isinstance(物, list):
        for 条 in 物:
            if isinstance(条, dict) and 条.get("name"):
                出[条["name"]] = int(条.get("count") or 1)
    elif isinstance(物, dict):
        for k, v in 物.items():
            出[str(k)] = int(v or 1)
    return 出


def 卸下(bridge):
    global _已装
    if not _已装:
        return False
    译 = getattr(bridge, "翻译器", None)
    if 译 is not None:
        if "收输出" in _原:
            译.收输出 = _原["收输出"]
        if "组Prompt" in _原组:
            译.组Prompt = _原组["组Prompt"]
        if "组Prompt" in _原:
            译.组Prompt = _原["组Prompt"]
    _原.clear()
    _原组.clear()
    if hasattr(bridge, "_生存常识外挂"):
        del bridge._生存常识外挂
    _已装 = False
    return True


# ══════════════════════════ 同步实例（车钩的可选钩子） ══════════════════════════

def 同步实例(bridge, 日志=None, 车钩=None):
    """热插拔不丢任务进度 —— 主人点名的红线。

    ┌───────────────────────────────────────────────────────────────┐
    │ 本车厢为什么**天生**不会丢进度                                 │
    └───────────────────────────────────────────────────────────────┘
    因为它**不缓存任何跟任务进度有关的东西**。分工是这样的：

        推演     ← 本车厢（无状态：给个意图就现推，毫秒级）
        执行进度 ← **主链的任务栈实例**（`实例.任务` 里的「第几步」）

    所以摘掉再挂上，跑着的活儿一点不受影响 —— 进度根本不在我这儿。
    ★ 这正是「无状态车厢」的好处，也是为什么 同步实例() 只需要**看一眼**，
      而不需要往回灌任何东西。

    但有个坑要防：**本车厢要是被摘掉，一个正在跑的常识任务就没人管了**吗？
    不会 —— 任务已经交给主链的任务栈了，任务栈自己会往下跑。
    本车厢只是「下单的人」，不是「监工」。

    所以这个钩子只做两件事：
      ① 看一眼现在有没有常识任务在跑（给日志/体检用）
      ② 顺手清理已经结束的任务留下的痕迹
    """
    try:
        活 = []
        if 车钩 is not None:
            活 = 车钩.活实例("任务栈")
        if not 活 and 日志:
            日志("  · 生存常识.同步实例：摸不到活的任务栈实例（不影响执行）")
        for 实例 in 活:
            任 = getattr(实例, "任务", None)
            if not 任:
                continue
            名 = str(任.get("名字") or "")
            if 名.startswith("常识："):
                统计["在跑"] = {"名字": 名, "第几步": 任.get("第几步"),
                              "共几步": len(任.get("步骤") or []),
                              "状态": 任.get("状态")}
                if 日志:
                    日志(f"  ⟳ 生存常识.同步实例：手上这条「{名}」跑到第 "
                        f"{任.get('第几步')} / {len(任.get('步骤') or [])} 步"
                        f"（状态 {任.get('状态')}）—— 进度在主链里，我没丢任何东西")
    except Exception as e:
        if 日志:
            日志(f"  ⚠ 生存常识.同步实例 出错：{type(e).__name__}: {e}")
    return 0


def 报个话(bridge):
    return {"装上": _已装, "统计": dict(统计),
            "记号": bool(getattr(bridge, "_生存常识外挂", None))}


# ══════════════════════════ 提示词：把 L2 降级成「翻译器」 ══════════════════════════
#
# 2026-10-07 补上的一块拼图。在此之前提示词还在教模型**写步骤**：
#
#     【你要输出的东西】② 给自己定个小目标 → {"任务":{"名字":"…","步骤":[…],…}}
#     【任务书的步骤类型】走到(p=[x,y,z]) / 挖(p) / …
#
# 那是「模型当大脑」的老架构。主人定的新架构里，**模型不该碰步骤**：
# 它只管「听」（把话变成意图）和「说」（把状态说成人话），
# 前置条件、配方、工具等级全部由本地常识库推。
#
# 所以这里往 prompt 后面追加一段，告诉它改用「意图」说话。

意图说明 = """

【★ 重要变化：不要再写步骤了，改用「意图」】
从今天起，**你不需要写步骤、不需要背配方、不需要算前置条件** ——
那些是本地常识库的活。你只要说清楚「想要什么」，本地会自己推演出整条链
（该先做什么工具、要挖什么、要几个、怎么合成，全自动）。

    想让它做一把石镐   →  {"意图":"要","目标":"stone_pickaxe"}
    想让它弄点铁锭     →  {"意图":"要","目标":"iron_ingot"}
    想让它弄点木头     →  {"意图":"要","目标":"oak_log"}
    想让它做把钻石镐   →  {"意图":"要","目标":"diamond_pickaxe"}

「目标」写**物品的英文名**（stone_pickaxe / iron_pickaxe / diamond /
oak_planks / torch …）。不知道英文名就先用汉语说给我听，我会告诉你。

★ 别写步骤、别写坐标、别写配料表 —— 写了也是白写，本地不吃那一套。
★ 目标必须是**它够得着的**：本地推不出来会当场告诉你「做不到」，
  不会硬来。够不着就换个目标，或者先给它弄把工具。
"""

_原组 = {}


def _装提示词(bridge):
    """追加「用意图说话」那一段。包壳，先调里面那层。"""
    译 = getattr(bridge, "翻译器", None)
    if 译 is None or not callable(getattr(译, "组Prompt", None)):
        return None
    _原组["组Prompt"] = 译.组Prompt

    def 新组Prompt(self, s, 用途="翻译", 任务状况="没有任务", 说话人=None, 原话=None):
        文 = _原组["组Prompt"](self, s, 用途=用途, 任务状况=任务状况,
                             说话人=说话人, 原话=原话)
        if not isinstance(文, str):
            return 文
        return 文 + 意图说明

    译.组Prompt = 新组Prompt
    return "翻译器.组Prompt()  ← 追加「用意图说话，别写步骤」（包壳）"
