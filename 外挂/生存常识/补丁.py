# ══════════════════════════ 点位解析 ══════════════════════════

# 状态帧里能拿到坐标的只有 scan.可交互（手侧那份「兴趣方块」名单）
def 扫描表(状态):
    """把状态帧里的扫描结果整理成 {方块名: [x,y,z]}。同一个方块取第一条。"""
    扫 = (状态 or {}).get("scan") or {}
    表 = {}
    for 条 in (扫.get("可交互") or []):
        if not isinstance(条, dict):
            continue
        名, p = 条.get("name"), 条.get("p")
        if 名 and isinstance(p, (list, tuple)) and len(p) >= 3:
            表.setdefault(名, [int(p[0]), int(p[1]), int(p[2])])
    return 表


def 可用方块(状态):
    """**给求解器看的「附近有什么」** = 扫描报的 + 脚下那块。

    ★ 为什么要加脚下那块：求解器只认 `方块在哪` 这张表。如果只喂扫描结果，
      它不知道「石头就在我脚下」，于是 `#stone_tool_materials` 这个标签里
      它会挑中 `blackstone`（字母序靠前、难度并列）—— 而黑石在下界。
      把脚下那块加进去，它就会正确地挑 `cobblestone`。
    """
    表 = 扫描表(状态)
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 and 脚位:
        表.setdefault(脚名, 脚位)
    return 表


def 脚下是什么(状态):
    """我正踩着的是什么方块 —— 扫描的「地面」字段，配合已知的自身坐标。

    这是**唯一一处能"免费"拿到坐标的方块**：不用扫描给，位置就是
    `[floor(x), floor(y)-1, floor(z)]`，而自身坐标是状态帧里每拍都有的。
    """
    扫 = (状态 or {}).get("scan") or {}
    名 = 扫.get("地面")
    if not 名:
        return None, None
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return 名, None
    return 名, [int(我[0] // 1), int(我[1]) - 1, int(我[2] // 1)]


def 找坐标(步骤, 状态, 扫描缓存, 要挖吗=False):
    """一个符号化步骤 → 具体坐标。找不到返回 (None, 原因)。"""
    方块 = 步骤.get("目标方块") or 步骤.get("方块")
    if not 方块:
        return None, "这一步没说要找哪个方块"

    # ① 扫描里有就直接用
    if 方块 in 扫描缓存:
        return 扫描缓存[方块], None

    # ② 它是不是我**正脚下**那块？—— 地面字段 + 自身坐标 = 免费定位
    #
    #   ⚠ 但「挖」不能用这个位置：手侧 `挖()` 有一条安全护栏
    #     （`node/plugins/body/proto_body.js:216`）——
    #     **不许挖自己正脚下那块**，理由是「挖了我自己就掉下去了」。
    #     所以这里必须分开：能定位 ≠ 能挖。
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 == 方块 and 脚位:
        if 要挖吗:
            return None, (f"我正站在「{方块}」上，可手侧不许我挖自己脚下那块"
                        f"（挖了我自己就掉下去）；扫描里又没报别的「{方块}」位置")
        return 脚位, None

    # ③ 定位不到 —— **明确失败，绝不猜**。而且要说清楚是哪一种「找不到」：
    #    「压根没有」和「有但没报位置」对主人来说是完全不同的两件事。
    扫 = (状态 or {}).get("scan") or {}
    见过的 = {b.get("name") for b in (扫.get("方块") or []) if isinstance(b, dict)}
    贴身的 = {b.get("name") for b in (扫.get("可交互") or []) if isinstance(b, dict)}
    if 方块 not in 见过的 and 方块 not in 贴身的:
        return None, (f"**我周围压根没有「{方块}」** —— 扫描看到的只有 "
                    f"{'、'.join(sorted(x for x in 见过的 if x)[:6]) or '（一片空）'}。"
                    f"得先走到有它的地方去。")
    return None, (f"我周围有「{方块}」，可手侧只上报「兴趣方块」的坐标，"
                f"它不在那份名单里 —— 我不会瞎挖一个坐标。")


# ══════════════════════════ 计划 → 具体步骤 ══════════════════════════

# 主链 任务栈 认的动作名。计划里的「烧炼/高炉/切石/锻造」这些**暂时不接**
# （要接得先给任务栈加动作 + 手侧有对应命令，那是下一节车厢的事）。
_动作名 = {"挖": "挖", "放": "放", "合成": "合成", "走到": "走到"}


def 落坐标(计划, 状态):
    """符号化计划 → 具体步骤表。返回 (步骤表, 失败原因)。

    ★ 熔炼那一支是 2026-10-07 接上的：手侧**早就有** `furnace_put` /
      `furnace_take` 两个命令，主链**早就认** `熔炉放料` / `熔炉取成品`
      两个动作（`bridge.py:1348` 里甚至有现成的用法示例）。
      所以这一段**一行主链都不用改**，只是把常识库的「烧炼」翻译过去。
    """
    扫 = 扫描表(状态)
    步骤, 缺 = [], []
    炉位 = None                      # 放炉子那一刻的位置，后面烧东西要用
    # 脚下那块：`地面` 字段给名字，自身坐标给位置 —— 这是**唯一**
    # 不用扫描报坐标就能确定位置的方块（而且不是猜的）。
    脚名, 脚位 = 脚下是什么(状态)

    def 我的位置():
        我 = (状态 or {}).get("pos")
        if isinstance(我, (list, tuple)) and len(我) >= 3:
            return [int(我[0] // 1), int(我[1]), int(我[2] // 1)]
        return None

    for 步 in 计划:
        动 = 步.get("动作")

        if 动 == "合成":
            步骤.append({"动作": "合成", "物品": 步.get("物品"),
                        "数量": 步.get("数量") or 1})
            continue

        if 动 == "挖":
            名 = 步.get("目标方块")
            p, 因 = 找坐标(步, 状态, 扫, 要挖吗=True)
            if p is None and 名 and 名 == 脚名 and 脚位:
                # ★★ 2026-10-07 想通的零改动解法：**不用找，脚下的就已经知道了。**
                #
                #   手侧的 `地面` 字段告诉我们「我踩着的就是 X」，而自身坐标每拍都有
                #   → **脚下那块 X 的坐标是确定无疑的**（不是猜的）。
                #   唯一的麻烦是手侧护栏不许挖「正脚下那块」（挖了自己就掉下去）。
                #
                #   那就**先挪开一格，再挖原来那格**。
                #   挪开之后它就不再是脚下那块了，护栏自然放行；
                #   而且主链的 `_挂探针()` 会把这一格报回来，完成判据也走得通。
                #
                #   ⚠ 这不是"猜一个坐标去挖" —— 坐标是从「地面字段 + 自身坐标」
                #     推出来的**事实**，只是需要先让开一步。
                我 = 我的位置()
                if 我:
                    旁边 = [我[0] + 1, 我[1], 我[2]]
                    步骤.append({"动作": "走到", "p": 旁边, "到点": 1.5})
                    步骤.append({"动作": "挖", "p": list(脚位)})
                    _说(f"  · 挖 {名}：它就在我脚下 —— 先挪开一格再挖（不猜坐标）")
                    continue
            if p is None:
                缺.append(f"挖 {名}：{因}")
                continue
            步骤.append({"动作": "挖", "p": p})
            continue

        if 动 == "放":
            位 = 我的位置()
            if 位 is None:
                缺.append(f"放 {步.get('方块')}：状态帧里没有我自己的坐标")
                continue
            # ⚠ 手侧的 放() 要求**目标格是空气**（它再挑一个实心邻面当参考）。
            #   「我自己站的那格」是我唯一**确定**是空气的位置，
            #   所以先放这儿 —— 实机可能要挪一格，那属于现场校准。
            步骤.append({"动作": "放", "p": 位, "方块": 步.get("方块")})
            if "furnace" in str(步.get("方块") or ""):
                炉位 = list(位)
            continue

        if 动 in ("烧炼", "高炉"):
            if 炉位 is None:
                return None, "计划里要烧东西，可前面没有「放炉子」那一步 —— 我不敢乱烧"
            料 = 步.get("料") or {}
            if len(料) != 1:
                return None, f"这一步要同时烧 {len(料)} 种原料，我现在只支持一种"
            原, 数 = next(iter(料.items()))
            燃 = 步.get("燃料") or {}
            # 手侧要求离炉子 **4.5 格内**才能放料/取货 —— 所以先走过去
            步骤.append({"动作": "走到", "p": list(炉位), "到点": 2.5})
            步骤.append({"动作": "熔炉放料", "p": list(炉位),
                        "输入": {"name": 原, "count": int(数)},
                        "燃料": {"name": 燃.get("物品"),
                               "count": int(燃.get("数量") or 1)}})
            # 取成品那一步自带「等它烧完」—— 主链的完成判据是
            # 「背包里这个物品够了没」，没够就一直等，不用我再插等待
            步骤.append({"动作": "熔炉取成品", "p": list(炉位),
                        "物品": 步.get("物品"), "数量": int(步.get("数量") or 1)})
            continue

        if 动 in ("烟熏", "营火", "切石", "锻造"):
            return None, f"这一步要「{动}」（加工 {步.get('物品')}）—— 这一支还没接线"

        if 动 == "走到":
            p, 因 = 找坐标(步, 状态, 扫)
            if p is None:
                缺.append(f"走到 {步.get('目标方块')}：{因}")
                continue
            步骤.append({"动作": "走到", "p": p, "到点": 2.5})
            continue

        return None, f"计划里有我不认识的动作「{动}」"

    if 缺:
        统计["定位失败"] += 1
        return None, "定位不到这些目标：\n  · " + "\n  · ".join(缺[:4])
    return 步骤, None


# ══════════════════════════ 探索：目标搜不到就自己出门找 ══════════════════════════
#
# 2026-10-07 实机：小家伙在地下/石山，周围一块木头都没有（扫描只有石头、铜矿、水）。
# 它已经能**说清楚**「我周围压根没有 acacia_log」，但**不会自己去找** ——
# 那时它只会站在那儿重复报了。这就是「陌生环境下自己推进科技树」缺的最后一环。
#
# 设计：**按心跳分段走**。
#   本车厢记住「我在找什么、从哪儿出发、朝哪个方向试过几趟」；
#   每次被问起（心跳约 60 秒一次）就走一段、同时等新扫描；
#   一看见目标，立刻转成完整计划。
#   ★ 不需要每个 tick 的钩子 —— 借用现有心跳的节奏就够了。
#   ★ 走之前会看 `scan.危险`：那个方向有岩浆/火就换一个方向。

方位表 = [(1, 0, "东"), (0, 1, "南"), (-1, 0, "西"), (0, -1, "北"),
        (1, 1, "东南"), (-1, 1, "西南"), (-1, -1, "西北"), (1, -1, "东北")]

每趟走多远 = 16          # 一格一格挪太慢，一趟走 16 格
危险范围 = 12            # 这个距离内有岩浆/火，就别往那边走

探索状态 = {}            # {目标方块: {"起点": [x,y,z], "试过": n}}


def 清探索(目标方块=None):
    if 目标方块 is None:
        探索状态.clear()
    else:
        探索状态.pop(目标方块, None)


def 安排一趟探索(目标方块, 状态, 缺的方块名):
    """目标方块搜不到 → 安排一趟「出去找」。返回 (步骤表, 说明) 或 (None, 原因)。"""
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return None, "状态帧里没有我自己的坐标，我不敢乱走"
    我 = [int(我[0] // 1), int(我[1]), int(我[2] // 1)]

    扫 = (状态 or {}).get("scan") or {}
    险 = []
    for d in (扫.get("危险") or []):
        p = d.get("p")
        if isinstance(p, (list, tuple)) and len(p) >= 3:
            险.append((int(p[0]), int(p[2]), str(d.get("name") or "危险")))

    记 = 探索状态.setdefault(目标方块, {"起点": list(我), "试过": 0})
    起 = 记.get("起点") or 我
    if not 记.get("起点"):
        记["起点"] = list(我)

    # 从「下一趟该走的方向」开始，顺时针找一个**路上没有危险**的
    总 = len(方位表)
    for 偏移 in range(总):
        号 = (记["试过"] + 偏移) % 总
        dx, dz, 名 = 方位表[号]
        终点 = [起[0] + dx * 每趟走多远, 起[1], 起[2] + dz * 每趟走多远]
        挡路 = [x for (x, z, n) in 险
               if (min(起[0], 终点[0]) - 危险范围 <= x <= max(起[0], 终点[0]) + 危险范围
                   and min(起[2], 终点[2]) - 危险范围 <= z <= max(起[2], 终点[2]) + 危险范围)]
        if 挡路:
            continue
        记["试过"] = 号 + 1
        记["上次终点"] = 终点
        步骤 = [{"动作": "走到", "p": 终点, "到点": 2.5}]
        # 去重 —— 一条链上同一个方块会被列好几次，念出来像结巴
        去重 = []
        for x in 缺的方块名:
            if x not in 去重:
                去重.append(x)
        return 步骤, (f"周围没有{'、'.join(去重[:3])} —— "
                   f"我朝**{名}**走 {每趟走多远} 格去找找（第 {记['试过']} 趟）")

    return None, (f"周围找不到目标，而且八个方向**都有危险**（"
                f"{'、'.join(n for _, _, n in 险[:3])}）—— 我不敢乱走，请主人带我过去")


