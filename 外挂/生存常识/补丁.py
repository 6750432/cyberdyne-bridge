    配方 = None
    for r in ((数.get("产物到配方") or {}).get(str(名)) or []):
        if r.get("方式") == "合成":
            配方 = r
            break
    if 配方 is None:
        return True, ""                      # 没配方就不管（烧炼什么的另说）
    缺 = []
    for 料, n in (配方.get("材料") or {}).items():
        要 = int(n) * max(int(要几个 or 1), 1)
