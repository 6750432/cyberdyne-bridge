统计 = {"接到意图": 0, "推演成功": 0, "推演失败": 0, "定位失败": 0}


def _说(文本):
    if _记:
        _记(文本, 屏幕=False)


# ══════════════════════════ 点位解析 ══════════════════════════

# 状态帧里能拿到坐标的只有 scan.可交互（手侧那份「兴趣方块」名单）
def 扫描表(状态):
    """把状态帧里的扫描结果整理成 {方块名: [x,y,z]}。同一个方块取第一条。"""
    扫 = (状态 or {}).get("scan") or {}
    表 = {}
    for 条 in (扫.get("可交互") or []):
        if not isinstance(条, dict):
            continue
        名, p = 条.get("name"), 条.get("p")
        if 名 and isinstance(p, (list, tuple)) and len(p) >= 3:
            表.setdefault(名, [int(p[0]), int(p[1]), int(p[2])])
    return 表


def 可用方块(状态):
    """**给求解器看的「附近有什么」** = 扫描报的 + 脚下那块。

    ★ 为什么要加脚下那块：求解器只认 `方块在哪` 这张表。如果只喂扫描结果，
      它不知道「石头就在我脚下」，于是 `#stone_tool_materials` 这个标签里
      它会挑中 `blackstone`（字母序靠前、难度并列）—— 而黑石在下界。
      把脚下那块加进去，它就会正确地挑 `cobblestone`。
    """
    表 = 扫描表(状态)
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 and 脚位:
        表.setdefault(脚名, 脚位)
    return 表


def 脚下是什么(状态):
    """我正踩着的是什么方块 —— 扫描的「地面」字段，配合已知的自身坐标。

    这是**唯一一处能"免费"拿到坐标的方块**：不用扫描给，位置就是
    `[floor(x), floor(y)-1, floor(z)]`，而自身坐标是状态帧里每拍都有的。
    """
    扫 = (状态 or {}).get("scan") or {}
    名 = 扫.get("地面")
    if not 名:
        return None, None
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return 名, None
    return 名, [int(我[0] // 1), int(我[1]) - 1, int(我[2] // 1)]


def 找坐标(步骤, 状态, 扫描缓存, 要挖吗=False):
    """一个符号化步骤 → 具体坐标。找不到返回 (None, 原因)。"""
    方块 = 步骤.get("目标方块") or 步骤.get("方块")
    if not 方块:
        return None, "这一步没说要找哪个方块"

    # ① 扫描里有就直接用
    if 方块 in 扫描缓存:
        return 扫描缓存[方块], None

    # ② 它是不是我**正脚下**那块？—— 地面字段 + 自身坐标 = 免费定位
    #
    #   ⚠ 但「挖」不能用这个位置：手侧 `挖()` 有一条安全护栏
    #     （`node/plugins/body/proto_body.js:216`）——
    #     **不许挖自己正脚下那块**，理由是「挖了我自己就掉下去了」。
    #     所以这里必须分开：能定位 ≠ 能挖。
    脚名, 脚位 = 脚下是什么(状态)
    if 脚名 == 方块 and 脚位:
        if 要挖吗:
            return None, (f"我正站在「{方块}」上，可手侧不许我挖自己脚下那块"
                        f"（挖了我自己就掉下去）；扫描里又没报别的「{方块}」位置")
        return 脚位, None

    # ③ 定位不到 —— **明确失败，绝不猜**
    return None, (f"扫描里没有「{方块}」的坐标（手侧只上报「兴趣方块」的位置，"
                f"「{方块}」不在那份名单里）。我不会瞎挖一个坐标。")


# ══════════════════════════ 计划 → 具体步骤 ══════════════════════════

# 主链 任务栈 认的动作名。计划里的「烧炼/高炉/切石/锻造」这些**暂时不接**
# （要接得先给任务栈加动作 + 手侧有对应命令，那是下一节车厢的事）。
_动作名 = {"挖": "挖", "放": "放", "合成": "合成", "走到": "走到"}


def 落坐标(计划, 状态):
    """符号化计划 → 具体步骤表。返回 (步骤表, 失败原因)。

    ★ 熔炼那一支是 2026-10-07 接上的：手侧**早就有** `furnace_put` /
      `furnace_take` 两个命令，主链**早就认** `熔炉放料` / `熔炉取成品`
      两个动作（`bridge.py:1348` 里甚至有现成的用法示例）。
      所以这一段**一行主链都不用改**，只是把常识库的「烧炼」翻译过去。
    """
    扫 = 扫描表(状态)
    步骤, 缺 = [], []
    炉位 = None                      # 放炉子那一刻的位置，后面烧东西要用
    # 脚下那块：`地面` 字段给名字，自身坐标给位置 —— 这是**唯一**
    # 不用扫描报坐标就能确定位置的方块（而且不是猜的）。
    脚名, 脚位 = 脚下是什么(状态)

    def 我的位置():
        我 = (状态 or {}).get("pos")
        if isinstance(我, (list, tuple)) and len(我) >= 3:
            return [int(我[0] // 1), int(我[1]), int(我[2] // 1)]
        return None

    for 步 in 计划:
        动 = 步.get("动作")

        if 动 == "合成":
            步骤.append({"动作": "合成", "物品": 步.get("物品"),
                        "数量": 步.get("数量") or 1})
            continue

        if 动 == "挖":
            名 = 步.get("目标方块")
            p, 因 = 找坐标(步, 状态, 扫, 要挖吗=True)
            if p is None and 名 and 名 == 脚名 and 脚位:
                # ★★ 2026-10-07 想通的零改动解法：**不用找，脚下的就已经知道了。**
                #
                #   手侧的 `地面` 字段告诉我们「我踩着的就是 X」，而自身坐标每拍都有
                #   → **脚下那块 X 的坐标是确定无疑的**（不是猜的）。
                #   唯一的麻烦是手侧护栏不许挖「正脚下那块」（挖了自己就掉下去）。
                #
                #   那就**先挪开一格，再挖原来那格**。
                #   挪开之后它就不再是脚下那块了，护栏自然放行；
                #   而且主链的 `_挂探针()` 会把这一格报回来，完成判据也走得通。
                #
                #   ⚠ 这不是"猜一个坐标去挖" —— 坐标是从「地面字段 + 自身坐标」
                #     推出来的**事实**，只是需要先让开一步。
                我 = 我的位置()
                if 我:
                    旁边 = [我[0] + 1, 我[1], 我[2]]
                    步骤.append({"动作": "走到", "p": 旁边, "到点": 1.5})
                    步骤.append({"动作": "挖", "p": list(脚位)})
                    _说(f"  · 挖 {名}：它就在我脚下 —— 先挪开一格再挖（不猜坐标）")
                    continue
            if p is None:
                缺.append(f"挖 {名}：{因}")
                continue
            步骤.append({"动作": "挖", "p": p})
            continue

        if 动 == "放":
            位 = 我的位置()
            if 位 is None:
                缺.append(f"放 {步.get('方块')}：状态帧里没有我自己的坐标")
                continue
            # ⚠ 手侧的 放() 要求**目标格是空气**（它再挑一个实心邻面当参考）。
            #   「我自己站的那格」是我唯一**确定**是空气的位置，
            #   所以先放这儿 —— 实机可能要挪一格，那属于现场校准。
            步骤.append({"动作": "放", "p": 位, "方块": 步.get("方块")})
            if "furnace" in str(步.get("方块") or ""):
                炉位 = list(位)
            continue

        if 动 in ("烧炼", "高炉"):
            if 炉位 is None:
                return None, "计划里要烧东西，可前面没有「放炉子」那一步 —— 我不敢乱烧"
            料 = 步.get("料") or {}
            if len(料) != 1:
                return None, f"这一步要同时烧 {len(料)} 种原料，我现在只支持一种"
            原, 数 = next(iter(料.items()))
            燃 = 步.get("燃料") or {}
            # 手侧要求离炉子 **4.5 格内**才能放料/取货 —— 所以先走过去
            步骤.append({"动作": "走到", "p": list(炉位), "到点": 2.5})
            步骤.append({"动作": "熔炉放料", "p": list(炉位),
                        "输入": {"name": 原, "count": int(数)},
                        "燃料": {"name": 燃.get("物品"),
                               "count": int(燃.get("数量") or 1)}})
            # 取成品那一步自带「等它烧完」—— 主链的完成判据是
            # 「背包里这个物品够了没」，没够就一直等，不用我再插等待
            步骤.append({"动作": "熔炉取成品", "p": list(炉位),
                        "物品": 步.get("物品"), "数量": int(步.get("数量") or 1)})
            continue

        if 动 in ("烟熏", "营火", "切石", "锻造"):
            return None, f"这一步要「{动}」（加工 {步.get('物品')}）—— 这一支还没接线"

        if 动 == "走到":
            p, 因 = 找坐标(步, 状态, 扫)
            if p is None:
                缺.append(f"走到 {步.get('目标方块')}：{因}")
                continue
            步骤.append({"动作": "走到", "p": p, "到点": 2.5})
            continue

        return None, f"计划里有我不认识的动作「{动}」"

    if 缺:
        统计["定位失败"] += 1
        return None, "定位不到这些目标：\n  · " + "\n  · ".join(缺[:4])
    return 步骤, None


# ══════════════════════════ 意图 → 计划 ══════════════════════════

# 意图词 → 常识库要的「目标物品」。**这是一张小对照表，不是配方表。**
意图名 = {
    "取物": "目标", "要": "目标", "拿": "目标", "做": "目标",
    "挖矿": "目标", "采集": "目标", "合成": "目标",
}


def 认意图(解析):
    """从模型输出里认出「这是一个意图」。不是意图就返回 None。"""
    if not isinstance(解析, dict):
        return None
    for 键 in ("意图", "intent", "要", "想要"):
        if 键 in 解析:
            意图 = str(解析.get(键) or "")
            目标 = 解析.get("目标") or 解析.get("item") or 解析.get("物件")
            if 目标:
                return str(目标)
            if 意图 and 意图 not in 意图名:
                # 「意图」字段直接写了物品名（模型常见写法）
                return 意图
    return None


# ══════════════════════════ 装上 / 卸下 ══════════════════════════

def 装上(bridge, 开关=True, 车钩=None, 日志=None):
    global _已装, _主链, _记
    if not 开关:
        return {"好": False, "打了": [],
                "为什么": "开关关着 —— 一个补丁都不打（行为与基线逐字节相同）"}
    if _已装 or getattr(bridge, "_生存常识外挂", None):
        return {"好": False, "打了": [], "为什么": "已经打过了，不重复打"}
    _主链, _记 = bridge, 日志
    try:
        import 求解器 as _求解器          # noqa: F401
    except Exception as e:
        return {"好": False, "打了": [],
                "为什么": f"常识库读不了（{type(e).__name__}: {e}）—— 拒绝打补丁"}

    译 = getattr(bridge, "翻译器", None)
    if 译 is None or not callable(getattr(译, "收输出", None)):
        return {"好": False, "打了": [], "为什么": "主链上没有 翻译器.收输出()"}

    _原["收输出"] = 译.收输出

    def 新收输出(self, 文本, s, 用途="翻译"):
        # 先让里面那层按老规矩做（严格 JSON、宪法检查、字段体检……）
        动作, 任务, 原因 = _原["收输出"](self, 文本, s, 用途=用途)
        # ★ 老路子**成了**就原样放行 —— 一个字不动
        #   （任务书、单步动作都走这条，宪法检查、字段体检全在里头）
        if 任务 is not None or 动作 is not None:
            return 动作, 任务, 原因
        # ★ 老路子**没成**，才轮到问一句：它是「意图」吗？
        #   （第一版写成「有理由就早退」，于是意图被那句
        #     「没有 act 字段」的拒绝理由**饿死在门口**，整条路根本走不到。
        #     2026-10-07 被测试当场抓到。）

        # ★ 走这儿 = 模型给的不是任务书、也不是单步动作 —— 那它是不是「意图」？
        import json as _json
        原文 = str(文本 or "").strip()
        if not (原文.startswith("{") and 原文.endswith("}")):
            return 动作, 任务, 原因
        try:
            解析 = _json.loads(原文)
        except Exception:
            return 动作, 任务, 原因
        目标 = 认意图(解析)
        if not 目标:
            return 动作, 任务, 原因

        统计["接到意图"] += 1
        _说(f"生存常识：接到意图「要 {目标}」—— 本地推演，不请示大模型")
        import 求解器
        r = 求解器.求解(目标, 1, 背包=_背包(s), 方块在哪=可用方块(s))
        if not r["好"]:
            统计["推演失败"] += 1
            _说(f"生存常识：推演不出来 —— {r['为什么']}")
            self.说(f"[{time.strftime('%H:%M')}] 「{目标}」我做不到：{r['为什么']}",
                   紧急=True)
            return None, None, f"常识推演说做不到：{r['为什么']}"

        步骤, 因 = 落坐标(r["计划"], s)
        if 步骤 is None:
            统计["定位失败"] += 1
            _说(f"生存常识：推演出来了，但定位不到目标 —— {因}")
            self.说(f"[{time.strftime('%H:%M')}] 我知道怎么做「{目标}」，"
                    f"可我看不见要挖的东西：{因}", 紧急=True)
            return None, None, f"定位不到：{因}"

        统计["推演成功"] += 1
        _说(f"生存常识：推演出 {len(步骤)} 步")
        for i, 步 in enumerate(步骤, 1):
            _说(f"  {i:2d}. {步.get('动作')} {步.get('物品') or 步.get('块') or 步.get('p')}")
        return None, {"名字": f"常识：{目标}", "为什么": "本地依赖树推的",
                     "步骤": 步骤}, None

    # 类属性？不 —— `bridge.翻译器` 拿到的是**类本身**
    译.收输出 = 新收输出
    bridge._生存常识外挂 = True
    _已装 = True
    return {"好": True, "为什么": "",
            "打了": ["翻译器.收输出()  ← 认得「意图」，本地推演成步骤表"]}


def _背包(s):
    """从状态帧里读背包 → {物品名: 个数}。读不到就给空（求解器会从头推）。"""
    物 = (s or {}).get("inv") or (s or {}).get("背包") or []
    出 = {}
    if isinstance(物, list):
        for 条 in 物:
            if isinstance(条, dict) and 条.get("name"):
                出[条["name"]] = int(条.get("count") or 1)
    elif isinstance(物, dict):
        for k, v in 物.items():
            出[str(k)] = int(v or 1)
    return 出


def 卸下(bridge):
    global _已装
    if not _已装:
        return False
    译 = getattr(bridge, "翻译器", None)
    if 译 is not None and "收输出" in _原:
        译.收输出 = _原["收输出"]
    _原.clear()
    if hasattr(bridge, "_生存常识外挂"):
        del bridge._生存常识外挂
    _已装 = False
    return True


# ══════════════════════════ 同步实例（车钩的可选钩子） ══════════════════════════

def 同步实例(bridge, 日志=None, 车钩=None):
    """热插拔不丢任务进度 —— 主人点名的红线。

    ┌───────────────────────────────────────────────────────────────┐
    │ 本车厢为什么**天生**不会丢进度                                 │
    └───────────────────────────────────────────────────────────────┘
    因为它**不缓存任何跟任务进度有关的东西**。分工是这样的：

        推演     ← 本车厢（无状态：给个意图就现推，毫秒级）
        执行进度 ← **主链的任务栈实例**（`实例.任务` 里的「第几步」）

    所以摘掉再挂上，跑着的活儿一点不受影响 —— 进度根本不在我这儿。
    ★ 这正是「无状态车厢」的好处，也是为什么 同步实例() 只需要**看一眼**，
      而不需要往回灌任何东西。

    但有个坑要防：**本车厢要是被摘掉，一个正在跑的常识任务就没人管了**吗？
    不会 —— 任务已经交给主链的任务栈了，任务栈自己会往下跑。
    本车厢只是「下单的人」，不是「监工」。

    所以这个钩子只做两件事：
      ① 看一眼现在有没有常识任务在跑（给日志/体检用）
      ② 顺手清理已经结束的任务留下的痕迹
    """
    try:
        活 = []
        if 车钩 is not None:
            活 = 车钩.活实例("任务栈")
        if not 活 and 日志:
            日志("  · 生存常识.同步实例：摸不到活的任务栈实例（不影响执行）")
        for 实例 in 活:
            任 = getattr(实例, "任务", None)
            if not 任:
                continue
            名 = str(任.get("名字") or "")
            if 名.startswith("常识："):
                统计["在跑"] = {"名字": 名, "第几步": 任.get("第几步"),
                              "共几步": len(任.get("步骤") or []),
                              "状态": 任.get("状态")}
                if 日志:
                    日志(f"  ⟳ 生存常识.同步实例：手上这条「{名}」跑到第 "
                        f"{任.get('第几步')} / {len(任.get('步骤') or [])} 步"
                        f"（状态 {任.get('状态')}）—— 进度在主链里，我没丢任何东西")
    except Exception as e:
        if 日志:
            日志(f"  ⚠ 生存常识.同步实例 出错：{type(e).__name__}: {e}")
    return 0


def 报个话(bridge):
    return {"装上": _已装, "统计": dict(统计),
            "记号": bool(getattr(bridge, "_生存常识外挂", None))}
