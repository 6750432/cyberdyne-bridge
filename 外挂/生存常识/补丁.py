    镐 = 找镐子(背包)
    if not 镐:
        return None, "手里没有镐子，挖不动石头 —— 只能绕路"
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return None, "状态帧里没有我自己的坐标"
    x0, y0, z0 = int(我[0] // 1), int(我[1]), int(我[2] // 1)
