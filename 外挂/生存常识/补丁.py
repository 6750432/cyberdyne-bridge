# ══════════════════════════ 探索：目标搜不到就自己出门找 ══════════════════════════
#
# 2026-10-07 实机：小家伙在地下/石山，周围一块木头都没有（扫描只有石头、铜矿、水）。
# 它已经能**说清楚**「我周围压根没有 acacia_log」，但**不会自己去找** ——
# 那时它只会站在那儿重复报了。这就是「陌生环境下自己推进科技树」缺的最后一环。
#
# 设计：**按心跳分段走**。
#   本车厢记住「我在找什么、从哪儿出发、朝哪个方向试过几趟」；
#   每次被问起（心跳约 60 秒一次）就走一段、同时等新扫描；
#   一看见目标，立刻转成完整计划。
#   ★ 不需要每个 tick 的钩子 —— 借用现有心跳的节奏就够了。
#   ★ 走之前会看 `scan.危险`：那个方向有岩浆/火就换一个方向。

方位表 = [(1, 0, "东"), (0, 1, "南"), (-1, 0, "西"), (0, -1, "北"),
        (1, 1, "东南"), (-1, 1, "西南"), (-1, -1, "西北"), (1, -1, "东北")]

# ★ 一趟走多远（格）。2026-10-07 实机定的数：
#   原来定 16，结果**一趟永远走不到**，每次都 60 秒超时、白烧 3 分钟。
#   原因是主链每 8 秒会兜底重下一次 goto，而**重下就是打断上一次寻路**
#   （bridge.py 里写明的既有行为）—— 于是它走走停停、16 格走不完。
#   缩短到 8 格：短腿更容易在超时前到位，到了就发下一趟。
#   **短腿多趟 > 长腿一趟**，实机试出来的。
# ★★ 关键数：**必须短于主链重下 goto 的间隔**。
#   主链每 8 秒兜底重下一次 goto，而重下 = 打断上一次寻路。
#   实测速度约 1 格/秒 —— 所以 8 格的腿**正好在第一次重下时被腰斩**，
#   永远差最后几格，每趟都要耗满 60 秒超时。缩到 4 格：约 4~5 秒走完，
#   抢在第一次打断之前交付，一趟就是一趟。
# ★★★ 距离必须小到**地形高度差不超过 2.5 格**。
#   主链判「走到了没」是：水平距离 ≤ 到点 **且 |Δy| ≤ 2.5**。
#   而我们的目标 y 用的是**出发那一刻的 y** —— 地形一起伏它就永远判「没到」。
#   实测：从 y=49 走到 y=46，Δy=3 > 2.5，60 秒超时 × 3 次，白烧三分钟。
#   砍到 3 格：这么短的距离内高度差基本不会超过 2.5，才判得了「到了」。
#   （真正的解法是给手侧加一个"随便逛逛"的原语，那是下一步的事。）
每趟走多远 = 3
每趟几段 = 6            # 一次任务连着走几段（3 × 6 = 18 格/趟）
危险范围 = 12            # 这个距离内有岩浆/火，就别往那边走

探索状态 = {}            # {目标方块: {"起点": [x,y,z], "试过": n}}


