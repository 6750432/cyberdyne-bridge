# ★★★ 挖阶梯上地表（主人 2026-10-07 点出来的点子）
#
#   「它寻路如果面前有方块阻挡，刚好背包里有工具，可以自己向上挖阶梯通道上地表」
#
#   为什么这招比"绕圈找路"强：它在石山里，四周全是被挡死的路 ——
#   寻路器算不出通向森林的路径，于是永远在原地打转。
#   而**它自己手里就有镐子**，往上挖一条 45° 阶梯，几格就能见到天。
#
#   阶梯怎么挖（MC 里的标准做法）：
#     站在 (x, y, z)，要爬到 (x+1, y+1, z)：
#       · 挖 (x+1, y+1, z) —— 前方**头部**那格，清掉它身体才进得去
#       · 挖 (x+1, y+2, z) —— 再上面那格，不然站不直
#       · 走到 (x+1, y+1, z) —— 一格台阶，寻路器自己会跳上去
#     重复 N 次，就是一串往上的台阶。
#
#   ★ 挖到空气也无所谓：手侧会回「那里是空气」，而主链的完成判据是
#     「那一格现在是空气了吗」—— 本来就是空气，直接算完成。不会卡。
每趟爬几格 = 3


def 找镐子(背包):
    """背包里有没有镐子？返回最好的一把（按挖掘矩阵的档位）。"""
    有 = [k for k in (背包 or {}) if isinstance(k, str) and k.endswith("_pickaxe")]
    if not 有:
        return None
    try:
        import 挖掘矩阵
        return 挖掘矩阵.最好的工具(有, "pickaxe") or sorted(有)[0]
    except Exception:
        return sorted(有)[0]


def 安排一趟挖上去(状态, 背包, 方向=(1, 0)):
    """手上有机镐时：挖一条 45° 阶梯往上爬。返回 (步骤表, 说明) 或 (None, 原因)。"""
    镐 = 找镐子(背包)
    if not 镐:
        return None, "手里没有镐子，挖不动石头 —— 只能绕路"
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return None, "状态帧里没有我自己的坐标"
    x0, y0, z0 = int(我[0] // 1), int(我[1]), int(我[2] // 1)
    dx, dz = 方向

    步骤 = []
    # ⓪ 先把自己站的地方头顶清空 —— 不然它窝在 1 格高的缝里，**跳都跳不起来**。
    #    （主人 2026-10-07：「阶梯得两格高他才能跳上去啊」）
    步骤.append({"动作": "挖", "p": [x0, y0 + 2, z0]})

    # ★★ 实测第二个坑：**它原地根本没动**。主链到达判据只看「水平 ≤ 到点」，
    #   目标只在前方 1 格时它站原地就判「到了」→ 下一步「挖」先把腿打断 → 迈不出去。
    #   所以：目标放到前方 **2 格**，到点收紧到 **1.0**，逼它真迈出去。
    列数 = 每趟爬几格 * 2
    每列挖几格 = 3          # 站上去以后头上足 2 格
    for k in range(1, 列数 + 1):
        x = x0 + dx * k
        z = z0 + dz * k
        y = y0 + k // 2
        for 层 in range(每列挖几格):
            步骤.append({"动作": "挖", "p": [x, y + 层, z]})
        if k % 2 == 0:                                   # 每 2 格走一步（斜坡）
            步骤.append({"动作": "走到", "p": [x, y, z], "到点": 1.0})
    return 步骤, (f"前面被石头挡着，我手里有{镐} —— "
                f"干脆**挖一条阶梯往上爬**（{每趟爬几格} 格台阶），出去就见天了")


def 安排一趟探索(目标方块, 状态, 缺的方块名, 背包=None):
    """目标方块搜不到 → 安排一趟「出去找」。返回 (步骤表, 说明) 或 (None, 原因)。"""
    我 = (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return None, "状态帧里没有我自己的坐标，我不敢乱走"
    我 = [int(我[0] // 1), int(我[1]), int(我[2] // 1)]

    扫 = (状态 or {}).get("scan") or {}
    险 = []
    for d in (扫.get("危险") or []):
        p = d.get("p")
        if isinstance(p, (list, tuple)) and len(p) >= 3:
            险.append((int(p[0]), int(p[2]), str(d.get("name") or "危险")))

    # ★★ 手上有镐子 → **先挖上去**，别绕圈。
    #   实测：它在石山里绕了十几分钟，8 个方向都不通 ——
    #   而它背包里的镐子一次都没用过。
    if 找镐子(背包):
        方 = 方位表[探索状态.get(目标方块, {}).get("试过", 0) % len(方位表)]
        爬, 说 = 安排一趟挖上去(状态, 背包, (方[0], 方[1]))
        if 爬:
            记 = 探索状态.setdefault(目标方块, {"起点": list(我), "试过": 0})
            记["试过"] = 记.get("试过", 0) + 1
            return 爬, 说

    记 = 探索状态.setdefault(目标方块, {"起点": list(我), "试过": 0})
    起 = 记.get("起点") or 我
    if not 记.get("起点"):
        记["起点"] = list(我)

    # 从「下一趟该走的方向」开始，顺时针找一个**路上没有危险**的
    总 = len(方位表)
    for 偏移 in range(总):
        号 = (记["试过"] + 偏移) % 总
        dx, dz, 名 = 方位表[号]
        终点 = [起[0] + dx * 每趟走多远, 起[1], 起[2] + dz * 每趟走多远]
        挡路 = [x for (x, z, n) in 险
               if (min(起[0], 终点[0]) - 危险范围 <= x <= max(起[0], 终点[0]) + 危险范围
                   and min(起[2], 终点[2]) - 危险范围 <= z <= max(起[2], 终点[2]) + 危险范围)]
        if 挡路:
            continue
        记["试过"] = 号 + 1
        记["上次终点"] = 终点
        # 到点放宽到 3.5：被反复打断的情况下，"差不多到了"就该算到，
        # 不然永远卡在最后一两格上
        # ★★ 一次发**一串**腿，不是一条。
        #   单条腿 0.5 秒就走完了，可下一趟要等 60 秒后的心跳 ——
        #   实测就是 3 格/分钟，慢得没法看。串起来之后同一份任务连着走 N 段，
        #   几秒钟就把一整趟走完。每段都短（3 格）保证高度差不超 2.5；
        #   中途哪段真过不去，整条任务失败，下次心跳从新位置重算 —— 不会卡死。
        步骤 = []
        for _i in range(每趟几段):
            步骤.append({"动作": "走到",
                        "p": [起[0] + dx * 每趟走多远 * (_i + 1),
                              起[1],
                             起[2] + dz * 每趟走多远 * (_i + 1)],
                        "到点": 3.5})
        # 去重 —— 一条链上同一个方块会被列好几次，念出来像结巴
        去重 = []
        for x in 缺的方块名:
            if x not in 去重:
                去重.append(x)
        return 步骤, (f"周围没有{'、'.join(去重[:3])} —— "
                   f"我朝**{名}**走 {每趟走多远 * 每趟几段} 格去找找"
                   f"（第 {记['试过']} 趟，分 {每趟几段} 段）")

    return None, (f"周围找不到目标，而且八个方向**都有危险**（"
                f"{'、'.join(n for _, _, n in 险[:3])}）—— 我不敢乱走，请主人带我过去")


