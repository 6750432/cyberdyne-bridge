def 认物品(原, 表):
    """从一句中文里认出物品名。**取最长匹配** —— 否则「石」会把「石镐」顶掉。"""
    候 = [(str(k), v) for k, v in (表 or {}).items() if k and str(k) in 原]
    if not 候:
        return None
    候.sort(key=lambda kv: -len(kv[0]))
    return 候[0][1]


