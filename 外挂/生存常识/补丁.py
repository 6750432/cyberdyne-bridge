"""生存常识·车厢本体 —— 把「意图」变成一串能执行的步骤（本地推演，不请示大模型）。

┌───────────────────────────────────────────────────────────────────┐
│ 它干的事：L2 说「我要一把石镐」→ 本地推演 → 交给任务栈            │
└───────────────────────────────────────────────────────────────────┘
    L2：「我要石镐」                          ← 意图，不是步骤
     ↓ 常识库.求解器（配方 DAG + DFS）
    符号化计划：挖 oak_log / 合成 oak_planks / 放 crafting_table / …
     ↓ 点位解析（读**状态帧里的扫描结果**）
    具体步骤：{"动作":"挖","p":[10,70,10]} / {"动作":"合成", …}
     ↓ 任务栈.接()   ← **照样过现有的 fail-closed 闸，一道不少**
    执行

★ 全程**不把配方塞进 Prompt、不问大模型**。大模型只负责「听」（把话变成意图）
  和「说」（把状态说成人话）。

┌───────────────────────────────────────────────────────────────────┐
│ ⚠ 本车厢发现的一个硬缺口（写在最前面，别让它埋在代码里）          │
└───────────────────────────────────────────────────────────────────┘
手侧的扫描（`node/server.js` 的 `扫环境`）给两样东西：

    scan.方块   = [{name:"stone", count:182}, …]      ← **只有名字和数量，没有坐标**
    scan.可交互 = [{name:"oak_log", p:[x,y,z]}, …]    ← 有坐标，但只收「兴趣方块」，最多 6 条

而 `兴趣方块` 那份名单是（原文照抄）：

    crafting_table furnace blast_furnace smoker chest barrel bed torch lantern
    water lava farmland wheat carrots potatoes **oak_log birch_log spruce_log**
    **iron_ore coal_ore copper_ore** glass oak_door ladder anvil
    enchanting_table sugar_cane pumpkin melon gravel clay snow ice

**里面有橡木、有铁矿 —— 但没有 `stone`。** 所以：

    撸树   → ✅ 解析得出坐标（oak_log 在名单里）
    挖石头 → ❌ **解析不出坐标**（stone 不在名单里，扫描只告诉你有 182 个）

最小闭环会在「挖石头」这一步卡住。这不是本车厢写得不好，
是**手侧的感知面不够** —— 见报告里的「待拍板第 7 条」。

本车厢先做**诚实的失败**：定位不到就**明确上报**，绝不瞎猜一个坐标去挖。
"""

