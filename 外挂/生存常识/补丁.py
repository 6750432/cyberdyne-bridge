# 状态帧里能拿到坐标的只有 scan.可交互（手侧那份「兴趣方块」名单）
def 扫描表(状态):
    """把状态帧里的扫描结果整理成 {方块名: [x,y,z]}。同一个方块取第一条。"""
    扫 = (状态 or {}).get("scan") or {}
    表 = {}
    for 条 in (扫.get("可交互") or []):
        if not isinstance(条, dict):
            continue
        名, p = 条.get("name"), 条.get("p")
        if 名 and isinstance(p, (list, tuple)) and len(p) >= 3:
            表.setdefault(名, [int(p[0]), int(p[1]), int(p[2])])
    # ★★ 石头类不在「兴趣方块」名单里 → 站在草地上就找不到石头坐标，
    #   求解器会去挑「黑石」（下界的东西）。手侧单开了一项 `scan.石头`。
    石 = 扫.get("石头")
    if isinstance(石, dict):
        名, p = 石.get("name"), 石.get("p")
        if 名 and isinstance(p, (list, tuple)) and len(p) >= 3:
            # ★★★ 2026-10-08 反矿透红线：**只把看得见的交给求解器**。
            #   实机事故（主人亲眼所见）：给了它一个**埋在地下**的石头坐标，
            #   它走过去隔着泥土挥镐，服务端一路中止，它在原地打转好几分钟，
            #   最后要主人亲手把泥土挖掉才拿到圆石 ✗
            #   手侧现在会给"最近的石头"标上 `裸露` / `视线` / `挡前`：
            #     · 六个面全被实心包住（`裸露 is False`）→ **不进这张表** ——
            #       求解器压根看不见它，也就不会去瞄它（这就是反矿透）；
            #     · 露出来的，进表；挡着的部分由 `落坐标` 插前置任务解决。
            #   ⚠ 情报缺失时（老版本的手、或者"那块不是石头"）**照旧放行** ——
            #     这条是**故意 fail-open** 的：宁可像从前那样多挖一次，
            #     也不要因为拿不到情报就彻底不干活。
            if 石.get("裸露") is False:
                _报(f"[反矿透] 最近的石头 {名}@{list(p)} 整个被埋住了（{石.get('挡')}）"
                    f" —— 不交给求解器，改走「向下盲挖」碰运气")
            else:
                表.setdefault(str(名), [int(p[0]), int(p[1]), int(p[2])])
    return 表


def _遮挡情报(状态, p):
    """查雷达内存里**这一格**的暴露情报 —— 手侧给「最近的石头」标的那一份。

    为什么单开一个函数：铁律「**同一件事只有一处实现**」。
    `扫描表` 要它来判"这块要不要喂给求解器"，`落坐标` 要它来判
    "要不要先挖掉挡着的那块" —— 两处必须看**同一份情报**，
    否则又是一个「两边口径不一致」（T3）。

    返回 dict，或 None（= 手侧没给这一格的情报 → 调用方**照旧放行**）。
    """
    try:
        扫 = (状态 or {}).get("scan") or {}
        目标 = [int(x) for x in list(p)[:3]]
        # ★★★ 2026-10-08 晚 实机抓到的「口径不一致」（T3，而且是我自己写的）：
        #   手侧能算**任何方块**的遮挡（挖之前现算 ✓），可我只从 `scan.石头`
        #   那一份里取情报 ✗ —— 而 `scan.石头` 只有"最近的石头"那一块。
        #   于是要挖的是一根 oak_log 时，车厢这边**拿不到任何遮挡情报** ✗
        #   → 「先挖掉挡着的」插不进去 → 它每秒重试同一镐：
        #     `[16:01] 「dig」没做成：「oak_log」前面挡着「oak_leaves」，我得先把那一块挖掉`
        #   现在两份都看：`scan.石头`（最近的石头）+ `scan.可交互`
        #   （求解器真正会瞄的那几格 = 那 6 个名额）。情报里带着 裸露/视线/挡前 ✓
        候选 = [扫.get("石头")] + list(扫.get("可交互") or [])
        for 条 in 候选:
            if not isinstance(条, dict):
                continue
            位 = 条.get("p")
            if not (isinstance(位, (list, tuple)) and len(位) >= 3):
                continue
            if [int(位[0]), int(位[1]), int(位[2])] == 目标:
                return 条
        return None
    except Exception:
        return None


