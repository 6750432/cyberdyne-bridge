def 身边空位(状态, 我=None):
    """★ 用**雷达**找「身边哪一格是空的」—— 放方块就放这儿，不猜。

    主人 2026-10-07：「妈的都有雷达了还不知道放哪儿？」
    坐标是白拿的（我 ± 1），「是不是空的」正是雷达该回答的事。
    返回 (空位列表, 还没读数的那几格)。
    """
    我 = 我 or (状态 or {}).get("pos")
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return [], []
    x, y, z = int(我[0] // 1), int(我[1]), int(我[2] // 1)
    候选 = [(x + 1, y, z), (x - 1, y, z), (x, y, z + 1), (x, y, z - 1)]
    已知 = {}
    for 条 in ((状态 or {}).get("blocks") or []):
        p = 条.get("p")
        if isinstance(p, (list, tuple)) and len(p) >= 3:
            已知[(int(p[0]), int(p[1]), int(p[2]))] = str(条.get("name") or "")
    空, 没读数 = [], []
    for c in 候选:
        if c not in 已知:
            没读数.append(list(c))
        elif 已知[c] in 空气名:
            空.append(list(c))
    return 空, 没读数


def _同名候选(状态, 名):
    """雷达报回来的同名方块坐标，按离我远近排序。**只收"报过坐标"的** ✓

    ★ 这个函数存在的唯一理由：把「不猜坐标」这句话变成一个**只有一处实现**的规矩 ✓
      证据有两个来源，缺一不可：
        · `状态["blocks"]` —— 雷达（含身边四格）；坐标是手侧实测的 ✓
        · `状态["scan"]["可交互"]` —— 扫描表；坐标也是手侧实测的 ✓
      两处都没有该方块 → 返回空 → 调用方**如实报缺**，绝不用算术凑一个 ✗
    """
    出, 见 = [], set()
    我 = (状态 or {}).get("pos") or [0, 0, 0]

    def 收(p):
        if not isinstance(p, (list, tuple)) or len(p) < 3:
            return
        try:
            q = (int(p[0]), int(p[1]), int(p[2]))
        except Exception:
            return
        if q in 见:
            return
        见.add(q)
