def 安排一趟向下盲挖(状态, 背包=None, 层=4, 方向=(1, 0)):
    """【向下盲挖】—— 找不到石头就**往下碰运气**，不跑远。

    ★ 依据是**地质学常识**：泥土 / 沙子 / 沙砾**下面大概率就是石头**。
      （主人 2026-10-08 点名的规则。）所以"要石头、可周围一块裸露的都没有"时，
      正确答案不是"出去找"，而是**就地往下挖几层**。

    ★ 为什么是**阶梯式**、不是直着往下：
      直下会把自己埋进一个竖井里，碰上加岩浆/水/沙砾就是事故，而且爬不上来 ✗
      老玩家的标准做法是斜着一格一格往下 —— 每层挖掉"前方脚那一格 + 它上面一格"，
      永远留得住一个能站的台阶；挖完还能沿原路走回来 ✓

    ★ 反矿透照样守着：这一趟**不瞄任何具体方块**，就是往下挖，
      **挖到什么算什么**。新露出来的东西由雷达报回来，
      再由常识树决定要不要插队（"惊喜时刻"）✓

    ⚠ 2026-10-09 补的一刀：**盲挖可以盲，但不能瞎** ✓
      脚下那三格**一个读数都没有 → 先请雷达看一眼**再下钻（不做无凭据的深钻）✓
      有读数而且看到岩浆/水/沙砾 → **不挖**，交回主链换法子 ✓

    返回 (步骤, 说明)；方向不通就返回 (None, 为什么)。
    """
    我 = None
    try:
        我 = 状态.get("pos")
    except Exception:
        我 = None
    if not (isinstance(我, (list, tuple)) and len(我) >= 3):
        return None, "不知道我站在哪，没法往下挖"
    x0, y0, z0 = int(我[0]), int(我[1]), int(我[2])
    dx, dz = 方向
    # ★ 先看清楚再下钻（见 `_看见地下吗` 的注释）
    _有, _险, _要看 = _看见地下吗(状态, [x0 + dx, y0, z0 + dz])
    if not _有 and _要看:
        return None, (f"脚下 {_要看} 这几格雷达一个读数都没有 —— "
                      f"我不做没凭据的深钻 ✗ 先请雷达（挖空守卫）看一眼，看清楚了下一拍再下")
    if _险:
        return None, f"脚下读到「{_险}」—— 挖下去就是事故，这一趟不挖 ✗（换方向或换法子）"
    步骤 = []
    for i in range(1, max(1, int(层)) + 1):
        台阶 = [x0 + dx * i, y0 - i, z0 + dz * i]          # 下行后的落脚点
        头上 = [x0 + dx * i, y0 - i + 1, z0 + dz * i]      # 站着走进去需要空的那格
