#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""物理体检车厢 —— 离线断言。

要证明的四件事：
  A 装上 / 幂等 / 卸下（一字不差还原）
  B ★★★ **今天实机抓到的每一类 bug，它都挑得出来**（这是它的全部意义）
  C ★★★ 能改正的就**当场改正**（`拾 grass_block` → `拾 dirt`）✓
  D 干净的步子**一个字不许碰**（不误伤 ✓）

⚠ 这个车厢的数据是**自动抓**的（`tools/生成物理常识.js` → `常识库/物理引擎规则.json`）
  所以这里**不重抄**那些数字 ✓ —— 用例读的是**同一个文件** ✓
  （抄一遍数字 = 又一份会过期的真相 ✓ 今天记过这条）

跑法：python3 外挂/测物理体检.py
"""

import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")
通过, 失败 = [], []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


def 载(名):
    p = os.path.join(外挂根, 名, "补丁.py")
    spec = importlib.util.spec_from_file_location("测_" + 名, p)
    m = importlib.util.module_from_spec(spec)
    sys.modules["测_" + 名] = m
    sys.path.insert(0, os.path.join(外挂根, 名))
    spec.loader.exec_module(m)
    return m


def 帧(方块=None):
    """造一份状态帧：`blocks` = 雷达读数；`items` = 手里有什么"""
    return {"pos": [-138.5, 74.0, 168.7], "items": {},
            "blocks": [{"p": list(k), "name": v} for k, v in (方块 or {}).items()],
            "scan": {}}


def 主():
    sys.path.insert(0, 外挂根)
    sys.path.insert(0, ROOT)
    import bridge
    体 = 载("物理体检")

    # ══════════ A 装 / 卸 ══════════
    print("── A 组：装、卸 ──")
    原接 = bridge.任务栈.接
    r = 体.装上(bridge, 日志=lambda *a, **k: None)
    试("A1 装上了（数据在、钩子打上了）", r.get("好") is True, str(r))
    试("A2 ★★ 打了 1 处补丁（任务栈.接）", len(r.get("打了", [])) == 1, str(r.get("打了")))
    试("A3 类方法真的被换掉了", bridge.任务栈.接 is not 原接)
    试("A4 幂等（重复装上不再套壳）", 体.装上(bridge)["为什么"].find("已经装过") >= 0)
    r2 = 体.卸下(bridge)
    试("A5 ★★ 卸下以后**一字不差还原**", r2.get("好") is True and bridge.任务栈.接 is 原接, str(r2))
    试("A6 卸载幂等", 体.卸下(bridge).get("好") is True)

    # ══════════ B ★★★ 今天实机抓到的每一类，它都得挑出来 ══════════
    #   这一组就是它**存在的全部意义** ✓
    #   下面每一条都是 2026-10-09 的**真机原话**，不是编的 ✓
    print("── B 组：今天实机抓到的每一类 ──")

    # ① 「挖 air」——「生存常识：本区块：air@[-136, 77, 159]，0.7 格」→ 挖成功却不掉东西
    _, 报 = 体.体检([{"动作": "挖", "p": [-136, 77, 159], "方块": "air"}],
                  帧({(-136, 77, 159): "air"}))
    试("B1 ★★★ 挖的目标**就是空气** → 挑得出来（实机：本区块 air@…，挖成功却不掉东西 ✓）",
       any("T1" in x for x in 报), str(报))

    # ② 「挖基岩」——diggable:false
    _, 报 = 体.体检([{"动作": "挖", "p": [-155, 74, 152], "方块": "bedrock"}],
                  帧({(-155, 74, 152): "bedrock"}))
    试("B2 ★★★ 挖**挖不动的**（基岩）→ 挑得出来（数据是 diggable:false ✓）",
       any("T2" in x for x in 报), str(报))

    # ③ 「拾 grass_block」——实机：挖草方块 → 拾 grass_block → 干等 60 秒 ×3
    改, 报 = 体.体检([{"动作": "挖", "p": [-141, 75, 163], "方块": "grass_block"},
                    {"动作": "拾", "物品": "grass_block", "数量": 1}],
                  帧({(-141, 75, 163): "grass_block"}))
    试("B3 ★★★ 拾的物品 ≠ 掉落物 → 挑得出来（实机原话：挖草方块却拾 grass_block ✓）",
       any("T3" in x for x in 报), str(报))

    # ④ 「要走到树冠上 4 格高」——今天实机那次（它爬不上去、干等 60 秒 ×3）
    #   ⚠ 我第一版的 T4 是**误报机器** ✗：去查"那一格的碰撞盒" ✓
    #     可「走到」本来就是"**靠近**那一格"，不是站进去 ✗ → 每条正常计划都被挑 ✓
    #     已改成**高度差**（依据：一步 0.6 格 / 跳 1.1 格 ✓ 都是抓来的常量 ✓）
    _, 报 = 体.体检([{"动作": "走到", "p": [-143, 79, 149]}], 帧())
    试("B4 ★★★ 要走到**比现在高 4 格**的地方 → 挑得出来"
       "（实机原话：计划要它走到 [-143,79,149]，可它站在 y=75 —— 爬不上去、干等 60 秒 ×3 ✓）",
       any("T4" in x for x in 报), str(报))
    _, 报 = 体.体检([{"动作": "走到", "p": [-143, 68, 149]}], 帧())
    试("B4b ★★ 要往下跳 6 格 → 也挑得出来（落差 > 3 会摔伤 ✓）",
       any("T4" in x for x in 报), str(报))

    # ⑤ 「要镐子的方块、可手里没镐子」——挖了也不掉东西
    _, 报 = 体.体检([{"动作": "挖", "p": [-141, 75, 163], "方块": "stone"}],
                  帧({(-141, 75, 163): "stone"}))
    试("B5 ★★★ 要镐子的方块 + 手里没镐子 → 挑得出来（挖了也不掉东西 ✓）",
       any("T5" in x for x in 报), str(报))

    # ⑤b ★★★ 但**计划自己会做那把镐子**的时候，这一条不许报 ✗
    #   ★ 2026-10-09 实机：stone_pickaxe 那条 23 步计划被 T5 报了 3 条 ✗
    #     「第 15/18/21 步要挖 stone —— 要镐子，手里没有」✗ **全是误报** ✗
    #     第 12 步就写着「合成 wooden_pickaxe」✓，挖 stone 在它**后面** ✓
    #     误报比漏报更危险：报一堆假的，真的那条就没人看了 ✓
    计划 = [{"动作": "合成", "物品": "wooden_pickaxe", "数量": 1},
           {"动作": "挖", "p": [-141, 75, 163], "方块": "stone"},
           {"动作": "拾", "物品": "cobblestone", "数量": 1}]
    _, 报 = 体.体检(计划, 帧({(-141, 75, 163): "stone"}))
    试("B5b ★★★ 计划前面就排了「合成 wooden_pickaxe」→ **不许报 T5**"
       "（2026-10-09 实机那条 3 连误报就是它 ✓）",
       not any("T5" in x for x in 报), str(报))
    计划2 = [{"动作": "挖", "p": [-141, 75, 163], "方块": "stone"}]
    _, 报2 = 体.体检(计划2, 帧({(-141, 75, 163): "stone"}))
    试("B5c ★★ 反过来：计划里**没有**那把镐子 → T5 照样报 ✓（别把闸门一起关掉）",
       any("T5" in x for x in 报2), str(报2))

    # ══════════ C ★★★ 能改正的**当场改正** ══════════
    print("── C 组：能改正的就当场改正 ──")
    改, 报 = 体.体检([{"动作": "挖", "p": [-141, 75, 163], "方块": "grass_block"},
                    {"动作": "拾", "物品": "grass_block", "数量": 1}],
                  帧({(-141, 75, 163): "grass_block"}))
    拾 = [x for x in 改 if x.get("动作") == "拾"]
    试("C1 ★★★ 「拾 grass_block」→ **当场改成「拾 dirt」** ✓（数据里 grass_block→dirt ✓）",
       bool(拾) and 拾[0].get("物品") == "dirt", str(拾))
    试("C2 ★★ 挖那一步一个字没动", 改[0].get("方块") == "grass_block", str(改[0]))
    改2, _ = 体.体检([{"动作": "挖", "p": [-141, 75, 163], "方块": "stone"},
                    {"动作": "拾", "物品": "stone", "数量": 1}],
                  帧({(-141, 75, 163): "stone"}))
    试("C3 ★★ 石头 → **cobblestone** ✓（不是 stone ✓）",
       [x for x in 改2 if x.get("动作") == "拾"][0].get("物品") == "cobblestone", str(改2))

    # ══════════ D 干净的步子一个字不许碰 ══════════
    print("── D 组：不误伤 ──")
    # ⚠ 这一组就是防"误报机器"的 ✗ —— 「走到」是"靠近"，**不是站进去** ✓
    干净 = [{"动作": "走到", "p": [-136, 74, 170]},
           {"动作": "挖", "p": [-141, 75, 163], "方块": "oak_log"},
           {"动作": "拾", "物品": "oak_log", "数量": 1},
           {"动作": "合成", "物品": "oak_planks", "数量": 1}]
    帧净 = 帧({(-136, 74, 170): "air", (-141, 75, 163): "oak_log"})
    改3, 报3 = 体.体检(干净, 帧净)
    试("D1 ★★★ 一条干净的计划 → **一处都不挑**（体检不是找茬 ✓）", not 报3, str(报3))
    试("D2 ★★ 而且计划**原样不动**（连顺序都不许变 ✓）",
       改3 == 干净, str(改3))
    试("D3 ★★ 原木挖了掉原木 → 拾原木是对的（不误改 ✓）",
       [x for x in 改3 if x.get("动作") == "拾"][0].get("物品") == "oak_log")

    # ══════════ E 数据读不到 → 拒绝装（fail-closed）══════════
    print("── E 组：读不到常识库就不装 ──")
    存 = 体._规
    体._规 = False
    r3 = 体.装上(type("桥", (), {"任务栈": bridge.任务栈})())
    试("E1 ★★★ 读不到 常识库/物理引擎规则.json → **拒绝装**（不装作体检过了 ✓）",
       r3.get("好") is False, str(r3))
    体._规 = 存

    # ══════════ E 组：乙（不刷屏）+ 丙（假活作废）══════════
    #   主人 2026-10-09：「怎么我水上建的平路桥他说有障碍？」——
    #   同一条警告**每 20 秒喊一次、喊了 7+ 次** ✗ 这就是刷屏 ✓
    #   而且那份计划**12 步全是挖空气** ✓ 每步 0 秒 ✗（主人原话：「怎么不动呢」）
    print("── E 组：乙 · 同一条只喊一次 ｜ 丙 · 整份白挖就作废 ──")
    原接2 = bridge.任务栈.接
    被原接过 = []

    def 假原(self, 名字, 步骤, s):
        被原接过.append(名字)
        return "接了"

    bridge.任务栈.接 = 假原
    说过 = []
    体._最近说过 = {"签": None, "次": 0}
    r = 体.装上(bridge, 日志=lambda 文: 说过.append(str(文)))
    试("E0 乙丙用的壳装上了", r.get("好") is True, str(r))

    计划真 = [{"动作": "挖", "p": [-141, 75, 163], "方块": "stone"},
             {"动作": "拾", "物品": "cobblestone", "数量": 1}]
    帧真 = 帧({(-141, 75, 163): "stone"})
    bridge.任务栈.接(None, "同一份计划", 计划真, 帧真)
    第一次 = len(说过)
    bridge.任务栈.接(None, "同一份计划", 计划真, 帧真)
    bridge.任务栈.接(None, "同一份计划", 计划真, 帧真)
    试("E1 ★★★ 乙：**同一条警告只喊一次** ✓（后面再报同一份不再刷屏 ✗）",
      第一次 > 0 and len(说过) == 第一次, f"第一次 {第一次} 条，三趟下来共 {len(说过)} 条")
    试("E2 ★★ 但它**照旧放行** ✓（乙只是不刷屏，不是不干活 ✗）",
       len(被原接过) == 3, str(被原接过))

    计划空 = [{"动作": "挖", "p": [-136, 77, 159], "方块": "air"},
             {"动作": "挖", "p": [-136, 76, 159], "方块": "air"},
             {"动作": "拾", "物品": "stone", "数量": 1}]
    帧空 = 帧({(-136, 77, 159): "air", (-136, 76, 159): "air"})
    体._最近说过 = {"签": None, "次": 0}
    前 = len(被原接过)
    果 = bridge.任务栈.接(None, "全是空气的计划", 计划空, 帧空)
    试("E3 ★★★ 丙：**整份都是挖空气 ⇒ 作废** ✗（返回 False，不接单 ✓）",
      果 is False, str(果))
    试("E4 ★★★ 而且**原接单口一次都没被叫到** ✓（真拒了，不是嘴上说说 ✗）",
       len(被原接过) == 前, str(被原接过))
    试("E5 ★★ 作废时**出声说清楚**（不许静默 ✗）",
       any("整份作废" in x for x in 说过), str(说过[-3:]))

    体.卸下(bridge)
    bridge.任务栈.接 = 原接2

    print()
    print("═" * 62)
    print(f"物理体检车厢：{len(通过)} 过 / {len(失败)} 失败")
    for x in 失败:
        print(f"  ❌ {x['名']} —— {x['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
