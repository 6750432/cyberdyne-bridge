#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""就地取材车厢 —— 离线断言（空间 RAG 四级优先 + 三条红线）。

主人点名要的那一条在最中间：
  **E 本区块没有石头 → 去隔壁区块找** ✓
三条红线各一条：
  · F 只查扫过的区域（没扫过的区块，内存里根本不许有它）—— 反透视
  · G 危险区（岩浆旁）自动降权/放弃
  · H 全都扫过都没有 → 返回第 ④ 级【探索】，不死磕

跑法：python3 外挂/测就地取材.py
"""

import importlib.util
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")
通过, 失败 = [], []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


我 = (-178.0, 72.0, 162.5)          # 区块 (-12, 10)


def 造帧(pos=我, 可交互=None, 石头=None, 危险=None):
    return {
        "pos": list(pos), "items": {}, "blocks": [],
        "scan": {"t": int(time.time() * 1000), "地面": "stone",
                 "方块": [{"name": "stone", "count": 30}],
                 "可交互": 可交互 if 可交互 is not None else [],
                 "危险": 危险 if 危险 is not None else [],
                 "石头": 石头},
    }


def 载(名):
    p = os.path.join(外挂根, 名, "补丁.py")
    spec = importlib.util.spec_from_file_location(f"测_{名}", p)
    m = importlib.util.module_from_spec(spec)
    sys.modules[f"测_{名}"] = m
    sys.path.insert(0, os.path.join(外挂根, 名))
    spec.loader.exec_module(m)
    return m


class 假译:
    def 收输出(self, 输出, 状态, 用途=None, *a, **k):
        return "原样", None, "定位不到：测试用"


class 假bridge:
    pass


def 清(取):
    取._记忆.clear()
    取._已知区块.clear()


def 主():
    sys.path.insert(0, 外挂根)
    取 = 载("就地取材")

    # ══════════ A 装卸 ══════════
    print("── A 组：装上 / 幂等 / 卸下 ──")
    b = 假bridge()
    b.翻译器 = 假译
    r = 取.装上(b, 日志=lambda *a, **k: None)
    试("A1 装上了", r.get("好") is True, str(r))
    试("A2 幂等", 取.装上(b)["为什么"].find("已经装过") >= 0)
    原 = 假译.收输出
    试("A3 卸下能还原", 取.卸下(b)["好"] is True and 假译.收输出 is not 原)

    # ══════════ B 只把扫到的存进内存 ══════════
    print("── B 组：本地内存（只存扫到的）──")
    清(取)
    取._记(造帧(可交互=[{"name": "oak_log", "p": [-170, 72, 160], "裸露": True}]))
    账 = 取.报个话()
    试("B1 扫到的方块进了内存", 账["条目数"] == 1, str(账))
    试("B2 它的区块被登记为「已知」", 取.块区((-170, 72, 160)) in 取._已知区块)
    试("B3 没扫过的区块**不在**已知里（反透视的第一道）",
       取.块区((100, 72, 100)) not in 取._已知区块)

    # ══════════ C 第 ① 级：手边 ══════════
    print("── C 组：① 手边（视线可达 + ≤4.5 + 裸露）──")
    清(取)
    f = 造帧(可交互=[{"name": "stone", "p": [-176, 72, 162], "裸露": True, "视线": True}])
    块 = 取.挑块(f, "stone")
    试("C1 手边的石头被挑中", bool(块) and 块["层级"] == "手边", str(块))
    试("C2 手边不走寻路，直接把坐标给它", bool(块) and 块["p"] == (-176, 72, 162), str(块))
    埋的 = 造帧(可交互=[{"name": "stone", "p": [-176, 72, 162], "裸露": False}])
    试("C3 ★ 整个被埋住的不许瞄（反矿透）", 取.挑块(埋的, "stone") is None, str(取.挑块(埋的, "stone")))
    远的 = 造帧(可交互=[{"name": "stone", "p": [-160, 72, 162], "裸露": True, "视线": True}])
    试("C4 超过 4.5 格的不算「手边」（它该在更低的层级里被找到，不是不找）",
       (取.挑块(远的, "stone") or {}).get("层级") != "手边", str(取.挑块(远的, "stone")))
    清(取)   # ★ 清掉内存，免得上面那条把方块留在内存里污染 C4

    # ══════════ D 第 ② 级：本区块 ══════════
    print("── D 组：② 本区块（查本地内存）──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-170, 72, 162], "裸露": True}]))   # 同区块、22 格外
    块 = 取.挑块(造帧(), "stone")            # 这一帧手边什么都没有
    试("D1 ★★ 手边没有 → 翻本地内存，本区块里找到了", bool(块) and 块["层级"] == "本区块", str(块))
    试("D2 给的是内存里那个坐标", bool(块) and 块["p"] == (-170, 72, 162), str(块))

    # ══════════ E 第 ③ 级：跨区块（主人点名的用例）══════════
    print("── E 组：③ 跨区块（本区块没有 → 去隔壁找）──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))   # 区块 (-10, 9)
    我的区 = 取.块区(我)
    试("E0 前提：它跟我不在同一个区块", 取.块区((-150, 72, 150)) != 我的区,
       f'{取.块区((-150, 72, 150))} vs {我的区}')
    试("E0b 而且本区块内存里确实一块石头都没有",
       not any("stone" in (取._记忆.get(我的区) or {}) for _ in [0]),
       str(取._记忆.get(我的区)))
    块 = 取.挑块(造帧(), "stone")
    试("E1 ★★★ **本区块没有石头 → 它去隔壁区块找到了**（主人点名的用例）",
       bool(块) and 块["层级"] == "隔壁区块", str(块))
    试("E2 报里能看出是哪个区块来的", bool(块) and 块["p"] == (-150, 72, 150), str(块))

    # 多个候选时，挑**最近的**（主人说"找到最近的可用目标方块"）
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-120, 72, 120], "裸露": True}]))
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    块 = 取.挑块(造帧(), "stone")
    试("E3 ★★ 两个区块都有时，挑**最近**的那个", bool(块) and 块["p"] == (-150, 72, 150), str(块))

    # ══════════ F 红线：只查扫过的区域 ══════════
    print("── F 组：红线① 绝不整图透视 ──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    块 = 取.挑块(造帧(), "stone")
    试("F1 先确认它本来能被挑中（不然下面那条说明不了问题）", bool(块), str(块))
    取._已知区块.discard(取.块区((-150, 72, 150)))      # 装成"这个区块没扫过"
    试("F2 ★★★ **没扫过的区块，就算内存里有记录也不许用**（反透视红线）",
       取.挑块(造帧(), "stone") is None, str(取.挑块(造帧(), "stone")))

    # ══════════ G 红线：危险区降权/放弃 ══════════
    print("── G 组：红线② 危险区（岩浆旁）自动降权或放弃 ──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    险 = 造帧(危险=[{"name": "lava", "p": [-149, 72, 150]}])       # 紧挨着
    试("G1 ★★★ 紧挨着岩浆的目标 → **放弃**", 取.挑块(险, "stone") is None,
       str(取.挑块(险, "stone")))
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    取._记(造帧(可交互=[{"name": "stone", "p": [-140, 72, 140], "裸露": True}]))
    块 = 取.挑块(险, "stone")
    试("G2 ★★ 危险的那个被降权 → 挑更安全的那个（不是一刀不干）",
       bool(块) and 块["p"] == (-140, 72, 140), str(块))

    # ══════════ H 第 ④ 级：探索 ══════════
    print("── H 组：④ 探索（全都没有 → 不死磕）──")
    清(取)
    步, 说 = 取.出计划(造帧(), "stone")
    试("H1 ★★★ 手边、本区块、隔壁区块都没有 → **不给计划**（交给探索）", 步 is None, str(步))
    试("H2 而且说清了「该去未知区碰运气」，不是沉默", "碰运气" in str(说) or "未知" in str(说), str(说))

    # ══════════ I 计划形状 ══════════
    print("── I 组：步骤表 ──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-170, 72, 162], "裸露": True}]))
    步, 说 = 取.出计划(造帧(), "stone")
    动 = [x.get("动作") for x in (步 or [])]
    试("I1 跨区块的活是「走到 → 挖 → 拾」三步", 动 == ["走到", "挖", "拾"], str(动))
    试("I2 ★ 寻路到点给 3.0（手侧会提前 ~2.6 格停下，实机教训）",
       bool(步) and 步[0].get("到点") == 3.0, str(步[:1]))
    试("I3 ★ 挖那一步**带方块名**（不然挖错东西也算完成）",
       bool(步) and 步[1].get("方块") == "stone", str(步[1]))

    # ══════════ J 陈坐标当场重查（主人今天的火气换来的）══════════
    print("── J 组：陈坐标 → 当场重查雷达 ──")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    帧J = 造帧()                                   # 当帧扫描里**没有** oak_leaves
    任 = {"步骤": [{"动作": "挖", "p": [-151, 75, 158], "方块": "oak_leaves"},
                   {"动作": "拾", "物品": "oak_leaves", "数量": 1}]}
    改, 说 = 取.补陈坐标(帧J, 任)
    试("J1 ★★★ 计划里那个「当帧压根没有」的目标 → **这步标作废，不挥空镐**",
       改 == 1 and 任["步骤"][0].get("跳过") is True, f"改={改} 步={任['步骤'][0]} 说={说}")
    清(取)
    取._记(造帧(可交互=[{"name": "stone", "p": [-150, 72, 150], "裸露": True}]))
    任2 = {"步骤": [{"动作": "挖", "p": [-151, 75, 158], "方块": "stone"}]}
    改2, 说2 = 取.补陈坐标(帧J, 任2)
    试("J2 ★★★ 名字对不上坐标（那格早不是它了）→ **坐标换成雷达里最新的那个**",
       改2 == 1 and list(任2["步骤"][0]["p"]) == [-150, 72, 150], f"改={改2} 步={任2['步骤'][0]} 说={说2}")
    帧J3 = 造帧(可交互=[{"name": "stone", "p": [-176, 72, 162], "裸露": True}])
    任3 = {"步骤": [{"动作": "挖", "p": [-176, 72, 162], "方块": "stone"}]}
    改3, _ = 取.补陈坐标(帧J3, 任3)
    试("J3 ★★ 新鲜的目标**一个字不动**（不许瞎改）",
       改3 == 0 and list(任3["步骤"][0]["p"]) == [-176, 72, 162], f"改={改3}")

    # ══════════ L 手侧报"刚没了" → 车厢当场划掉（今晚最后一块拼图）══════════
    print("── L 组：手侧说它没了，车厢当场划掉 ──")
    清(取)
    取._记(造帧(可交互=[{"name": "oak_leaves", "p": [-151, 75, 158], "裸露": True}]))
    试("L1 先确认它在记忆里（不然下面说明不了问题）",
       bool(取.挑块(造帧(), "oak_leaves")), str(取.挑块(造帧(), "oak_leaves")))
    帧没了 = 造帧()
    帧没了["scan"]["没了"] = [[-151, 75, 158]]        # ← 手侧刚报的"这一格变空气了"
    取._记(帧没了)
    试("L2 ★★★ 手侧一报「没了」，车厢**当场划掉** —— 再也不会拿它去「刷新」计划",
       取.挑块(造帧(), "oak_leaves") is None, str(取.挑块(造帧(), "oak_leaves")))
    试("L3 ★★ 别的方块不受牵连（只划掉报上来的那一格）",
       取._记(造帧(可交互=[{"name": "stone", "p": [-170, 72, 162], "裸露": True}]))
       or bool(取.挑块(造帧(), "stone")), "同区块的石头被误伤了")

    # ══════════ M ★★★ **空气不是材料**（实机 13:50 那一场）══════════
    #   实机原话：「生存常识：本区块：**air**@[-136, 77, 159]，0.7 格」
    #   → 它把"空气"当材料挑出来 → 派了「挖 air」+「拾 air」✗
    #     → 挖"成功"了（那里本来就是空气），可什么都不掉 → 「拾」干等 60 秒 ✓
    #   空气是从哪儿进来的：雷达会把**盯着的格子**（含身边那 4 格）报上来 ✓
    #     那里面天然就有空气 ✓ 而 2026-10-09 刚把身边 4 格改成**永远要报** ✓
    #     → 空气进了内存 → 被当成候选材料 ✗
    print("── M 组：空气不是材料 ──")
    清(取)
    帧空 = 造帧(可交互=[{"name": "air", "p": [-136, 77, 159], "裸露": True}])
    帧空["blocks"] = [{"p": [-136, 77, 159], "name": "air"},
                    {"p": [-136, 77, 160], "name": "air"}]
    取._记(帧空)
    试("M1 ★★★ 掺在「可交互」里的空气 → **进不了内存** ✗",
       取.挑块(造帧(), "air") is None, str(取.挑块(造帧(), "air")))
    试("M2 ★★★ 掺在雷达 `blocks` 里的空气 → 同样进不了内存 ✗"
       "（身边那 4 格永远要报 ✓ 那里面天然就有空气 ✓）",
       (-136, 77, 160) not in ((取._记忆.get(取.块区((-136, 77, 160))) or {}).get("air") or {}),
       str(取._记忆.get(取.块区((-136, 77, 160)))))
    试("M3 ★★ **不挑方块名**（想要=None）时也不许把空气挑出来 ✗"
       "（实机就是这条：挑出来的是 air@0.7 格 —— 最近的那个正好是空气 ✓）",
       取.挑块(造帧()) is None or 取.挑块(造帧())["名"] != "air",
       str(取.挑块(造帧())))
    取._记(造帧(可交互=[{"name": "stone", "p": [-136, 77, 158], "裸露": True}]))
    试("M4 ★★ 真材料照旧收得进（别误伤 ✓）",
       bool(取.挑块(造帧(), "stone")), str(取.挑块(造帧(), "stone")))
    试("M5 ★★ 水也不算材料（它是「能穿」的东西，不是「能拿」的东西 ✓）",
       (取._记(造帧(可交互=[{"name": "water", "p": [-136, 77, 157], "裸露": True}])) or True)
       and 取.挑块(造帧(), "water") is None, str(取.挑块(造帧(), "water")))

    print("\n" + "═" * 62)
    print(f"就地取材车厢：{len(通过)} 过 / {len(失败)} 失败")
    for f in 失败:
        print(f"  ❌ {f['名']} —— {f['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
