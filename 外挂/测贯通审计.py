#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""贯通审计车厢（閘一）—— 离线测试。

★ 最重要的一组是 C 组：它把「**漏了要点名**」钉成断言 ——
  主人 2026-10-08 的原话是「比值必須 = 1.0，**不足即報警並指出漏在哪個決策點**」，
  光有个数字没用，得能一眼看出是哪个点漏的。

跑法：python3 外挂/测贯通审计.py
"""

import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")
通过, 失败 = [], []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


class 假栈:
    def __init__(self):
        self.去过 = []

    def _下发(self, 步, 任, 现在, s):
        self.去过.append((步 or {}).get("动作"))
        return "原装-下发"


class 假桥:
    def __init__(self):
        self.任务栈 = 假栈
        self.栈 = 假栈()


def 主():
    sys.path.insert(0, 外挂根)
    sys.path.insert(0, ROOT)
    spec = importlib.util.spec_from_file_location(
        "测_贯通审计", os.path.join(外挂根, "贯通审计", "补丁.py"))
    贯 = importlib.util.module_from_spec(spec)
    sys.modules["测_贯通审计"] = 贯
    spec.loader.exec_module(贯)

    def 清账():
        贯._账.update({"需要": 0, "查了": 0, "漏": {}, "按动作": {}})

    # ══════════ A 组：装 / 卸 / 不误伤 ══════════
    print("── A 组：装、卸、别把主链弄坏 ──")
    原类 = 假栈._下发
    桥 = 假桥()
    r = 贯.装上(桥)
    试("A1 ★★ 装上了", r["好"] and len(r["打了"]) == 1, str(r))
    试("A2 ★★★ 重复装上不套两层壳（踩过：套两层自己把自己拦死）",
       贯.装上(桥)["打了"] == [])
    试("A3 ★★★ **原样传下去**，不改变返回值（审计车厢不许改主链行为）",
       桥.栈._下发({"动作": "走到", "p": [1, 2, 3]}, {}, 1.0, {}) == "原装-下发"
       and 桥.栈.去过 == ["走到"])
    试("A4 ★★ 卸下还原", 贯.卸下(桥)["好"] and 假栈._下发 is 原类)

    # ══════════ B 组：判据表 ══════════
    print("── B 组：每个动作需要什么空间信息 ──")
    清账()
    试("B1 ★★ 挖：有 blocks 就算查了", 贯.记一笔("挖", {"blocks": [{"p": [1, 2, 3]}]}) is True)
    试("B2 ★★★ 挖：blocks 空但有 scan.石头 → 也算查了（石头不在 blocks 里）",
       贯.记一笔("挖", {"scan": {"石头": {"p": [1, 2, 3]}}}) is True)
    试("B3 ★★★ 挖：两样都空 → **漏了**", 贯.记一笔("挖", {"blocks": [], "scan": {}}) is False)
    试("B4 ★★ 放：要 blocks", 贯.记一笔("放", {"blocks": [{"p": [1, 2, 3]}]}) is True)
    试("B5 ★★ 拾：要 drops", 贯.记一笔("拾", {"drops": [{"name": "oak_log"}]}) is True)
    试("B6 ★★★ 拾：没有 drops → 漏了（实机就是站着干等 60 秒）",
       贯.记一笔("拾", {"drops": []}) is False)
    试("B7 ★★ 熔炉放料：要 furnace", 贯.记一笔("熔炉放料", {"furnace": {"输入": []}}) is True)
    试("B8 ★★★ 走到/合成/说/给 **不需要**空间信息 → 不计入（返回 None）",
      贯.记一笔("走到", {}) is None and 贯.记一笔("合成", {}) is None
       and 贯.记一笔("说", {}) is None and 贯.记一笔("给", {}) is None)

    # ══════════ C 组：贯通率 + **点名** ══════════
    print("── C 组：比值必须 = 1.0，漏了要点名 ──")
    清账()
    for _ in range(7):
        贯.记一笔("挖", {"blocks": [{"p": [1, 2, 3]}]})
    贯.记一笔("拾", {"drops": []})
    率, n, 查 = 贯.贯通率()
    试("C1 ★★★ 8 次需要、7 次查了 → 贯通率 = 0.875", abs(率 - 0.875) < 1e-9, f"{率}")
    试("C2 ★★ 账对得上（需要 8 / 查了 7）", (n, 查) == (8, 7), f"{n}/{查}")
    试("C3 ★★★ **漏的决策点点名了**：拾 ×1（主人原话：不足即報警並指出漏在哪個決策點）",
       贯._账["漏"] == {"拾": 1}, str(贯._账["漏"]))
    试("C4 ★★ 按动作分项统计也在", 贯._账["按动作"].get("挖") == 7, str(贯._账["按动作"]))
    动 = []
    贯._记 = lambda 文: 动.append(str(文))
    贯.报表(强制=True)
    试("C5 ★★★ 报警时**说得出是哪个点漏的**",
       any("拾" in x and "贯通率" in x for x in 动), str(动))
    试("C6 ★★ 而且明确说「比值不到 1.0」", any("不到 1.0" in x for x in 动), str(动))

    清账()
    动.clear()
    for _ in range(5):
        贯.记一笔("挖", {"blocks": [{"p": [1, 2, 3]}]})
        贯.记一笔("放", {"blocks": [{"p": [1, 2, 3]}]})
    贯.报表(强制=True)
    试("C7 ★★★ 一个都没漏 → 贯通率 **正好 1.0**，而且**不报警**",
       abs(贯.贯通率()[0] - 1.0) < 1e-9 and not any("不到 1.0" in x for x in 动), str(动))

    清账()
    试("C8 ★★ 一个都不需要时（只走路）→ 满分 1.0，不是 0/0 崩掉", 贯.贯通率()[0] == 1.0)

    # ══════════ D 组：接线（真挂上以后能不能自动计数）══════════
    print("── D 组：挂上以后自动计数 ──")
    清账()
    桥 = 假桥()
    贯.装上(桥)
    桥.栈._下发({"动作": "拾", "物品": "oak_log"}, {}, 1.0, {"drops": []})
    桥.栈._下发({"动作": "拾", "物品": "oak_log"}, {}, 2.0, {"drops": [{"name": "oak_log"}]})
    率, n, 查 = 贯.贯通率()
    试("D1 ★★★ 挂上以后**自动**数了（拾 2 次、查了 1 次 → 0.5）",
       (n, 查) == (2, 1), f"{n}/{查}")
    试("D2 ★★ 而且**照旧把动作传下去**了（审计不能吃掉动作）",
       桥.栈.去过 == ["拾", "拾"], str(桥.栈.去过))
    贯.卸下(桥)

    # ══════════ E 组：红线 ══════════
    print("── E 组：红线 ──")
    import hashlib
    with open(os.path.join(ROOT, "bridge.py"), "rb") as f:
        哈 = hashlib.sha256(f.read()).hexdigest()
    试("E1 ★★★ 主链 bridge.py 一个字节都没动", 哈.startswith("2499f81f807431b0"), 哈[:16])

    print("\n" + "═" * 62)
    print(f"贯通审计车厢：{len(通过)} 过 / {len(失败)} 失败")
    for f in 失败:
        print(f"  ❌ {f['名']} —— {f['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
