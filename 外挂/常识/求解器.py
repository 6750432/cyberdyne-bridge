无穷 = 10 ** 6


def 物品难度(重算=False):
    """每个物品「从零搞到它有多难」。**不动点松弛，与遍历顺序无关。**

    ┌───────────────────────────────────────────────────────────────┐
    │ 为什么不能像第一版那样用「递归 + 共享的『正在算』栈」做环检测   │
    └───────────────────────────────────────────────────────────────┘
    第一版是递归 + 一个 `在算` 集合，撞见栈上的东西就判无穷。
    听起来对，实际上**结果依赖遍历顺序**：

        iron_ingot ←→ iron_block（9 个锭 ↔ 1 个方块）是真环
        先算 iron_ingot → iron_block 被环挡住 → 判无穷
        先算 iron_block → iron_ingot 走烧炼那条活路 → 两个都有有限值

    2026-10-07 实测就是这样：**同一份数据，单跑通、全跑不通**，
    而且两次跑出来的难度表不一样。这种不确定性的求解器不能上路。

    不动点松弛就没这个问题：所有值先置无穷，然后反复「放宽」——
    每轮只看邻居**当前**的值，一轮轮传下去，直到不再变化。
    环自然停在无穷，而且**跟从谁开始算毫无关系**。

    打分规则（越小越容易）：
        徒手能挖到的         = 1
        要工具的               = 1 + 那把工具的难度
        能合成/能加工的        = 1 + max(材料难度, 设备难度)
        怎么都弄不到的         = 无穷
    """
    global _难度表
    if _难度表 is not None and not 重算:
        return _难度表
    数 = 数据模块.载入()
    表 = {名: 无穷 for 名 in 数["名到编号"]}
    标签表 = 数.get("标签") or {}

    def 值(名):
        """材料的难度。标签取候选里最容易的那个。"""
        if isinstance(名, str) and 名.startswith("#"):
            return min((表.get(c, 无穷) for c in (标签表.get(名[1:]) or [])),
                      default=无穷)
        return 表.get(名, 无穷)

    # ── 初始：徒手能挖到的一律 1 ──
    for 名 in 表:
        for b in (数["掉落索引"].get(名) or []):
            blk = 数["方块"].get(b)
            if blk and blk["能挖"] and not blk["需要工具"]:
                表[名] = 1
                break

    # ── 松弛到不动点（最多 60 轮，实际几轮就停） ──
    轮 = 0
    for 轮 in range(1, 61):
        变了 = False
        for 名 in 表:
            最好 = 表[名]
            # 甲：挖（这个物品是某个方块的掉落，且那个方块要工具）
            for b in (数["掉落索引"].get(名) or []):
                blk = 数["方块"].get(b)
                if not blk or not blk["能挖"]:
                    continue
                要 = blk["需要工具"]
                if not 要:
                    continue                      # 徒手那种上面已经给过 1 了
                工 = min((表.get(t, 无穷) for t in 要), default=无穷)
                if 工 < 无穷 and 1 + 工 < 最好:
                    最好 = 1 + 工
            # 乙：合成 / 加工
            for r in (数["产物到配方"].get(名) or []):
                材 = 0
                够 = True
                for m in r["材料"]:
                    d = 值(m)
                    if d >= 无穷:
                        够 = False
                        break
                    材 = max(材, d)
                if 够:
                    设 = r.get("设备")
                    if 设:
                        ds = 表.get(设, 无穷)
                        if ds >= 无穷:
                            够 = False
                        else:
                            材 = max(材, ds)
                if 够 and 1 + 材 < 最好:
                    最好 = 1 + 材
            if 最好 < 表[名]:
                表[名] = 最好
                变了 = True
        if not 变了:
            break

    # 标签也记一份（键写成 `#名字`，跟配方里的写法一致）
    for 标, 候 in 标签表.items():
        表["#" + 标] = min((表.get(c, 无穷) for c in 候), default=无穷)

    _难度表 = 表
    return 表


