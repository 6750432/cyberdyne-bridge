"""常识库·依赖求解器 —— 「我要一把石镐」→ 一条能直接执行的步骤链。

┌───────────────────────────────────────────────────────────────────┐
│ 它回答的问题                                                     │
└───────────────────────────────────────────────────────────────────┘
L2 只说一句「我要一把石镐」（意图）。**前置条件全是这里推的**：

    撸树 → 木板 → 木棍 → 工作台 → 木镐 → 挖石头 → 石镐

★ 决策依据**全部来自本地数据**（数据.py / 挖掘矩阵.py），
  **一个配方都不写死，也一个字都不进 Prompt。**

┌───────────────────────────────────────────────────────────────────┐
│ 三件必须做对的事（每一件都有对应测试）                            │
└───────────────────────────────────────────────────────────────────┘
① **数量账**：1 个原木出 4 块木板；工作台要 4 块、木镐要 3 块 ——
   加起来 7 块，所以**得砍两棵**。同一批木料不能算两次。
② **工具前置**：挖石头需要镐子 → 求解器得先插一段「造木镐」。
   而造木镐又需要工作台 → 再往里插一段。**递归到自己解决为止。**
③ **不可达就立刻报**：既没配方、又不在任何方块的掉落里 →
   抛「无法达成」，**绝不无限展开**（另有最大深度兜底）。

┌───────────────────────────────────────────────────────────────────┐
│ 输出的「计划」是符号化的（不带坐标）                              │
└───────────────────────────────────────────────────────────────────┘
求解器**不知道世界长什么样**（它只是常识）。所以它输出的是：

    {"动作": "挖",   "目标方块": "oak_log"}      ← 挖一棵橡木，哪棵待定
    {"动作": "合成", "物品": "oak_planks", "数量": 4, "要工作台": False}
    {"动作": "放",   "方块": "crafting_table"}   ← 放哪待定

真正落地时由车厢拿**状态帧里的扫描结果**把「哪棵」「放哪」填成具体坐标，
再交给 任务栈.接() 走现有的 fail-closed 闸。
"""

import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import 数据 as 数据模块            # noqa: E402
import 挖掘矩阵                    # noqa: E402

默认最多深度 = 8
_追踪 = bool(os.environ.get("COMMON_TRACE"))

# 手工合成最多 2×2，所以「有形状且任一边 > 2」的配方必须用工作台
_工作台方块 = "crafting_table"


class 求解不出(Exception):
    """做不到 —— 带上人话理由。调用方要把它报给 L2，**不许吞**。"""


_难度表 = None
无穷 = 10 ** 6


def 物品难度(重算=False):
    """每个物品「从零搞到它有多难」——递归算，带**环检测**。

    ★ 为什么非要这张表：第一版挑工具只数「材料种类数」，
      木镐和钻石镐都是 2 种材料，打成平手，然后按名字排 ——
      `diamond_pickaxe` 恰好排在 `wooden_pickaxe` 前面，于是它去造钻石镐了。
      结果撞进 `diamond ↔ diamond_block` 这个真环（9 钻石 ↔ 1 方块），爆栈。

    打分规则（越小越容易）：
        徒手能挖到的            = 1
        要工具的                  = 1 + 那把工具的难度
        能合成的                  = 1 + 最难的那个材料的难度
        怎么都弄不到的            = 无穷
    成环的路线**当场判无穷**（那就是此路不通），不参与比较。
    """
    global _难度表
    if _难度表 is not None and not 重算:
        return _难度表
    数 = 数据模块.载入()
    表 = {}
    在算 = set()

    def 算(名):
        if 名 in 表:
            return 表[名]
        if 名 in 在算:
            return 无穷                 # ★ 成环 → 此路不通，别钻进去
        在算.add(名)
        最好 = 无穷
        try:
            # 甲：挖
            for b in (数["掉落索引"].get(名) or []):
                if b == 名:
                    continue
                blk = 数["方块"].get(b)
                if not blk or not blk["能挖"]:
                    continue
                要 = blk["需要工具"]
                if not 要:
                    最好 = min(最好, 1)
                else:
                    工 = min((算(t) for t in 要), default=无穷)
                    if 工 < 无穷:
                        最好 = min(最好, 1 + 工)
            # 乙：合成
            for r in (数["产物到配方"].get(名) or []):
                材 = 0
                for m in r["材料"]:
                    d = 算(m)
                    if d >= 无穷:
                        材 = 无穷
                        break
                    材 = max(材, d)
                if 材 < 无穷:
                    最好 = min(最好, 1 + 材)
            表[名] = 最好
            return 最好
        finally:
            在算.discard(名)

    for 名 in 数["名到编号"]:
        算(名)
    _难度表 = 表
    return 表


def 要工作台吗(配方):
    """这条配方需要工作台吗？（2×2 手工做不了就得有台子）"""
    return bool(配方.get("要台子"))


def _配方尺寸(配方):
    return 配方.get("尺寸") or 1


def _选配方(目标, 数, 账):
    """从数据里挑一条最可行的配方。

    挑法（简单但够用）：
      1. 优先挑**材料我们已经有**的（少跑腿）
      2. 其次挑**材料种类少**的
      3. 最后按产出数多的优先
    """
    条 = 数["产物到配方"].get(目标) or []
    if not 条:
        return None
    背包 = 账["背包"] | {k: v for k, v in 账["已做"].items() if v > 0}
    难度 = 物品难度()
    近处 = set(账["方块在哪"])          # ★ 附近**真的挖得到**的方块
    可及表 = {}
    在算 = set()

    def 可及(m, 深=0):
        """这个东西，**只用附近的东西**能不能搞到？（递归，带环检测）

        ★ 必须递归。第一版只看一层，于是：
            `oak_planks` 不是任何方块掉的 → 判「够不着」
            `bamboo_planks` 同理 → 也判「够不着」
            两边打平 → 按名字/数据原序 → 挑中了竹子。
          实际上橡木木板能用**附近的橡木原木**造，竹子木板要跑去砍 16 棵竹子。
        """
        if m in 可及表:
            return 可及表[m]
        if m in 在算 or 深 > 10:
            return False                 # 成环 / 太深 → 当作够不着
        在算.add(m)
        try:
            if 背包.get(m, 0) > 0 or m in 近处:
                可及表[m] = True
                return True
            if any(b in 近处 for b in (数["掉落索引"].get(m) or [])):
                可及表[m] = True
                return True
            for r in (数["产物到配方"].get(m) or []):
                if all(可及(x, 深 + 1) for x in r["材料"]):
                    可及表[m] = True
                    return True
            可及表[m] = False
            return False
        finally:
            在算.discard(m)

    def 够不着(m):
        return 0 if 可及(m) else 1

    def 分(r):
        # ① 材料我们已经有的优先（少跑腿）
        有 = sum(1 for m in r["材料"] if 背包.get(m, 0) > 0)
        # ② ★ 材料的**来源在不在附近** —— 这一条最重要。
        #    没有它，求解器会挑「竹子」当木头来源（bamboo_planks 也是 11 种变体之一），
        #    然后为了 4 块木板去砍 16 棵竹子。实测就是这么翻车的。
        够不着数 = sum(够不着(m) for m in r["材料"])
        # ③ 再看材料**本身有多难搞**（木头 1 分，钻石几百几千分）
        难 = max((难度.get(m, 无穷) for m in r["材料"]), default=0)
        return (够不着数, -有, 难, len(r["材料"]), -r["产出数"])
    return sorted(条, key=分)[0]


def _补配方尺寸(数):
    """给每条配方补上「要不要工作台」—— 从原版 inShape 的尺寸推。

    ★ 数据里我没存原始网格，所以这里用**材料种类数和总格数**近似：
      总格数 > 4 就一定放不进 2×2。这是保守判断（宁可多造个工作台）。
    """
    for 产物, 条们 in 数["产物到配方"].items():
        for r in 条们:
            if "要台子" in r:
                continue
            总格 = sum(r["材料"].values())
            r["要台子"] = bool(r.get("有形状")) and 总格 > 4
    return 数


def 求解(目标, 数量=1, 背包=None, 方块在哪=None, 最多深度=None):
    """主入口。返回 {"好", "为什么", "计划", "统计"}。

    ★★ 核心是「工作库存」模型（第一版不是这么写的，连栽三次）：
         · `工作` 是背包的副本，`求(名, N)` 会**先从它里面扣**
         · 扣光了才去造/挖，造出来的**先放回工作库**，再扣掉自己要用掉的
         · 于是「同一批木板被两个步骤各算一次」这种事**结构上不可能发生**

       前三次栽的跟头（都留在这儿当教训）：
         ① 拿原始背包判「手上有没有镐子」→ 看不见计划里刚造的木镐 → 无限递归
         ② 先求料、后扣账 → 一份料算两次 → 计划少一块木板
         ③ 先扣账、再按原数求料 → 同一份需求算两次 → 多挖 3 个木头
    """
    最多 = 最多深度 if 最多深度 is not None else 默认最多深度
    数 = _补配方尺寸(数据模块.载入())

    if 目标 not in 数["名到编号"]:
        return {"好": False, "为什么": f"我不认识「{目标}」这个东西",
                "计划": [], "统计": {}}

    工作 = {k: int(v) for k, v in (背包 or {}).items()}     # ← 可用库存（会被扣）
    在哪 = dict(方块在哪 or {})
    统计 = {"递归次数": 0, "最深": 0, "合成次数": 0, "挖掘次数": 0}
    状态 = {"台子立好了": False}

    # ── 可及性：只用附近的东西，能不能搞到？ ──
    近处 = set(在哪)
    可及表, 在算 = {}, set()

    def 可及(m, 深=0):
        if m in 可及表:
            return 可及表[m]
        if m in 在算 or 深 > 10:
            return False
        在算.add(m)
        try:
            if 工作.get(m, 0) > 0 or m in 近处:
                可及表[m] = True
                return True
            if any(b in 近处 for b in (数["掉落索引"].get(m) or [])):
                可及表[m] = True
                return True
            for r in (数["产物到配方"].get(m) or []):
                if all(可及(x, 深 + 1) for x in r["材料"]):
                    可及表[m] = True
                    return True
            可及表[m] = False
            return False
        finally:
            在算.discard(m)

    # ── 挑配方：附近搞得到的优先，其次材料少、产出多 ──
    难度 = 物品难度()

    def 选配方(名):
        条 = 数["产物到配方"].get(名) or []
        if not 条:
            return None

        def 分(r):
            够不着 = sum(0 if 可及(m) else 1 for m in r["材料"])
            有 = sum(1 for m in r["材料"] if 工作.get(m, 0) > 0)
            难 = max((难度.get(m, 无穷) for m in r["材料"]), default=0)
            return (够不着, -有, 难, len(r["材料"]), -r["产出数"])
        return sorted(条, key=分)[0]

    def 求(名, 要几个, 深, 路=frozenset()):
        # ★ `路` = 当前这条递归链上已经出现过的物品。用来**断环**。
        #   没有它，`iron_ingot ↔ iron_block`（1 方块 ↔ 9 锭）这种真环
        #   会把深度耗光，最后只报一句没用的「嵌套太深」，
        #   而不是主人要的那句「**当前条件无法达成**」。
        统计["递归次数"] += 1
        统计["最深"] = max(统计["最深"], 深)
        if _追踪:
            print("  " * 深 + f"└ 求({名} ×{要几个}) 深={深} 库={工作.get(名, 0)}")
        if 深 > 最多:
            raise 求解不出(f"嵌套太深（超过 {最多} 层）—— 这超出我的常识范围")
        要几个 = int(要几个)
        if 要几个 <= 0:
            return []

        # ① 先吃库存
        有 = 工作.get(名, 0)
        if 有 >= 要几个:
            工作[名] = 有 - 要几个
            return []
        还差 = 要几个 - 有
        工作[名] = 0

        # ② 合成（★ 在环上就不再展开配方，免得空转）
        配方 = None if 名 in 路 else 选配方(名)
        if 配方:
            批 = math.ceil(还差 / max(配方["产出数"], 1))
            步骤 = []
            # 台子先立（它也要吃料，所以排在前面）
            if 要工作台吗(配方) and not 状态["台子立好了"]:
                步骤 += 求(_工作台方块, 1, 深 + 1)
                步骤.append({"动作": "放", "方块": _工作台方块})
                状态["台子立好了"] = True
            for 材料, 单个用量 in sorted(配方["材料"].items()):
                for _ in range(批):
                    步骤 += 求(材料, 单个用量, 深 + 1, 路 | {名})
            产 = 批 * 配方["产出数"]
            工作[名] = 工作.get(名, 0) + 产 - 还差     # 多的留在库里给后面的人
            步骤.append({"动作": "合成", "物品": 名, "数量": 产,
                        "要工作台": 要工作台吗(配方),
                        # ★ 把用料明细写进步骤里 —— 计划就**自包含**了：
                        #   执行的人不用回查配方，测试也能精确模拟执行、验材料账。
                        "料": {m: k * 批 for m, k in 配方["材料"].items()}})
            统计["合成次数"] += 1
            return 步骤

        # ③ 挖
        方块们 = [b for b in (数["掉落索引"].get(名) or [])
                 if 数["方块"][b]["能挖"]]
        if 方块们:
            # 掉自己的方块排后面（树掉自己，但别的来源更"自然"时优先别的）
            方块们.sort(key=lambda b: (len(数["方块"][b]["需要工具"]), b == 名, b))
            选中 = None
            for b in 方块们:
                需 = 数["方块"][b]["需要工具"]
                if not 需 or (需 & {t for t, n in 工作.items() if n > 0}):
                    选中 = b
                    break
            步骤 = []
            if 选中 is None:
                选中 = 方块们[0]
                需 = 数["方块"][选中]["需要工具"]
                工具 = 最好的那把(需)
                if 工具 is None:
                    # ★ 光说「弄不到」不够 —— 得把**卡在哪一环**也说清楚。
                    #   这一段是只读的（查难度表），不会改状态。
                    # 排掉环上的（比如"想要钻石镐去挖钻石"这种自指）
                    候选 = [t for t in 需 if t not in 路] or list(需)
                    最近 = sorted(候选, key=lambda t: (难度.get(t, 无穷), t))[0]
                    卡 = []
                    for r in (数["产物到配方"].get(最近) or []):
                        for m in r["材料"]:
                            if 难度.get(m, 无穷) >= 无穷 and m not in 卡:
                                卡.append(m)
                    细 = (f"。连最容易的「{最近}」都造不出 —— "
                         f"它卡在 {'、'.join(卡)} 上" if 卡 else "")
                    raise 求解不出(
                        f"当前条件无法达成：「{名}」只能从 {'、'.join(方块们)} 挖到，"
                        f"而它们必须用 {'、'.join(sorted(需))} 这一档以上的工具{细}"
                        f"（这类东西要靠熔炼/交易/打怪掉落，我还没学）")
                步骤 += 求(工具, 1, 深 + 1, 路 | {名})   # ★「没镐子 → 自己造一把」
            挖几块 = min(还差, 64)
            工作[名] = 工作.get(名, 0) + 挖几块 - 还差
            for _ in range(挖几块):
                步 = {"动作": "挖", "目标方块": 选中}
                if 选中 in 在哪:
                    步["p"] = list(在哪[选中])
                步骤.append(步)
            统计["挖掘次数"] += 挖几块
            if 还差 > 挖几块:
                raise 求解不出(f"「{名}」一次要 {还差} 个太多 —— 分几次给我")
            return 步骤

        # ★ 主人点名要的那句「当前条件无法达成」——得说清楚**为什么**。
        #   分类报账：合成没有、挖掘没有，那多半是熔炼/交易/打怪掉落，
        #   这些是**另外一整类获取方式**，我还没学。
        有配方但成环 = bool(数["产物到配方"].get(名))
        猜 = ("（它大概只能靠**熔炼**、交易或者打怪掉落拿到 —— 这些我还没学）"
             if 有配方但成环 else "（它没有任何方块直接掉它）")
        raise 求解不出(
            f"当前条件无法达成：「{名}」既没有我能用的配方、"
            f"也不在任何方块的掉落表里 {猜}")

    try:
        计划 = 求(目标, int(数量), 0)
    except 求解不出 as e:
        return {"好": False, "为什么": str(e), "计划": [], "统计": 统计}
    统计["剩料"] = {k: v for k, v in 工作.items() if v}
    return {"好": True, "为什么": "", "计划": 计划, "统计": 统计}


def 最好的那把(候选工具):
    """从一组**都行**的工具里挑一把「最容易搞到」的（不是挑最好的）。

    ★ 这里跟 挖掘矩阵.最好的工具 不一样：那是「手上已经有几把，用哪把」；
      这里是「一把都还没有，去造哪把」。所以挑**材料最容易**的 ——
      木镐永远比石镐容易，石镐永远比铁镐容易。
    """
    数 = 数据模块.载入()
    难度 = 物品难度()
    能造 = [t for t in 候选工具 if 难度.get(t, 无穷) < 无穷]
    if not 能造:
        return None
    # ★ 挑**最容易搞到**的那把（木镐永远比石镐容易），不是挑最好的。
    #   平手时按名字排 —— 但这次难度已经把钻石镐甩开到几千分去了，不会再打平。
    return sorted(能造, key=lambda t: (难度[t], t))[0]


