def 说计划(计划, 数=None):
    """把计划打印成人看得懂的一行行。"""
    行 = []
    for i, 步 in enumerate(计划, 1):
        a = 步.get("动作")
        if a == "挖":
            行.append(f"{i:2d}. 挖 {步.get('目标方块')}"
                     + (f" @{步.get('p')}" if 步.get("p") else ""))
        elif a == "合成":
            行.append(f"{i:2d}. 合成 {步.get('物品')} ×{步.get('数量')}"
                     + ("（用工作台）" if 步.get("要工作台") else "（手工）"))
        elif a == "放":
            行.append(f"{i:2d}. 放 {步.get('方块')}")
        elif a == "走到":
            行.append(f"{i:2d}. 走到 {步.get('目标方块')}")
        else:
            行.append(f"{i:2d}. {步}")
    return "\n".join(行)


