def _标签成员(数, 材料名):
    """`#oak_logs` → [oak_log, …] ✓（不是标签就原样返回一个 ✓）

    ★ 这里是我第一版踩空的地方 ✗：我按"材料是列表"写 ✓
      可真形状是 **dict {材料名: 数量}** ✓ 而且材料名**经常是个 `#标签`** ✗
      ⇒ 于是 `用了什么("oak_log")` 只答出 oak_wood ✗ 漏掉 oak_planks ✓
      （规矩：**先看数据再写码** ✗ 别照脑子里那个形状写 ✓）
    """
    if not str(材料名).startswith("#"):
        return [材料名]
    表 = 数.get("标签") or {}
    v = 表.get(材料名)
    if v is None:
        v = 表.get(材料名[1:])
    if v is None:
        return []
    if isinstance(v, dict):
        return sorted(v.keys())
    if isinstance(v, (list, tuple, set)):
        return sorted(v)
    return []


