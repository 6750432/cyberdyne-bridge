ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")

通过 = []
失败 = []


def 试(名, 条件, 为啥="条件不成立"):
    (通过 if 条件 else 失败).append(名 if 条件 else {"名": 名, "为啥": 为啥})
    return bool(条件)


def 含(名, 文, *词):
    return 试(名, all(w in str(文) for w in 词),
             f"「{文}」里没有 {' 或 '.join(w for w in 词 if w not in str(文))}")


# ══════════════════════════ A 组：体检本身 ══════════════════════════

def A组(体检模块):
    print("── A 组：体检本身（纯函数）──")
    好 = 体检模块.体检
    一 = 体检模块.体检一步

    # ★ A1 真实复现
    坏 = 一({"动作": "走到", "目标": "copper_ore(-38,50,-23)"}, 1)
    试("A1 ★ 实机那个坏任务书被抓住", 坏 is not None, "**放过了！**")
    含("A1b 理由点明了是不认识的字段", 坏, "不认识的字段")
    含("A1c 理由点出了「目标」这个词", 坏, "目标")
    含("A1d 理由告诉了它需要什么", 坏, "p")

    试("A2 正确的走到能过",
      一({"动作": "走到", "p": [-38, 50, -23], "到点": 2.5}, 1) is None)
    含("A3 走到缺 p 被拒", 一({"动作": "走到"}, 1), "缺", "p")
    含("A4 坐标只有两个数被拒", 一({"动作": "挖", "p": [1, 2]}, 1), "三个")
    含("A5 ★ 坐标是字符串被拒（这种会让主链 float() 当场炸）",
      一({"动作": "走到", "p": "-38 50 -23"}, 1), "不是三个数")
    含("A6 坐标里混了非数字被拒",
      一({"动作": "挖", "p": ["石头", 2, 3]}, 1), "不是数字")
    试("A7 「起点」占位符放行",
      一({"动作": "挖", "p": "起点"}, 1) is None)
    含("A8 说缺文本被拒", 一({"动作": "说"}, 1), "缺", "文本")
    含("A9 熔炉放料缺燃料被拒",
      一({"动作": "熔炉放料", "p": [1, 2, 3], "输入": {"name": "raw_iron", "count": 1}}, 1),
       "缺", "燃料")
    含("A10 合成缺物品被拒", 一({"动作": "合成", "数量": 2}, 1), "缺", "物品")
    含("A11 往箱子里放数量保留都没有被拒",
      一({"动作": "往箱子里放", "p": [1, 2, 3], "物品": "cobblestone"}, 1), "保留")
    试("A12 拾/等 不强求字段",
      一({"动作": "拾"}, 1) is None and 一({"动作": "等", "ms": 2000}, 1) is None)
    试("A13 少见但合法的字段不误退",
       一({"动作": "挖", "p": [1, 2, 3], "超时_ms": 30000, "跳过": True}, 1) is None)

    坏 = 好([{"动作": "走到", "p": [1, 2, 3]},
            {"动作": "挖", "目标": [1, 2, 3]}])
    试("A14 ★ 一票否决：两步里第二步坏 → 整份退", 坏 is not None, "只退了坏的那步")
    含("A14b 理由指明是第 2 步", 坏, "第 2 步")

    试("A15 空步骤表不炸", 好([]) is None)
    试("A16 步骤不是字典也不炸", 好(["走到"]) is not None)
    试("A17 正确的一整套任务过",
       好([{"动作": "走到", "p": [-38, 50, -23]},
          {"动作": "等", "ms": 2000},
          {"动作": "说", "文本": "铜矿在这儿呢"}]) is None)


# ══════════════════════════ B 组：挂上车之后端到端 ══════════════════════════

# ★ 实机原文（抄自 logs/llm审计.jsonl 的「原文」字段）
实机坏原文 = ('{"任务":{"名字":"看看铜矿","步骤":['
          '{"动作":"走到","目标":"copper_ore(-38,50,-23)"},'
          '{"动作":"等","时长":5},'
          '{"动作":"说","内容":"铜矿真好看"}],'
          '"为什么":"上次没看完的铜矿，就在旁边不远，去看看"}}')

实机对原文 = ('{"任务":{"名字":"看看铜矿","步骤":['
          '{"动作":"走到","p":[-38,50,-23]},'
          '{"动作":"等","ms":2000},'
          '{"动作":"说","文本":"铜矿在这儿呢"}],'
          '"为什么":"看看铜矿"}}')


def B组(bridge, 车钩, 临时, 表):
    print("── B 组：挂上车之后端到端 ──")
    列 = 车钩.列车(bridge)
    列.车厢表 = 表        # ★ 用同一张表：不然模块会被重新载一份，测试摸不到真的那个
    列.换轨(["动作面", "受限脚本", "任务书体检", "拒单反馈"], 理由="测试")
    试("B1 四节车厢都挂上了",
       列.编组 == ["动作面", "受限脚本", "任务书体检", "拒单反馈"], str(列.编组))
    试("B1b 宪法体检全过", 列.宪法体检()["好"])

    日志 = os.path.join(临时, "脑日志")
    os.makedirs(日志, exist_ok=True)
    栈 = bridge.任务栈({"task_enable": True}, lambda *a, **k: None,
                      lambda o: None, 日志)
    译 = bridge.翻译器({"prompt_limit": 6000}, lambda *a, **k: None, 日志,
                     任务栈=栈, 三觉=None, 人格="",
                     允许动作=bridge.任务栈.允许动作, 记忆=None)
    s = {"pos": [-33.52, 50, -20.7], "scan": {}, "players": []}

    动作, 任务, 原因 = 译.收输出(实机坏原文, s, 用途="心跳")
    试("B2 ★ 实机那份坏任务书被拒了", 任务 is None and 原因, f"任务={任务} 原因={原因}")
    含("B2b 拒单理由里点明了「目标」", 原因, "目标")
    含("B2c 拒单理由里告诉了正确写法", 原因, "p=[x,y,z]")

    动作, 任务, 原因 = 译.收输出(实机对原文, s, 用途="心跳")
    试("B3 改对之后能过", 任务 is not None and not 原因, f"原因={原因}")
    步 = (任务 or {}).get("步骤") or []
    试("B3b 拿到的是干净的 3 步",
       len(步) == 3 and 步[0].get("p") == [-38, 50, -23], str(步[:1]))

    # 主链自己的宪法检查要**优先**（不能被体检盖成「缺 p」）
    动作, 任务, 原因 = 译.收输出(
        '{"任务":{"名字":"x","步骤":[{"动作":"打","名":"猪"}]}}', s, 用途="心跳")
    试("B4 ★ 主链的宪法检查优先：不许有「打」", 任务 is None)
    含("B4b 理由说的是宪法那条，不是字段那条", 原因, "不许有")

    试("B5 坐标太远还是主链自己拦（体检不越权）",
       译.收输出('{"任务":{"名字":"x","步骤":[{"动作":"走到","p":[999,64,999]}]}}',
                s, 用途="心跳")[1] is None)
    return 列, 译, s, 栈


# ══════════════════════════ C 组：拒单反馈 ══════════════════════════

def C组(列, 译, s, 体检模块, 反馈模块):
    print("── C 组：拒单反馈 ──")
    反馈模块._被拒.clear()

    文0 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    试("C1 还没被拒过时，prompt 里没有那段提醒",
       "被退回来了" not in 文0)

    译.收输出(实机坏原文, s, 用途="心跳")
    文1 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    试("C2 ★ 被拒之后，prompt 里出现了提醒", "被退回来了" in 文1)
    含("C2b 提醒里带着退回原因", 文1, "目标")
    含("C2c 提醒里引用了模型当时的原文", 文1, "copper_ore")
    含("C2d 提醒里告诉它该怎么改", 文1, "一个字都不差")

    试("C2e 提醒是**追加**在后面，原有内容没被挤掉",
       "【你要输出的东西】" in 文1)

    译.收输出(实机对原文, s, 用途="心跳")
    文2 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    试("C3 ★ 改对之后，那段提醒就没了（不念旧账）", "被退回来了" not in 文2)

    # 陈旧记录
    反馈模块.记一笔("心跳", "这是很久以前的错", "很久以前写的")
    反馈模块._被拒["心跳"][-1]["t"] = time.time() - 99999
    文3 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    试("C4 ★ 超过 15 分钟的旧账不再念叨", "很久以前的错" not in 文3)

    # 字数上限
    反馈模块._被拒.clear()
    for i in range(9):
        反馈模块.记一笔("心跳", f"第 {i} 条很长的退回原因" + "啰" * 120, "原" * 300)
    文4 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    段 = 文4[文4.find("【★ 你上一次"):] if "【★ 你上一次" in 文4 else ""
    试("C5 ★ 提醒有字数硬顶（不会把 prompt 挤爆）",
       len(段) <= 反馈模块.提醒上限 + 40, f"实际 {len(段)} 字")
    试("C5b 但至少还留着最近的一条", "第 8 条" in 文4 or "第 7 条" in 文4)

    # 其他车厢写进 prompt 的内容不能被吃掉
    文5 = 译.组Prompt(s, 用途="心跳", 任务状况="没有任务")
    试("C6 受限脚本的剧本说明还在（组Prompt 包壳链没断）",
       "重复 5 次 记作 i" in 文5, "受限脚本那节好像被盖掉了")
    反馈模块._被拒.clear()


# ══════════════════════════ D 组：热插拔真的生效 ══════════════════════════

def D组(列, 译, s):
    print("── D 组：热插拔真的生效 ──")
    列.摘("任务书体检")
    _, 任务, 原因 = 译.收输出(实机坏原文, s, 用途="聊天")
    试("D1 ★ 摘掉体检之后，那份坏任务书又能过了（证明车厢真在起作用）",
       任务 is not None and not 原因, f"还是被拒：{原因}")

    列.挂("任务书体检")
    _, 任务, 原因 = 译.收输出(实机坏原文, s, 用途="聊天")
    试("D2 ★ 挂回来之后又被拒了", 任务 is None and 原因, f"居然过了：{任务}")

    列.摘("拒单反馈")
    文 = 译.组Prompt(s, 用途="聊天", 任务状况="没有任务")
    试("D3 摘掉反馈之后，提醒也不再出现", "被退回来了" not in 文)
    列.挂("拒单反馈")

    列.换轨([], 理由="D组收尾")
    试("D4 收尾：摘干净", 列.编组 == [], str(列.编组))


# ══════════════════════════ 主流程 ══════════════════════════

def 主():
    sys.path.insert(0, 外挂根)
    sys.path.insert(0, ROOT)
    import 车钩
    import bridge
    import importlib

    临时 = tempfile.mkdtemp(prefix="任务书测试-")
    try:
        # 测试**不许**动真的 外挂/编组.json 和插座
        车钩.编组文件 = os.path.join(临时, "编组.json")
        车钩.插座路径 = os.path.join(临时, "车钩.sock")

        # ★ 两节车厢的入口**都叫 补丁.py** —— 直接 import 会撞名
        #   （后载的顶掉先载的）。所以走车钩自己的载入器，它按文件路径载、
        #   模块名带车厢 id。这里顺便把这条也验了。
        表 = 车钩.发现车厢()
        车钩.载入车厢(表["任务书体检"])
        车钩.载入车厢(表["拒单反馈"])
        体检模块 = 表["任务书体检"].模块
        反馈模块 = 表["拒单反馈"].模块
        试("A0 两节车厢的入口模块是**两个不同的对象**（没撞名）",
           体检模块 is not 反馈模块,
           "两个模块居然是同一个 —— sys.modules 撞名了")

        A组(体检模块)
        列, 译, s, 栈 = B组(bridge, 车钩, 临时, 表)
        C组(列, 译, s, 体检模块, 反馈模块)
        D组(列, 译, s)
    finally:
        shutil.rmtree(临时, ignore_errors=True)

    import hashlib
    指纹 = hashlib.sha256(open(os.path.join(ROOT, "bridge.py"), "rb").read()).hexdigest()
    试("Z1 主链 sha256 还是 a649665c970d84ba（自始至终没被动过）",
       指纹.startswith("a649665c970d84ba"))

    print(f"\n{'═' * 62}")
    print(f"任务书体检 + 拒单反馈：{len(通过)} 过 / {len(失败)} 失败")
    for x in 通过:
        print(f"  ✅ {x}")
    for x in 失败:
        print(f"  ❌ {x['名']} —— {x['为啥']}")
    print("═" * 62)
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(主())
