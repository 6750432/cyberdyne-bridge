"""车钩离线测试 —— 证明「随时连/断、自由组合」是真的，不是嘴上说说。

┌───────────────────────────────────────────────────────────────────┐
│ 这个测试最值钱的部分是 D 组和 H 组                                 │
└───────────────────────────────────────────────────────────────────┘
车厢机制本质上是「给了一段代码随便改内存的权力」。所以真正要证明的不是
「能挂上去」，而是：

    D 组：**一辆想偷偷扩权的车厢，能不能被当场抓住并退回**
    H 组：**一项正在被使用的本事，能不能被摘走**（不能）

A/B/C/E/F 是功能，D/H 是安全。安全那两组红了，这列车就不该上路。

跑法：
    python3 外挂/测车钩.py           全部跑
    python3 外挂/测车钩.py --json    机器看的
退出码：0 全过 / 1 有失败
"""

import json
import os
import shutil
import sys
import tempfile
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
外挂根 = os.path.join(ROOT, "外挂")

通过 = []
失败 = []


def 过(名, 为啥=""):
    通过.append(名)
    if 为啥:
        pass


def 挂(名, 为啥):
    失败.append({"名": 名, "为啥": 为啥})


def 试(名, 条件, 为啥="条件不成立"):
    if 条件:
        过(名)
    else:
        挂(名, 为啥)
    return bool(条件)


def 试抛(名, 函数, 异常类, 关键词=""):
    """必须抛出某种异常 —— 用来证明「闸真的拦了」而不是「悄悄放过」。"""
    try:
        函数()
    except 异常类 as e:
        if 关键词 and 关键词 not in str(e):
            挂(名, f"拦住了但理由不对：「{e}」里没有「{关键词}」")
        else:
            过(名)
        return True
    except Exception as e:
        挂(名, f"抛了意料之外的 {type(e).__name__}: {e}")
        return False
    挂(名, "**该拦却放过了**（一点动静都没有）")
    return False


# ══════════════════════════ 假车厢工厂 ══════════════════════════

def 造车厢(根, 名, 正文, 清单=None, 有卸下=True):
    """在测试沙箱里造一辆车厢。**不碰真的 外挂/ 目录。**"""
    目录 = os.path.join(根, 名)
    os.makedirs(目录, exist_ok=True)
    牌 = {"id": 名, "名字": f"测试车厢 {名}", "版本": "0.1", "入口": "补丁.py"}
    if 清单:
        牌.update(清单)
    with open(os.path.join(目录, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(牌, f, ensure_ascii=False)
    码 = textwrap.dedent(正文)
    if 有卸下 and "def 卸下" not in 码:
        码 += "\n\ndef 卸下(bridge):\n    return True\n"
    with open(os.path.join(目录, "补丁.py"), "w", encoding="utf-8") as f:
        f.write(码)
    return 目录


def 干净车厢(名):
    """一辆规矩的、什么坏事都不干的车厢。"""
    return f'''
    _已装 = False

    def 装上(bridge, 开关=True, 车钩=None, 日志=None):
        global _已装
        if not 开关:
            return {{"好": False, "打了": [], "为什么": "开关关着"}}
        if _已装:
            return {{"好": False, "打了": [], "为什么": "已经打过了"}}
        _已装 = True
        bridge._{名}记号 = True
        return {{"好": True, "为什么": "", "打了": ["打了 {名}"]}}


    def 卸下(bridge):
        global _已装
        if not _已装:
            return False
        _已装 = False
        if hasattr(bridge, "_{名}记号"):
            del bridge._{名}记号
        return True
    '''


# ══════════════════════════ 主流程 ══════════════════════════

def 主():
    json输出 = "--json" in sys.argv
    临时 = tempfile.mkdtemp(prefix="车钩测试-")
    try:
        _跑(临时, json输出)
    finally:
        shutil.rmtree(临时, ignore_errors=True)

    主链没问题 = _查主链()
    过("Z1 主链 sha256 还是 a649665c970d84ba（自始至终没被动过）") \
        if 主链没问题 else 挂("Z1 主链指纹", "**主链被改了！**")

    if json输出:
        print(json.dumps({"通过": 通过, "失败": 失败,
                          "过": len(通过), "挂": len(失败)},
                         ensure_ascii=False, indent=1))
    else:
        print(f"\n{'═' * 62}")
        print(f"车钩测试：{len(通过)} 过 / {len(失败)} 失败")
        for x in 通过:
            print(f"  ✅ {x}")
        for x in 失败:
            print(f"  ❌ {x['名']} —— {x['为啥']}")
        print("═" * 62)
    return 1 if 失败 else 0


def _查主链():
    import hashlib
    try:
        with open(os.path.join(ROOT, "bridge.py"), "rb") as f:
            return hashlib.sha256(f.read()).hexdigest().startswith("a649665c970d84ba")
    except OSError:
        return False


