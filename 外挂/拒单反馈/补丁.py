#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""拒单反馈·车厢本体 —— 被退回来的原因，要**喂回给模型**。

┌───────────────────────────────────────────────────────────────────┐
│ 为什么光有校验还不够                                               │
└───────────────────────────────────────────────────────────────────┘
2026-10-07 实机看到的循环：

    心跳 → 模型写一份任务书 → 被拒 → 心跳记一笔「被校验拒了」
         → 心跳记着「连续失败 2 次就退避 5 分钟」→ 退避完再来一遍
         → **模型完全不知道上次为什么被拒，于是原样再写一遍**

主链其实**把原因记下来了**（`bridge.py:2843` 那条
`{"事件": "被校验拒了", "原因": 原因, "原文": 原文[:400]}`），
但它只写进账本，**没有回到下一次的 prompt 里**。

于是模型是在**盲改**。它唯一的反馈是「连续失败」这个次数 ——
知道「我错了」，不知道「我错在哪」。

┌───────────────────────────────────────────────────────────────────┐
│ 它做的两件事                                                       │
└───────────────────────────────────────────────────────────────────┘
① 包住 `翻译器.收输出()` —— 它返回 `(动作, 任务, 原因)`：
      原因 非空 = 被拒了 → 把原因和**模型当时写的原文**记下来
      成功            → 把这一类的旧账清掉（它改对了，别再念叨）

② 包住 `翻译器.组Prompt()` —— 在原有 prompt 后面补一段：

      【★ 你上一次交上来的东西被退回来了】
        · 退回原因：第 1 步「走到」里有不认识的字段：目标；它需要 p…
          你当时写的是："{"任务":{"名字":"看看铜矿","步骤":[{"动作":"走到",…
        请照上面的原因改好再交一次。**字段名要一模一样**。

★ 顺序：本车厢顺序=40，排在最外面。它调完里面那几层的组Prompt
  才追加自己的 —— 所以动作面和受限脚本写进 prompt 的内容一个字不少。

┌───────────────────────────────────────────────────────────────────┐
│ 节流                                                               │
└───────────────────────────────────────────────────────────────────┘
· 只有 15 分钟以内的被拒记录才会被念叨（陈年老账翻出来只会占 token）
· 每一类「用途」（心跳 / 闲聊）最多记 2 条
· 整段提醒硬顶 600 字 —— prompt 是有额度的，不能把正文挤没了
"""

import os
import sys
import time

_原 = {}
_已装 = False
_主链 = None
_记 = None

# 用途 -> [{"原因":…, "原文":…, "t":…}]，最近的在后面
_被拒 = {}
统计 = {"记下被拒": 0, "清掉旧账": 0, "喂回去次数": 0}

时效秒 = 900          # 超过这个岁数的记录不再念叨
每类最多 = 2          # 每一类最多念叨几条
提醒上限 = 600        # 整段提醒的字数硬顶
原文上限 = 180        # 引用模型原文的字数上限


def _说(文本):
    if _记:
        _记(文本, 屏幕=False)


def 记一笔(用途, 原因, 原文):
    条 = _被拒.setdefault(用途 or "翻译", [])
    条.append({"原因": str(原因)[:200],
              "原文": str(原文 or "").strip()[:原文上限],
              "t": time.time()})
    del 条[:-每类最多]          # 只留最近几条
    统计["记下被拒"] += 1
    _说(f"拒单反馈：记下「{用途}」的一次退回 —— {str(原因)[:60]}")


def 清旧账(用途):
    if _被拒.pop(用途 or "翻译", None) is not None:
        统计["清掉旧账"] += 1


def 提醒(用途, 现在=None):
    """生成要追加到 prompt 后面那一段。没有就返回空串。"""
    现在 = 现在 or time.time()
    条 = [x for x in (_被拒.get(用途 or "翻译") or [])
          if 现在 - x["t"] < 时效秒]
    if not 条:
        return ""
    行 = ["【★ 你上一次交上来的东西被退回来了，先看这个再动手】"]
    for x in 条[-每类最多:]:
        行.append(f"  · 退回原因：{x['原因']}")
        if x["原文"]:
            行.append(f"    你当时写的是：{x['原文']}")
    行.append("  请照上面的原因改好再交一次。**字段名必须和规格一个字都不差**，"
             "写错名字等于没写；缺的字段要补上。")
    文 = "\n".join(行)
    if len(文) > 提醒上限:
        文 = 文[:提醒上限 - 20] + "\n（…太长，砍掉了一些）"
    统计["喂回去次数"] += 1
    return 文


# ══════════════════════════ 装上 / 卸下 ══════════════════════════

def 装上(bridge, 开关=True, 车钩=None, 日志=None):
    global _已装, _主链, _记
    if not 开关:
        return {"好": False, "打了": [],
                "为什么": "开关关着 —— 一个补丁都不打（行为与基线逐字节相同）"}
    if _已装 or getattr(bridge, "_拒单反馈外挂", None):
        return {"好": False, "打了": [], "为什么": "已经打过了，不重复打"}
    _主链, _记 = bridge, 日志

    译 = getattr(bridge, "翻译器", None)
    if 译 is None:
        return {"好": False, "打了": [], "为什么": "主链上没有 翻译器 —— 拒绝打补丁"}
    for 名 in ("收输出", "组Prompt"):
        if not callable(getattr(译, 名, None)):
            return {"好": False, "打了": [],
                    "为什么": f"主链上没有 翻译器.{名}() —— 拒绝打补丁"}

    # ★ `bridge.翻译器` 就是类本身（见 任务书体检/补丁.py 里那条同款教训）
    译类 = 译
    _原["收输出"] = 译类.收输出
    _原["组Prompt"] = 译类.组Prompt
    打 = []

    # ── ① 收输出：记下被拒的原因 ──
    def 新收输出(self, 文本, s, 用途="翻译"):
        动作, 任务, 原因 = _原["收输出"](self, 文本, s, 用途=用途)
        if 原因:
            记一笔(用途, 原因, 文本)
        elif 任务 is not None or 动作 is not None:
            清旧账(用途)          # 它改对了，别再念叨
        return 动作, 任务, 原因

    译类.收输出 = 新收输出
    打.append("翻译器.收输出()  ← 记下被拒的原因与原文；改对了就清账")

    # ── ② 组Prompt：把旧账念叨回去 ──
    def 新组Prompt(self, s, 用途="翻译", 任务状况="没有任务", 说话人=None, 原话=None):
        文 = _原["组Prompt"](self, s, 用途=用途, 任务状况=任务状况,
                            说话人=说话人, 原话=原话)
        if not isinstance(文, str):
            return 文
        补 = 提醒(用途)
        return (文 + "\n\n" + 补) if 补 else 文

    译类.组Prompt = 新组Prompt
    打.append("翻译器.组Prompt()  ← 追加「上次为什么被退回来」（包壳，先调里面那层）")

    bridge._拒单反馈外挂 = True
    _已装 = True
    return {"好": True, "为什么": "", "打了": 打}


def 卸下(bridge):
    global _已装
    if not _已装:
        return False
    译 = getattr(bridge, "翻译器", None)
    if 译 is not None:
        译类 = 译
        for 名 in ("收输出", "组Prompt"):
            if 名 in _原:
                setattr(译类, 名, _原[名])
    _原.clear()
    _被拒.clear()          # 摘了就不该再念叨
    if hasattr(bridge, "_拒单反馈外挂"):
        del bridge._拒单反馈外挂
    _已装 = False
    return True


def 报个话(bridge):
    return {"装上": _已装, "统计": dict(统计),
            "还记着": {k: len(v) for k, v in _被拒.items()},
            "记号": bool(getattr(bridge, "_拒单反馈外挂", None))}
