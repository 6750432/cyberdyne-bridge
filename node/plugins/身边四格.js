'use strict';
/**
 * 身边四格.js —— 「我身边那 4 格」永远要报（手侧的小工具）
 *
 * 为什么要有它（2026-10-09 实机，主人的 P0-1 那一场）
 * ================================================
 * 脑侧「放东西」这一步得先知道**旁边哪一格是空的** ✓
 * 而它是靠雷达（`watch_blocks`）拿到的 ✗ —— 可**任务一结束，主链会 `_撤探针`
 * 把雷达整个清空**（`watch_blocks: []` 在协议里就是"显式清空"）✓
 * → 「生存常识」刚指过去的 4 格，下一秒就被抹掉 ✓
 * → 实机表现（原话）：
 *      [探针-落坐标后] 步骤=0 ｜ 因=雷达还没盯我身边那 4 格（放crafting_table要先知道旁边哪格是空的）
 *      它说「（已把雷达指过去）」→ 下一轮**又是同一句** ✓ 五分钟一步没动 ✗
 *
 * 规矩：**身边那几格是"我本来就该知道的"** ✓
 *   一个玩家不用谁去"指"，就知道自己旁边是不是空的 ✓
 *   雷达是"额外盯着远处的东西"✓ —— 两者不是一回事，别混在一起 ✗
 *   （也不违反反矿透：挨着我的那 4 格，肉眼本来就看得到 ✓）
 *
 * ⚠ 坐标口径：跟脑侧 `身边空位()` 对齐 ——
 *   `x = floor(pos.x)`、`y = floor(pos.y)`（**脚底下那一层**）、`z = floor(pos.z)` ✓
 *   （`pos` 是"脚的位置"，不是眼睛 ✓ —— 眼睛在脚上方 ~1.62）
 */

/** 我身边那 4 个"手能够到"的相邻格：[+x, -x, +z, -z]（跟脑侧同一个顺序 ✓） */
function 身边四格(我) {
  // ⚠ 光查 `typeof === 'number'` **挡不住 NaN / Infinity** ✗
  //   （NaN 的 typeof 也是 'number' ✓ —— 用例 S7 当场把它抓出来了 ✓）
  if (!我 || !Number.isFinite(我.x) || !Number.isFinite(我.y) || !Number.isFinite(我.z)) {
    return [];
  }
  const x = Math.floor(我.x);
  const y = Math.floor(我.y);
  const z = Math.floor(我.z);
  return [[x + 1, y, z], [x - 1, y, z], [x, y, z + 1], [x, y, z - 1]];
}

/**
 * 把「身边四格」补进要盯/要报的格子表里（去重；**排在最前面** ✓）。
 *
 * ⚠ 为什么排最前面：手侧 `看的方块` 只有 32 个名额，而且**新的从尾巴挤旧的** ✓
 *   身边这 4 格要是排在后面，一忙起来就会被挤掉 ✗（那就又回到今天那个坑 ✓）
 */
function 补齐身边四格(看, 我) {
  const 出 = [];
  const 见过 = new Set();
  const 加 = (p) => {
    if (!Array.isArray(p) || p.length < 3) return;
    const 键 = p.join(',');
    if (见过.has(键)) return;
    见过.add(键);
    出.push(p);
  };
  for (const p of 身边四格(我)) 加(p);            // ★ 身边先占位 ✓
  for (const p of (Array.isArray(看) ? 看 : [])) 加(p);
  return 出;
}

module.exports = { 身边四格, 补齐身边四格 };
