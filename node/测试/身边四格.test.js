#!/usr/bin/env node
'use strict';
/*
 * 「我身边那 4 格」—— 离线断言。
 *
 * 为什么要有它（主人 2026-10-09 的 P0-1 那一场）
 * ============================================
 * 实机原话（脑侧探针，一遍又一遍）：
 *   [探针-落坐标后] 步骤=0 ｜ 因=雷达还没盯我身边那 4 格
 *     （放crafting_table要先知道旁边哪格是空的）
 *   它说「（已把雷达指过去）」→ 下一轮**又是同一句** ✓ 五分钟一步没动 ✗
 *
 * 根子：脑侧"放东西"要靠雷达知道旁边哪格是空的 ✓
 *   可**任务一结束，主链会 `_撤探针` 把雷达整个清空**（空列表 = 显式清空 ✓）
 *   → 「生存常识」刚指过去的 4 格，下一秒就被抹掉 ✓
 *
 * 规矩：**身边那几格是"我本来就该知道的"** ✓ 不该等谁来指 ✓
 *   （也不违反反矿透 —— 挨着我的那 4 格，肉眼本来就看得到 ✓）
 *
 * 跑法：node --test node/测试/身边四格.test.js
 */
const test = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const { 身边四格, 补齐身边四格 } = require(path.join(__dirname, '..', 'plugins', '身边四格.js'));

test('S1 ★★★ 四个方向都算（跟脑侧「身边空位()」同一套口径）', () => {
  const 出 = 身边四格({ x: 10.5, y: 64.0, z: 20.5 });
  assert.deepStrictEqual(出, [
    [11, 64, 20], [9, 64, 20], [10, 64, 21], [10, 64, 19],
  ], '四格算错了：' + JSON.stringify(出));
});

test('S2 ★★★ y 取的是**脚底下那一层**（floor(pos.y)），不是眼睛', () => {
  // ⚠ 这一条是对着脑侧 `身边空位()` 的读法定的：
  //   它写的是 `int(我[1])`，而 `我` 就是状态帧里的 `pos` —— **脚的位置** ✓
  //   （眼睛在脚上方 ~1.62；要是按下取整成"眼睛那一层"，
  //     算出来的 4 格会整整高一格 ✗ —— 那就永远"没读数" ✓）
  // ⚠ 负数取整我自己先算错过一次 ✗：floor(-149.5) = **-150**（不是 -149）
  //   （用例红了先看自己 ✓ —— 这一条今天记了不知道第几遍了）
  const 出 = 身边四格({ x: -149.5, y: 74.0, z: 156.5 });
  assert.deepStrictEqual(出, [
    [-149, 74, 156], [-151, 74, 156], [-150, 74, 157], [-150, 74, 155],
  ], 'y 或 x/z 的取整不对：' + JSON.stringify(出));
});

test('S3 ★★ 半格位置也能对（玩家坐标永远是 *.5）', () => {
  const 出 = 身边四格({ x: -143.5, y: 76.5, z: 156.5 });
  // ⚠ 76.5 是"跳起来的半路" —— floor 给 76（脚底下那一层）✓ 跟脑侧一致 ✓
  assert.deepStrictEqual(出, [
    [-143, 76, 156], [-145, 76, 156], [-144, 76, 157], [-144, 76, 155],
  ], JSON.stringify(出));
});

test('S4 ★★★ 身边四格**排在最前面**（手侧只有 32 个名额，新的从尾巴挤旧的）', () => {
  // 手侧 `看的方块` 的名额是 32 个、而且**新的从尾巴挤旧的** ✓
  // 身边这 4 格要是排在后面，一忙起来就会被挤掉 ✗
  // ——那就是今天这个坑的翻版 ✓
  const 看 = [[1, 2, 3], [4, 5, 6]];
  const 出 = 补齐身边四格(看, { x: 10.0, y: 64.0, z: 20.0 });
  assert.deepStrictEqual(出.slice(0, 4), 身边四格({ x: 10.0, y: 64.0, z: 20.0 }),
    '身边四格没排在最前面：' + JSON.stringify(出));
  assert.deepStrictEqual(出.slice(4), 看, '原来的格子被弄丢或改序了：' + JSON.stringify(出));
});

test('S5 ★★ 雷达那几格**一个都不许少**（原来是它负责报的，别被挤掉）', () => {
  const 看 = [];
  for (let i = 0; i < 40; i++) 看.push([i, 64, 0]);      // 比 32 还多（手侧会截）
  const 出 = 补齐身边四格(看, { x: 0.0, y: 64.0, z: 0.0 });
  // ⚠ 看里**本来就有** [1,64,0]（那是身边的一格）→ 去重之后是 40+3 ✓
  //   （第一版我按 40+4 写，红了自己才发现 ✓ 又是"用例算错" ✓）
  assert.strictEqual(出.length, 40 + 3,
    '补齐之后条数不对（重了或丢了）：' + 出.length);
  assert.strictEqual(new Set(出.map((p) => p.join(','))).size, 出.length, '有重复的格子 ✗');
});

test('S6 ★★ 身边那 4 格本来就在雷达里 → **不重复**（去重）', () => {
  const 我 = { x: 10.0, y: 64.0, z: 20.0 };
  const 四 = 身边四格(我);
  const 出 = 补齐身边四格(四.concat([[99, 64, 99]]), 我);
  assert.strictEqual(出.length, 5, '去重没生效：' + JSON.stringify(出));
  assert.strictEqual(出.filter((p) => p.join(',') === '11,64,20').length, 1, '有重复的 ✗');
});

test('S7 ★★ 拿不到自己的位置 → 老实返回空（不许瞎编一格出来 ✗）', () => {
  assert.deepStrictEqual(身边四格(null), []);
  assert.deepStrictEqual(身边四格(undefined), []);
  assert.deepStrictEqual(身边四格({}), []);
  assert.deepStrictEqual(身边四格({ x: NaN, y: 1, z: 2 }), []);
});

test('S8 ★★★ 接线：`方块快照()` 里**真的**调了它（源码不变量）', () => {
  // ⚠ 为什么这么验：`server.js` 一 require 就把服务器起起来 ✗ 没法当模块引 ✓
  //   而"工具写好了、可压根没接上"正是今天栽过的那类事
  //   （`先挖` 写好了、可"被整个埋住"那一支没接 ✓ 五分钟一步没动 ✓）
  //   所以这里退一步：**验源码里那根线在** ✓ 功能上由实机那一场兜底 ✓
  const fs = require('node:fs');
  const 源 = fs.readFileSync(path.join(__dirname, '..', 'server.js'), 'utf8');
  const 快照 = 源.slice(源.indexOf('function 方块快照()'), 源.indexOf('function 物品快照()'));
  assert.ok(快照.length > 50, '找不到 方块快照() —— 主链改名了？');
  assert.match(快照, /补齐身边四格\(/,
    '方块快照() 里**没有**补身边四格 ✗ —— 那 4 格又会"任务一结束就被清空" ✓');
  assert.ok(!/!看的方块\.length\)\s*return null/.test(快照),
    '方块快照() 还留着"雷达空就直接返回 null"那道闸 ✗ —— 那身边那 4 格照样报不出去 ✓');
});
