"""M4c·任务栈的离线回归。

为什么必须离线先验：任务栈是"时间 + 事实 + 优先级"三样拧在一起的东西 ——
在游戏里"看它干完没干完"永远说不清是哪一条没生效。这里用手工造的事实帧
（虚拟时钟 + 假的方块/物品/熔炉探针）把每条规则单独拧出来验：

  ① fail-closed（清单外的动作一律拒绝）
  ② 多步推进 + 进度可查
  ③ 完成判据看事实（走到 / 挖 / 拾 / 熔炉）
  ④ 失败重试（含退避、原因、上限）与"挖不动"的快速判死
  ⑤ ★ wait_until：**不发任何动作**、独立超时、超时不进退避重试
  ⑥ ★ 反射层一票否决：同一拍里下发的是反射层的动作，任务被暂停
  ⑦ 暂停与恢复：**从断点继续**；暂停太久算这一步失败
  ⑧ 中止、替换、探针挂载与撤下

用法：
    python3 tools/测任务.py [-v]
退出码：0 = 全过；1 = 有失败。
"""
import argparse
import json
import os
import shutil
import sys
import tempfile
