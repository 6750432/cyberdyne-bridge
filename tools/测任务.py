ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ── 虚拟时钟必须在 import bridge 之前装好（和 回放.py / 测猎手.py 同一套路）──
_虚拟 = [1000.0]
_时间.time = lambda: _虚拟[0]

sys.path.insert(0, ROOT)
import bridge  # noqa: E402

CFG = json.load(open(os.path.join(ROOT, "config.json"), encoding="utf-8"))
日志目录 = tempfile.mkdtemp(prefix="测任务-")

通过, 失败 = [], []
详细 = False


def 断言(名, 条件, 实际=None):
    行 = f"{'✅' if 条件 else '❌'} {名}" + (f"　实际：{实际}" if (实际 is not None and not 条件) else "")
    (通过 if 条件 else 失败).append(行)
    if 详细 or not 条件:
        print(行)


def 造帧(我=(0.0, 78.0, 0.0), 血=20.0, 方块=None, 物品=None, 熔炉=None,
         敌人=(), 掉落=(), 玩家=(), 食物=20):
    """造一帧"事实"。方块={坐标元组: 名字}、物品={名字: 数量}、熔炉=探针读数。"""
    块 = [{"p": list(k), "name": v} for k, v in (方块 or {}).items()]
    threats = [{"name": 名, "kind": "hostile", "dist": 距, "pos": [我[0] + 距, 我[1], 我[2]]}
               for 名, 距 in 敌人]
    return {
        "type": "state", "connected": True, "t": _虚拟[0] * 1000,
        "pos": list(我), "hp": float(血), "food": 食物, "onGround": True,
        "threats": threats,
        "players": [{"name": 名, "dist": 距, "pos": [我[0], 我[1], 我[2] + 距],
                     "hostile": bool(敌对)} for 名, 距, 敌对 in 玩家],
        "friends": [], "weapons": [{"name": "iron_sword", "count": 1}],
        "foods": [{"name": "cooked_beef", "count": 16}], "drops": list(掉落),
        "plugins": {"pathfinder": True, "body": True},
        "blocks": 块 or None, "items": 物品, "furnace": 熔炉,
        "watched": None, "respawned": False, "acting": "idle", "held": "iron_sword",
        "near": [], "look": {"yaw": 0.0, "pitch": 0.0}, "msg": None,
        "deaths": 0, "attacked_by": None, "stuck_count": 0, "stuck_ms": None,
    }


def 建栈(**改):
    m4 = dict(CFG["m4"])
    m4["task_enable"] = True
    m4.update(改)
    说 = lambda *a, **k: None
    返 = bridge.任务栈(m4, 说, lambda o: None, 日志目录)
    return 返


def 走(栈, 秒=0.2, **帧参):
    _虚拟[0] += 秒
    帧 = 造帧(**帧参)
    命令 = []
    栈.发 = 命令.append
    占 = 栈.跑(帧)
    return 占, 命令


def 读日志():
    路 = os.path.join(日志目录, "任务.jsonl")
    if not os.path.exists(路):
        return []
    with open(路, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def 清日志():
    try:
        os.remove(os.path.join(日志目录, "任务.jsonl"))
    except Exception:
        pass


