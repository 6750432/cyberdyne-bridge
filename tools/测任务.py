def 用例_多步与进度():
    清日志()
    栈 = 建栈()
    好 = 栈.接("去一趟再回来", bridge.搭去回任务([10, 78, 5]), 造帧())
    断言("正常任务接单成功", 好 is True and 栈.在跑())
    断言("进度一句话能说清第几步", "第 1/4 步" in 栈.进度一句话(), 栈.进度一句话())

    # 第 1 步：走到 (10,78,5) —— 远处不完成、近处完成
    _, 命令 = 走(栈, 我=(0, 78, 0))
    断言("走到：没到就下发 goto", any(c.get("act") == "goto" for c in 命令), 命令)
    走(栈, 我=(3, 78, 2), 秒=3.0)          # 重下节流 + 还没到
    断言("走到：还差一点不算完成", 栈.任务["第几步"] == 0, 栈.任务["第几步"])
    走(栈, 我=(9.5, 78, 4.6))
    断言("走到：进到点半径 → 进下一步", 栈.任务["第几步"] >= 1, 栈.任务["第几步"])

    # 第 2 步是「说」：要发出 say 才算完
    _, 命令 = 走(栈, 我=(9.5, 78, 4.6))
    说命令 = [c for c in 命令 if c.get("cmd") == "say"]
    断言("「说」这一步真的说了", bool(说命令), 命令)
    走(栈, 我=(9.5, 78, 4.6))
    断言("说完就往下走", 栈.任务["第几步"] >= 2, 栈.任务["第几步"])

    # 剩下的：走回起点 + 再说一句 → 任务完成
    for _ in range(3):
        走(栈, 我=(0, 78, 0), 秒=3.0)
    断言("任务最终完成", 栈.任务["状态"] == "完", 栈.任务["状态"])
    记 = 读日志()
    断言("任务日志里有每一步的开始/完成",
         sum(1 for e in 记 if e.get("事件") == "步骤开始") >= 4
         and any(e.get("事件") == "任务完成" for e in 记),
         [e.get("事件") for e in 记][:12])
    命令2 = []
    栈.发 = 命令2.append
    栈.接("再走一趟", [{"动作": "走到", "p": [0, 78, 0], "到点": 2.5}], 造帧(我=(0, 78, 0)))
    走(栈, 秒=3.0, 我=(0, 78, 0))
    断言("任务完成时把探针撤下来（快照不白胖）",
         any(c.get("cmd") == "watch_blocks" and c.get("list") == [] for c in 命令2), 命令2)


def 用例_挖与拾看事实():
    清日志()
    栈 = 建栈()
    步 = [{"动作": "走到", "p": [5, 79, 5], "到点": 3.0},
          {"动作": "挖", "p": [5, 78, 5]},
          {"动作": "拾", "物品": None, "看方块": [5, 78, 5], "数量": 1}]
    栈.接("挖一格", 步, 造帧(我=(0, 78, 0)))
    走(栈, 秒=0.3, 我=(0, 78, 0), 方块={(5, 78, 5): "stone"},
       物品={"iron_pickaxe": 1})     # 远处：还在"走到"
    断言("走到没到 → 还停在第 1 步", 栈.任务["第几步"] == 0, 栈.任务["第几步"])
    # 探针还没到货（blocks 为 None）时，绝不能算"挖完了"
    _, _ = 走(栈, 秒=0.3, 我=(5, 79, 5), 方块=None, 物品={"iron_pickaxe": 1})
    断言("进入挖这一步了，但探针没到货（None）时绝不算挖完",
         栈.任务["第几步"] <= 1 and not (栈.任务["第几步"] > 1), 栈.任务["第几步"])
    _, 命令 = 走(栈, 秒=3.0, 我=(5, 79, 5), 方块={(5, 78, 5): "stone"},
               物品={"iron_pickaxe": 1})   # 到了 → 进"挖"
    断言("走到了 → 进「挖」这一步", 栈.任务["第几步"] == 1, 栈.任务["第几步"])
    for _ in range(4):
        _, 命令 = 走(栈, 秒=1.5, 我=(5, 79, 5), 方块={(5, 78, 5): "stone"},
                   物品={"iron_pickaxe": 1})
    断言("挖：方块还是石头 → 不下发完成、并且真的在挖",
        栈.任务["第几步"] == 1 and any(c.get("cmd") == "dig" for c in 命令), 命令)
    # 方块变空气 → 挖完成；紧接着「拾」要能自己认出该盯 cobblestone
    走(栈, 我=(5, 79, 5), 方块={(5, 78, 5): "air"},
       物品={"cobblestone": 0, "iron_pickaxe": 1})
    断言("挖：探针说变空气 → 算完成", 栈.任务["第几步"] >= 2, 栈.任务["第几步"])
    步2 = 栈.任务["步骤"][2]
    断言("拾：从方块探针认出该拾 cobblestone", 步2.get("物品") == "cobblestone", 步2)
    走(栈, 秒=0.2, 我=(5, 78, 5), 物品={"cobblestone": 1, "iron_pickaxe": 1},
       方块={(5, 78, 5): "air"})
    断言("拾：物品探针够数 → 完成", 栈.任务["状态"] in ("完",), 栈.任务["状态"])


def 用例_挖不动快速判死与重试():
    清日志()
    栈 = 建栈(每步重试上限=2)
    栈.接("挖基岩", [{"动作": "挖", "p": [0, 78, 0]}], 造帧())
    _, 命令 = 走(栈, 方块={(0, 78, 0): "bedrock"})
    记 = 读日志()
    断言("挖不动的方块 → 立刻判失败（不用等 60 秒超时）",
         any(e.get("事件") == "步骤失败" and "挖不动" in str(e.get("原因")) for e in 记),
         [e.get("事件") for e in 记])
    断言("失败之后进入重试并记账（第 1 次）",
         any(e.get("事件") == "重试" and e.get("第几次") == 1 for e in 记),
         [e.get("原因") for e in 记 if e.get("事件") == "重试"])
    # 退避期间不下发
    _, 命令 = 走(栈, 秒=0.3, 方块={(0, 78, 0): "bedrock"})
    断言("退避期间不下发动作", 命令 == [], 命令)
    for _ in range(6):
        走(栈, 秒=2.0, 方块={(0, 78, 0): "bedrock"})
    断言("重试用完 → 任务判失败（状态=败）", 栈.任务["状态"] == "败", 栈.任务["状态"])
    记 = 读日志()
    断言("失败原因具体（带方块名与次数）",
         any(e.get("事件") == "任务失败" and "bedrock" in str(e.get("原因")) for e in 记),
         [e.get("原因") for e in 记 if e.get("事件") == "任务失败"])


def 用例_非阻塞等待():
    """★ wait_until：不发动作、独立超时、超时不退避重试。"""
    清日志()
    栈 = 建栈(等待超时毫秒=300000)
    炉 = {"p": [20, 78, -20], "输入": {"name": "iron_ore", "count": 3},
          "燃料": {"name": "coal", "count": 1}, "输出": None}
    栈.接("等炉子", [{"动作": "wait_until", "条件": "furnace_done", "熔炉": [20, 78, -20],
                      "数量": 1, "等待超时_ms": 300000}], 造帧())
    总命令 = []
    for i in range(20):                      # 10 秒（虚拟时钟）里一直没烧完
        _, 命令 = 走(栈, 秒=0.5, 熔炉=炉)
        总命令 += 命令
    断言("★等待期间**一个动作都不发**", 总命令 == [], 总命令)
    断言("等待期间任务保持在第 1 步（进度没丢）", 栈.任务["第几步"] == 0 and 栈.在跑())
    断言("等待步不占快档（省电）", 栈.要快() is False)
    # 烧完了
    炉2 = dict(炉, 输入={"name": "iron_ore", "count": 1}, 输出={"name": "iron_ingot", "count": 1})
    走(栈, 秒=0.5, 熔炉=炉2)
    断言("输出槽有货 → 条件满足、任务完成", 栈.任务["状态"] == "完", 栈.任务["状态"])
    记 = 读日志()
    断言("等待完成也进日志（用了多少秒）",
         any(e.get("事件") == "步骤完成" and e.get("动作") == "wait_until" for e in 记),
         [e.get("事件") for e in 记])

    # 超时：独立超时，且**不进退避重试**
    清日志()
    栈2 = 建栈()
    栈2.接("等不到", [{"动作": "wait_until", "条件": "furnace_done", "熔炉": [20, 78, -20],
                      "等待超时_ms": 5000}], 造帧())
    for _ in range(30):
        走(栈2, 秒=0.5, 熔炉=炉)
    记 = 读日志()
    断言("等待超时 → 任务失败（不是重试）", 栈2.任务["状态"] == "败", 栈2.任务["状态"])
    断言("★等待超时不进退避重试（日志里没有「重试」）",
         not any(e.get("事件") == "重试" for e in 记), [e.get("事件") for e in 记])
    断言("超时的原因说得清楚", any("超时" in str(e.get("原因")) for e in 记), [e.get("原因") for e in 记])


