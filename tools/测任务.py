def 用例_暂停与恢复():
    清日志()
    栈 = 建栈()
    炉 = {"p": [20, 78, -20], "输入": {"name": "iron_ore", "count": 3}, "输出": None}
    栈.接("等炉子", [{"动作": "wait_until", "条件": "furnace_done", "熔炉": [20, 78, -20],
                      "数量": 1, "等待超时_ms": 300000}], 造帧())
    走(栈, 秒=1.0, 熔炉=炉)
    栈.暂停("逃跑", 造帧())
    断言("暂停：状态变成暂停并记账", 栈.任务["状态"] == "暂停"
         and any(e.get("事件") == "暂停" for e in 读日志()))
    for _ in range(10):                      # 暂停期间照样轮询（不丢进度）
        走(栈, 秒=0.5, 熔炉=炉)
    断言("暂停期间不下发动作", 栈.任务["状态"] == "暂停")
    栈.恢复(造帧())
    断言("恢复：**从断点继续**（还是第 1 步，不重头）",
         栈.任务["状态"] == "跑" and 栈.任务["第几步"] == 0,
         (栈.任务["状态"], 栈.任务["第几步"]))
    炉2 = dict(炉, 输入=None, 输出={"name": "iron_ingot", "count": 1})
    走(栈, 秒=0.5, 熔炉=炉2)
    断言("恢复之后能接着把活干完", 栈.任务["状态"] == "完", 栈.任务["状态"])

    # 暂停太久 → 这一步算失败（走重试）
    清日志()
    栈2 = 建栈(暂停上限秒=10, 每步重试上限=2)
    栈2.接("走一格", [{"动作": "走到", "p": [3, 78, 0]}], 造帧())
    走(栈2, 秒=0.5, 我=(0, 78, 0))
    栈2.暂停("被打", 造帧())
    _虚拟[0] += 20
    栈2.恢复(造帧(我=(0, 78, 0)))
    记 = 读日志()
    断言("暂停超过上限 → 这一步判失败并重试",
         any(e.get("事件") == "重试" and "打断" in str(e.get("原因")) for e in 记),
         [e.get("原因") for e in 记 if e.get("事件") == "重试"])


def 用例_一票否决():
    """★ 主循环优先级：同一拍里，反射层有事干 → 下发的是反射层的动作，任务被暂停。"""
    清日志()
    _虚拟[0] = 1000.0
    说 = lambda *a, **k: None
    反射 = bridge.反射层({**CFG["m1"], **CFG["m2"], **CFG["m4"]}, 说)
    节拍 = bridge.节拍器(CFG["m2"], 说)
    栈 = 建栈()
    栈.接("慢慢走", [{"动作": "走到", "p": [30, 78, 0]}], 造帧())

    class 假温度:
        cpu = None
        gpu = None
        def 采样(self, 强制=False):
            pass

    class 假接口:
        def __init__(self):
            self.命令 = []
        def 发(self, o):
            self.命令.append(o)

    # 一个"要命"的现场：血很低 + 敌人贴脸 → 反射层必然接管（逃跑）
    帧 = 造帧(我=(0, 78, 0), 血=5.0, 敌人=(("zombie", 2.0),),
              玩家=(("mintstar", 20.0, True),))
    接口 = 假接口()
    栈.发 = 接口.发          # 主链里这一步是 `任务.发 = iface.发`（每个连接接一次）
    bridge._跑一轮反射(帧, 反射, type("N", (), {"静默移动": False})(), 假温度(),
                       接口, False, 节拍, None, 栈)
    有反射动作 = any(c.get("cmd") in ("move", "retreat", "attack", "jumpattack") for c in 接口.命令)
    断言("★同一拍下发的是反射层的动作（逃跑/反击）", 有反射动作, 接口.命令)
    断言("★任务被暂停（一票否决生效）", 栈.任务["状态"] == "暂停", 栈.任务["状态"])
    断言("暂停原因写的是反射层的状态（逃跑）",
         any(e.get("事件") == "暂停" and e.get("原因") in ("逃跑", "濒危", "反击")
             for e in 读日志()),
         [e.get("原因") for e in 读日志() if e.get("事件") == "暂停"])

    # 危险过去 → 恢复并继续干。
    # ⚠ 要**连续安静一小会儿**才算恢复（防抖，见 恢复冷静秒）：
