def 用例_动态超时与暂停冻结():
    """★ 补丁③：件数越多给得越宽；暂停期间秒表停住。"""
    栈 = 建栈(动作超时毫秒=60000, 每块超时毫秒=20000, 每件超时毫秒=15000)
    一 = 栈._这步超时({"动作": "挖", "数量": 1})
    三 = 栈._这步超时({"动作": "挖", "数量": 3})
    拾 = 栈._这步超时({"动作": "拾", "数量": 5})
    断言("动态超时：挖 3 块比挖 1 块给得宽（%d → %d 毫秒）" % (一, 三), 三 >= 一)
    断言("动态超时：拾 5 件按件数放大", 拾 >= 5 * 15000, 拾)
    断言("步骤自己写了超时就听它的（测试用的短超时）",
        栈._这步超时({"动作": "挖", "超时_ms": 3000}) == 3000)

    # 暂停冻结：走到一步中间暂停 30 秒，恢复后不该判超时
    清日志()
    栈2 = 建栈(动作超时毫秒=8000, 每步重试上限=0)
    栈2.接("走远点", [{"动作": "走到", "p": [50, 78, 0]}], 造帧())
    走(栈2, 秒=1.0, 我=(0, 78, 0))
    步开始 = 栈2.任务["步骤开始"]
    栈2.暂停("逃跑", 造帧())
    _虚拟[0] += 30                      # 打了 30 秒的架（远超 8 秒超时）
    栈2.恢复(造帧(我=(0, 78, 0)))
    断言("★ 暂停期间秒表冻结（步骤开始被往后推 30 秒）",
         abs(栈2.任务["步骤开始"] - 步开始 - 30) < 0.6,
         (步开始, 栈2.任务["步骤开始"]))
    走(栈2, 秒=0.5, 我=(0, 78, 0))
    断言("★ 打完架接着干，不因为「打架那 30 秒」被判超时",
         栈2.任务["状态"] == "跑", 栈2.任务["状态"])


def 用例_长任务切片():
    """★ 补丁②：多块任务拆成"一块一组步骤"，进度按块记账、已挖过的不重挖。"""
    步 = bridge.搭挖任务([[1, 77, 1], [2, 77, 2], [3, 77, 3]])
    挖步 = [s for s in 步 if s.get("动作") == "挖"]
    断言("三块 → 三个独立的「挖」步骤（切片）", len(挖步) == 3, len(挖步))
    断言("每一步都带着「第几块/共几块」（进度看得见）",
         [s.get("第几块") for s in 挖步] == [1, 2, 3]
         and all(s.get("共几块") == 3 for s in 挖步),
         [(s.get("第几块"), s.get("共几块")) for s in 挖步])

    # 打断之后：已经挖过的那一块**不会再挖一次**
    清日志()
    栈 = 建栈(每步重试上限=0)
    栈.接("挖两块", bridge.搭挖任务([[1, 77, 1], [2, 77, 2]]), 造帧(我=(0, 78, 0)))
    块 = {(1, 77, 1): "air", (2, 77, 2): "stone"}      # 第 1 块已经挖掉了
    全部命令 = []
    for _ in range(4):
        _, 命令 = 走(栈, 秒=3.0, 我=(2, 78, 2), 方块=块, 物品={"iron_pickaxe": 1})
        全部命令 += 命令
    打给第一块的 = [c for c in 全部命令
                  if c.get("cmd") == "dig" and (c.get("p") or [])[:3] == [1, 77, 1]]
    断言("★ 已经挖过的那一块不会被重挖（看事实直接跳过 → 不发 dig）",
         not 打给第一块的, 打给第一块的 or 全部命令)
    挖完成 = [e for e in 读日志() if e.get("事件") == "步骤完成" and e.get("动作") == "挖"]
    断言("第 1 块的「挖」照样在日志里结了账（没卡住）",
         any(e.get("第几块") == 1 and e.get("动作") == "挖" for e in 挖完成), 挖完成)


