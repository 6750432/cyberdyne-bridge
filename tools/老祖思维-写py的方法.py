def 打一条(条):
    print("  ── %d. %s" % (条["号"], 条["做法"]))
    print("     为什么：%s" % 条["为什么"])
    print("     老祖思维：%s" % 条["老祖思维"])
    print()


def 主(argv):
    if argv and argv[0] in ("--组", "-g"):
        for g in 组:
            print(g["组名"])
        return 0
    if argv:
        try:
            要 = int(argv[0])
        except ValueError:
            print("用法：老祖思维-写py的方法.py [条号] ｜ --组")
            return 2
        for g in 组:
            for 条 in g["条"]:
                if 条["号"] == 要:
                    打一条(条)
                    return 0
        print("没有第 %d 条" % 要)
        return 1
    n = sum(len(g["条"]) for g in 组)
    print()
    print("  老祖思维 · 写 py 的方法 —— 我们在这台机器上摸出来的 %d 条" % n)
    print("  （每条先给做法；故事只是证据，重点是最后那半句）")
    print()
    for g in 组:
        print("═" * 68)
        print("  " + g["组名"])
        print("═" * 68)
        for 条 in g["条"]:
            打一条(条)
    return 0


