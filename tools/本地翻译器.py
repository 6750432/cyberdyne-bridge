#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""本地翻译器.py —— **确定性翻译**（纯标准库 ✓ 零依赖 ✓）

为什么要有它（主人 2026-10-09 原话）
====================================
  「**LLM 的翻译太不可控了，我们做本地确定性翻译！**」✓
  今晚的教训全指向这一条 ✓：LLM 会**答空** ✗、会把「石镐」译成「木板」✗、
  会在 JSON 前后带闲话 ✗ —— 而主人的命令**本来就是有限的句式** ✓
  能本地认出来的，就**不该**去问一个"每次都不一样"的东西 ✗

两层（主人定的形状）
====================
  ① **精确意图字典**：高频指令的句式（「做个石镐」「我要一把石镐」「来把石镐」…）
  ② **正则提取器**：带数量的（「砍 3 个木头」「挖五个石头」「打2根木头」…）
  两层都 Miss ⇒ 返回 **None** ✓（调用方降级去走「LLM + Cas9 剪枝」那条慢路 ✓）

⚠ 两条纪律（今晚反复验过 ✓）
  · 词表**绝不另抄一份** ✗ —— 由调用方把现成的 `物品映射` 传进来 ✓
    （主人点过三次"别抄第二遍" ✓）
  · **不许瞎猜** ✗ —— 认不出就是 None ✓ 绝不返回一个"看起来差不多"的目标 ✓
"""

import re

# ── 数量词（中文 → 数字）──
_个数 = {"零": 0, "一": 1, "两": 2, "二": 2, "三": 3, "四": 4, "五": 5,
        "六": 6, "七": 7, "八": 8, "九": 9, "十": 10}
_全角 = "０１２３４５６７８９"


def 认数(串):
    """→ int 或 None ✓（支持 3 / 三 / 十五 / ２ 这种 ✓）"""
    s = str(串 or "").strip()
    if not s:
        return None
    s = "".join(str(_全角.index(c)) if c in _全角 else c for c in s)
    if s.isdigit():
        return int(s)
    if s == "十":
        return 10
    if s.startswith("十") and len(s) == 2 and s[1] in _个数:
        return 10 + _个数[s[1]]
    if s.endswith("十") and len(s) == 2 and s[0] in _个数:
        return _个数[s[0]] * 10
    if len(s) == 3 and s[1] == "十" and s[0] in _个数 and s[2] in _个数:
        return _个数[s[0]] * 10 + _个数[s[2]]
    if len(s) == 1 and s in _个数:
        return _个数[s]
    return None


def _洗(原话):
    """归一化：去空白 ✓ 全角空格 ✓ 常见语气尾巴（啊/吧/呀/喵/，/。…）✓"""
    s = str(原话 or "").strip()
    s = s.replace("　", " ").replace(" ", "")
    s = re.sub(r"[，。！!？?、~～]+$", "", s)
    s = re.sub(r"(啊|吧|呀|哈|喵|呗|嘛)+$", "", s)
    return s


def _认物品(词, 物品映射):
    """在**调用方给的那张表**里找 ✓（不另抄表 ✗）
    找法：① 原样 ✓ ② 大小写不敏感 ✓ ③ 表里名字尾部相同（「木头」→「橡木木头」这种）✓
    找不到 ⇒ None ✓（不许瞎猜 ✗）"""
    w = str(词 or "").strip()
    if not w:
        return None
    表 = dict(物品映射 or {})
    if w in 表:
        return str(表[w])
    小写 = {str(k).lower(): v for k, v in 表.items()}
    if w.lower() in 小写:
        return str(小写[w.lower()])
    # ⚠⚠ 2026-10-09 测试当场抓到的**瞎猜** ✗：
    #   我原来还留了一条"同尾匹配"（表里唯一的同尾词就用它 ✓）——
    #   结果「钻石镐」被认成了「石镐」✗（因为 石镐 是它的尾巴 ✓）
    #   ⇒ **删掉** ✗ —— 认不出就是认不出 ✓ 交给 LLM 那条慢路 ✓
    #   （主人那句"绝对不准瞎猜"就是冲这个来的 ✓）
    return None


# ── ① 精确意图字典：高频句式 ✓（整句锚定 ✓ 不留模糊空间 ✗）──
_句式 = [
    r"^(?:帮我|替我|给我|麻烦)?(?:我)?(?:想要|要|做个|做一个|做|造个|造|来个|来|拿个|拿|买个|买|弄个|弄)(?:一|1)?(?:个|把|块|根|棵|份|只)?(?P<物>.+)$",
    r"^(?:给我|帮我|替我)(?:一|1)?(?:个|把|块|根|棵)?(?P<物>.+)$",
]
_数量式 = [
    r"^(?:帮我|替我|给我|我)?(?:去)?(?:砍|挖|打|采|搞|弄|要|做|来|收集|收集到)(?P<数>[0-9０-９一二两三四五六七八九十]{1,3})(?:个|块|根|棵|把|份|捆)?(?P<物>.+)$",
]


def 译一句(原话, 物品映射=None):
    """→ {"意图":"要","目标":<物品名>,"数量":N,"来自":"本地翻译器","层":<哪一层>} 或 None ✓"""
    干净 = _洗(原话)
    if not 干净:
        return None
    # ② 先试**带数量**的（它对句式的约束更强 ✓ 先匹配更具体的不吃亏 ✓）
    for 式 in _数量式:
        m = re.match(式, 干净)
        if not m:
            continue
        数 = 认数(m.group("数"))
        物 = _认物品(m.group("物"), 物品映射)
        if 数 and 物:
            return {"意图": "要", "目标": 物, "数量": int(数),
                    "来自": "本地翻译器", "层": "正则提取器", "原话": str(原话)}
    # ① 再试精确句式字典 ✓
    for 式 in _句式:
        m = re.match(式, 干净)
        if not m:
            continue
        物 = _认物品(m.group("物"), 物品映射)
        if 物:
            return {"意图": "要", "目标": 物, "数量": 1,
                    "来自": "本地翻译器", "层": "精确意图字典", "原话": str(原话)}
    return None      # ★ 两层都 Miss ⇒ 交给"LLM + Cas9 剪枝"那条慢路 ✓（绝不瞎猜 ✗）


if __name__ == "__main__":
    import json
    import sys
    表 = {}
    for 路 in (sys.argv[1:] or []):
        try:
            with open(路, encoding="utf-8") as f:
                表.update(json.load(f).get("物品映射") or {})
        except Exception as e:
            print(f"（读不了 {路}：{e}）")
    for 话 in ("做个石镐", "我要一把石镐", "砍3个木头", "挖五个石头"):
        print(f"  {话} → {译一句(话, 表)}")
