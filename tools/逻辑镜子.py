# ═══════════════ 一、引擎（老祖那套就这点东西 ✓）═══════════════
变量序号 = [0]


def 新变量(前缀="x"):
    变量序号[0] += 1
    return ("?", "%s%d" % (前缀, 变量序号[0]))


def 是变量(x):
    return isinstance(x, tuple) and len(x) == 2 and x[0] == "?"


空表 = ("空表",)


def 表(*项):
    """★ 照老祖的规矩：表是 **cons 对** ✓ 不是 Python 列表 ✗
    （我第一版拿 Python 列表当表用 ⇒ `全都能做` 那两条规则**永远匹配不上** ✗
      因为 Python 列表是定长的 ✓ 而逻辑里的表是 [头 | 尾] ✓ 长度不定 ✓）"""
    出 = 空表
    for x in reversed(项):
        出 = ("点", x, 出)
    return 出


def 重命名(项, 对照):
    """★★★ 老祖的**第一条军规**：每次用一条子句，里面的变量都要**换成全新的** ✓
    （fresh renaming ✓）

    为什么非要有它（今天照镜子照出来的 ✓）：
      我把同几个变量对象在**所有子句里共用** ✗ ⇒ 解到第二层时 `物` 已经绑成 oak_planks ✓
      ⇒ 再拿同一个 `物` 去问 `能做(oak_log)` **必然撞车** ✗
      ⇒ 表现：三个子目标**单独问都有解** ✓ 合起来问**一个解都没有** ✗
        （`能做(oak_planks)` = 0 ✓ 而 配方/全都能做/设备有了 各自都 = 1 ✗）
      这就是逻辑编程里最经典的一个坑 ✓ 老祖们一开局就把它定成规矩 ✓"""
    if 是变量(项):
        if 项 not in 对照:
            对照[项] = 新变量(项[1].split("#")[0])
        return 对照[项]
    if isinstance(项, tuple):
        return tuple(重命名(x, 对照) for x in 项)
    return 项


def 走(绑定, x):
    while 是变量(x):
        if x not in 绑定:
            return x
        x = 绑定[x]
    return x


def 统一(a, b, 绑定):
    """★ 老祖最核心的那一招：**统一** ✓ 成功给新绑定表 ✓ 失败给 None ✗
    （失败是**常态** ✗ 所以不抛异常 ✓ 这一点跟我们求解器用异常表示失败正好相反 ✓）"""
    a, b = 走(绑定, a), 走(绑定, b)
    if a == b:
        return 绑定
    if 是变量(a):
        新 = dict(绑定)
        新[a] = b
        return 新
    if 是变量(b):
        新 = dict(绑定)
        新[b] = a
        return 新
    if isinstance(a, tuple) and isinstance(b, tuple) and len(a) == len(b):
        绑 = 绑定
        for x, y in zip(a, b):
            绑 = 统一(x, y, 绑)
            if 绑 is None:
                return None
        return 绑
    return None


class 知识库:
    def __init__(self, 名字="库", 步数上限=200000):
        self.名字 = 名字
        self.条 = []
        self.步数 = 0
        self.步数上限 = 步数上限
        self.爆了 = False

    def 加事实(self, 头):
        """★ 一条事实就是**一个元组** ✓ 参数直接摆在里面 ✗
        （我第一版写成 `加事实(*项)` ⇒ 整条子句被塞进**一元组** ✗
          ⇒ 头永远匹配不上任何目标 ✓ 一条解都问不出来 ✗
          **这是「第一面：拿已知答案对」抓出来的** ✓ —— 镜子自己也得先照准 ✓）"""
        self.条.append((头, ()))

    def 加规则(self, 头, *体):
        self.条.append((头, 体))

    def 解(self, 目标, 绑定=None, 深=0, 最多深=40):
        """回溯搜索 ✓ 生成器 ⇒ **能枚举全部解** ✓（这正是我们求解器缺的那半 ✓）"""
        if 深 > 最多深 or self.爆了:
            return
        self.步数 += 1
        if self.步数 > self.步数上限:
            self.爆了 = True
            print("      ✗✗ 裸引擎**爆了**（步数超过 %d ✓）—— 见下面「第三面」✓" % self.步数上限)
            return
        绑定 = 绑定 or {}
        # ★ 内建谓词：`不同` —— 就是 Prolog 的 `\=` ✓（手搓一个 ✓ 别拿事实凑 ✗）
        if 目标 and 目标[0] == "不同":
            a = 走(绑定, 目标[1]) if len(目标) > 1 else None
            b = 走(绑定, 目标[2]) if len(目标) > 2 else None
            if not 是变量(a) and not 是变量(b) and a != b:
                yield 绑定
            return
        for 头, 体 in self.条:
            对照 = {}                                   # ★ 每用一次子句，变量全部换新 ✓
            头 = 重命名(头, 对照)
            体 = [重命名(子, 对照) for 子 in 体]
            新 = 统一(目标, 头, dict(绑定))
            if 新 is None:
                continue
            if not 体:
                yield 新
                continue
            栈 = [新]
            for 子 in 体:
                下 = []
                for 绑 in 栈:
                    for 绑2 in self.解(子, 绑, 深 + 1, 最多深):
                        下.append(绑2)
                        if len(下) > 400:
                            break
                栈 = 下
                if not 栈:
                    break
            for 绑 in 栈:
                yield 绑

    def 问(self, 目标, 取几个=50, 最多深=40):
        出 = []
        for 绑 in self.解(目标, None, 0, 最多深):
            出.append(绑)
            if len(出) >= 取几个:
                break
        return 出

    def 有吗(self, 目标, 最多深=40):
        for _ in self.解(目标, None, 0, 最多深):
            return True
        return False


