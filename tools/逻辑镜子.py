def 造库(带守卫):
    """带守卫 = 逻辑编程里治环的正统办法：**沿路记着走过谁** ✓
    （对应我们求解器里那个 `路` ✓ —— 照镜子要照出的就是"同一个东西两边都有" ✓）"""
    库 = 知识库("带守卫" if 带守卫 else "裸库")
    库.加事实(("挖到", "oak_log", "oak_log"))
    库.加事实(("挖到", "stone", "cobblestone"))
    库.加事实(("挖到", "raw_iron", "raw_iron"))
    for 名, 材, 设 in 配方:
        库.加事实(("配方", 名, 材, 设))

    物, 材, 设, 头, 尾 = 新变量("物"), 新变量("材"), 新变量("设"), 新变量("头"), 新变量("尾")
    路0, 路1 = 新变量("路"), 新变量("路")
    if not 带守卫:
        # ★ 一条子句 = 一个元组 ✓ **参数直接摆在里面** ✗ 别再套一层括号 ✓
        #   （我第一版写成 ("能做", (物,)) ⇒ 那是「1 个参数、值是 1 元组」✗
        #     跟事实 ("配方", 名, 材, 设) 的 4 个参数**根本对不上** ✓ ⇒ 一条解都问不出来 ✗
        #     **这次是镜子把我照出来的** ✓ 老祖那边管这叫「元数与结构不匹配」✓）
        库.加规则(("能做", 物), ("配方", 物, 材, 设), ("全都能做", 材), ("设备有了", 设))
        库.加规则(("全都能做", 空表))
        库.加规则(("全都能做", ("点", 头, 尾)), ("能做", 头), ("全都能做", 尾))
        库.加规则(("设备有了", None))
        库.加规则(("设备有了", 设), ("能做", 设))
        # ★ 方向别写反 ✗：`挖到(方块, 掉什么)` ✓ 所以是「挖**某个方块**能得到 物」✓
        #   （我第一版写成 `挖到(物, ?掉)` ⇒ 只能得出"能做石头" ✗ 做不出圆石 ✗）
        库.加规则(("能做", 物), ("挖到", 新变量("方块"), 物))
    else:
        # ★ 每问一样东西都带上「已经走过谁」✓ 再进来的必须**不在路上** ✗
        库.加规则(("能做", 物, 路0), ("不在路上", 物, 路0), ("配方", 物, 材, 设),
                  ("全都能做", 材, ("点", 物, 路0)), ("设备有了", 设, ("点", 物, 路0)))
        库.加规则(("能做", 物, 路0), ("不在路上", 物, 路0), ("挖到", 物, 新变量("掉")))
        库.加规则(("全都能做", 空表, 路1))
        库.加规则(("全都能做", ("点", 头, 尾), 路1), ("能做", 头, 路1), ("全都能做", 尾, 路1))
        库.加规则(("设备有了", None, 路1))
        库.加规则(("设备有了", 设, 路1), ("能做", 设, 路1))
        库.加规则(("不在路上", 物, 空表))
        库.加规则(("不在路上", 物, ("点", 头, 尾)), ("不同", 物, 头), ("不在路上", 物, 尾))
    return 库        # 「不同」在内建里 ✓ 不用事实凑 ✓（我第一版凑了，绕 ✗）


